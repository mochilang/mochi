// Package asyncbridge generates Swift @_cdecl wrappers for async/throws functions.
// The bridge uses DispatchGroup.wait() to block the calling C (Go) thread until
// the Swift Task completes, avoiding deadlocks by running on a separate thread pool.
package asyncbridge

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mochi/package3/swift/emit"
	"mochi/package3/swift/typemap"
)

// AsyncWrapSpec describes one async/throws function to wrap.
type AsyncWrapSpec struct {
	// MochiName is the @_cdecl exported symbol name.
	MochiName string
	// SwiftName is the original Swift function name.
	SwiftName string
	// Module is the Swift module name.
	Module string
	// ReturnKind is the Mochi kind of the return type.
	ReturnKind typemap.Kind
	// IsThrowing indicates the function can throw.
	IsThrowing bool
	// Params is the list of parameter mappings.
	Params []emit.ParamMapping
}

// WrapAsync wraps an async function spec into a synchronous @_cdecl spec.
// The wrapper name is unchanged (the bridge handles the async→sync conversion).
func WrapAsync(spec AsyncWrapSpec) AsyncWrapSpec {
	return AsyncWrapSpec{
		MochiName:  spec.MochiName,
		SwiftName:  spec.SwiftName,
		Module:     spec.Module,
		ReturnKind: spec.ReturnKind,
		IsThrowing: spec.IsThrowing,
		Params:     spec.Params,
	}
}

// EmitDispatchBridgeFile writes a Swift file containing DispatchGroup-based
// wrappers for all provided async/throws functions.
func EmitDispatchBridgeFile(specs []AsyncWrapSpec, outPath string) error {
	cs := buildDispatchBridgeFile(specs)
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("asyncbridge: mkdir: %w", err)
	}
	return os.WriteFile(outPath, []byte(cs), 0o644)
}

func buildDispatchBridgeFile(specs []AsyncWrapSpec) string {
	var b strings.Builder
	b.WriteString("// Generated by mochi/package3/swift/asyncbridge; do not edit.\n")
	b.WriteString("import Foundation\n\n")
	for _, spec := range specs {
		b.WriteString(emitDispatchWrapper(spec))
		b.WriteString("\n")
	}
	return b.String()
}

func emitDispatchWrapper(spec AsyncWrapSpec) string {
	var b strings.Builder
	isVoid := spec.ReturnKind == typemap.KindUnit
	isString := spec.ReturnKind == typemap.KindString

	// Build @_cdecl parameter list.
	var cdeclParams []string
	var callArgs []string
	for _, p := range spec.Params {
		ctype := kindToCType(p.Mapping.Kind)
		cdeclParams = append(cdeclParams, fmt.Sprintf("_ %s: %s", p.Name, ctype))
		callArgs = append(callArgs, p.Name)
	}

	if !isVoid {
		if isString {
			cdeclParams = append(cdeclParams, "_ resultBuf: UnsafeMutablePointer<CChar>?")
			cdeclParams = append(cdeclParams, "_ resultLen: UnsafeMutablePointer<CInt>?")
		} else {
			cdeclParams = append(cdeclParams, fmt.Sprintf("_ resultOut: UnsafeMutablePointer<%s>?", kindToSwiftCType(spec.ReturnKind)))
		}
	}
	if spec.IsThrowing {
		cdeclParams = append(cdeclParams, "_ errorBuf: UnsafeMutablePointer<CChar>?")
		cdeclParams = append(cdeclParams, "_ errorLen: UnsafeMutablePointer<CInt>?")
	}

	fmt.Fprintf(&b, "@_cdecl(%q)\n", spec.MochiName)
	fmt.Fprintf(&b, "public func %s(%s) {\n", spec.MochiName, strings.Join(cdeclParams, ", "))
	b.WriteString("    let group = DispatchGroup()\n")
	b.WriteString("    group.enter()\n")
	b.WriteString("    Task {\n")
	if spec.IsThrowing {
		b.WriteString("        do {\n")
	}
	callStr := fmt.Sprintf("%s.%s(%s)", spec.Module, spec.SwiftName, strings.Join(callArgs, ", "))
	if isVoid {
		if spec.IsThrowing {
			fmt.Fprintf(&b, "            try await %s\n", callStr)
		} else {
			fmt.Fprintf(&b, "        await %s\n", callStr)
		}
	} else if isString {
		indent := "        "
		if spec.IsThrowing {
			indent = "            "
		}
		fmt.Fprintf(&b, "%slet __result = %s await %s\n", indent, ifThrowing(spec.IsThrowing, "try"), callStr)
		fmt.Fprintf(&b, "%s__result.utf8CString.withUnsafeBufferPointer { ptr in\n", indent)
		fmt.Fprintf(&b, "%s    resultBuf?.initialize(from: ptr.baseAddress!, count: ptr.count)\n", indent)
		fmt.Fprintf(&b, "%s    resultLen?.pointee = CInt(ptr.count)\n", indent)
		fmt.Fprintf(&b, "%s}\n", indent)
	} else {
		indent := "        "
		if spec.IsThrowing {
			indent = "            "
		}
		fmt.Fprintf(&b, "%sresultOut?.pointee = %s await %s\n", indent, ifThrowing(spec.IsThrowing, "try"), callStr)
	}
	if spec.IsThrowing {
		b.WriteString("        } catch {\n")
		b.WriteString("            let msg = error.localizedDescription.utf8CString\n")
		b.WriteString("            msg.withUnsafeBufferPointer { ptr in\n")
		b.WriteString("                errorBuf?.initialize(from: ptr.baseAddress!, count: ptr.count)\n")
		b.WriteString("                errorLen?.pointee = CInt(ptr.count)\n")
		b.WriteString("            }\n")
		b.WriteString("        }\n")
	}
	b.WriteString("        group.leave()\n")
	b.WriteString("    }\n")
	b.WriteString("    group.wait()\n")
	b.WriteString("}\n")
	return b.String()
}

func ifThrowing(throwing bool, s string) string {
	if throwing {
		return s
	}
	return ""
}

func kindToCType(k typemap.Kind) string {
	switch k {
	case typemap.KindInt:
		return "CLongLong"
	case typemap.KindFloat:
		return "CDouble"
	case typemap.KindBool:
		return "CBool"
	case typemap.KindString:
		return "UnsafePointer<CChar>"
	default:
		return "CLongLong"
	}
}

func kindToSwiftCType(k typemap.Kind) string {
	switch k {
	case typemap.KindInt:
		return "CLongLong"
	case typemap.KindFloat:
		return "CDouble"
	case typemap.KindBool:
		return "CBool"
	default:
		return "CLongLong"
	}
}
