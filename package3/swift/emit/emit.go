// Package emit is the MEP-69 phase 5 Mochi extern emitter. It consumes a list
// of MappedFn values (Swift functions with resolved type mappings) and produces
// Mochi source files with matching extern fn declarations.
package emit

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	swifterrors "mochi/package3/swift/errors"
	"mochi/package3/swift/typemap"
)

// ParamMapping is one parameter with its resolved type mapping.
type ParamMapping struct {
	Name    string
	Mapping *typemap.Mapping
}

// MappedFn is a Swift function with all parameters and return type resolved to
// Mochi type mappings.
type MappedFn struct {
	SwiftName  string
	MochiName  string
	Params     []ParamMapping
	Return     *typemap.Mapping
	IsAsync    bool
	IsThrowing bool
}

// SkipReport is re-exported from the errors package for use by callers who
// only import this package.
type SkipReport = swifterrors.SkipReport

// EmitExterns writes a Mochi source file containing extern fn declarations for
// all functions in fns to outPath.
func EmitExterns(moduleName string, fns []MappedFn, outPath string) error {
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("emit: mkdir: %w", err)
	}

	// Sort for deterministic output
	sorted := make([]MappedFn, len(fns))
	copy(sorted, fns)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].MochiName < sorted[j].MochiName
	})

	var sb strings.Builder
	sb.WriteString("// Auto-generated by mochi swift bridge. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Module: %s\n\n", moduleName))

	for _, fn := range sorted {
		line := renderExtern(fn)
		sb.WriteString(line)
		sb.WriteByte('\n')
	}

	return os.WriteFile(outPath, []byte(sb.String()), 0o644)
}

// renderExtern renders a single extern fn declaration for fn.
func renderExtern(fn MappedFn) string {
	var params []string
	for _, p := range fn.Params {
		if p.Mapping.Kind == typemap.KindSkip {
			continue
		}
		params = append(params, fmt.Sprintf("%s: %s", p.Name, p.Mapping.MochiType))
	}

	retType := "unit"
	if fn.Return != nil && fn.Return.Kind != typemap.KindSkip {
		retType = fn.Return.MochiType
	}

	async := ""
	if fn.IsAsync {
		async = "async "
	}

	return fmt.Sprintf("extern %sfn %s(%s) -> %s",
		async, fn.MochiName, strings.Join(params, ", "), retType)
}

// EmitSkipped writes a SKIPPED.txt file listing all skipped items to outPath.
func EmitSkipped(skipped []SkipReport, outPath string) error {
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("emit: mkdir for skipped: %w", err)
	}

	// Sort for deterministic output
	sorted := make([]SkipReport, len(skipped))
	copy(sorted, skipped)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].ItemPath < sorted[j].ItemPath
	})

	var sb strings.Builder
	sb.WriteString("# Swift bridge skipped items\n\n")
	for _, s := range sorted {
		sb.WriteString(fmt.Sprintf("SKIPPED: %s\n", s.ItemPath))
		sb.WriteString(fmt.Sprintf("  Reason: %s\n", s.Reason))
		if s.Detail != "" {
			sb.WriteString(fmt.Sprintf("  Detail: %s\n", s.Detail))
		}
		sb.WriteByte('\n')
	}

	return os.WriteFile(outPath, []byte(sb.String()), 0o644)
}
