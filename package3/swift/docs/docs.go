// Package docs emits DocC-compatible documentation from Mochi doc comments.
// It produces a .docc catalog suitable for hosting on Swift Package Index.
package docs

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DocComment holds one extracted doc comment from Mochi source.
type DocComment struct {
	// Name is the function or type name.
	Name string
	// Kind is "function", "type", or "property".
	Kind string
	// Summary is the first paragraph of the doc comment.
	Summary string
	// Discussion is the remaining paragraphs.
	Discussion string
	// Params is the parameter documentation.
	Params []ParamDoc
	// Returns is the return value documentation.
	Returns string
}

// ParamDoc documents one function parameter.
type ParamDoc struct {
	Name        string
	Description string
}

// CatalogSpec describes the DocC catalog to generate.
type CatalogSpec struct {
	// ModuleName is the Swift module name.
	ModuleName string
	// Version is the package version.
	Version string
	// Comments is the list of doc comments to include.
	Comments []DocComment
}

// EmitDocC writes a DocC-compatible .docc catalog to outDir.
// The catalog contains:
//   - <ModuleName>.docc/
//       <ModuleName>.md  — module-level documentation
//       Symbols/
//         <Name>.md      — per-symbol documentation
func EmitDocC(spec CatalogSpec, outDir string) error {
	doccDir := filepath.Join(outDir, spec.ModuleName+".docc")
	symbolsDir := filepath.Join(doccDir, "Symbols")
	if err := os.MkdirAll(symbolsDir, 0o755); err != nil {
		return fmt.Errorf("docs: mkdir: %w", err)
	}

	// Write module-level documentation.
	moduleDoc := emitModuleDoc(spec)
	if err := os.WriteFile(filepath.Join(doccDir, spec.ModuleName+".md"), []byte(moduleDoc), 0o644); err != nil {
		return fmt.Errorf("docs: write module doc: %w", err)
	}

	// Write per-symbol documentation.
	for _, c := range spec.Comments {
		symbolDoc := emitSymbolDoc(spec.ModuleName, c)
		safeName := strings.ReplaceAll(c.Name, "/", "_")
		path := filepath.Join(symbolsDir, safeName+".md")
		if err := os.WriteFile(path, []byte(symbolDoc), 0o644); err != nil {
			return fmt.Errorf("docs: write symbol %s: %w", c.Name, err)
		}
	}
	return nil
}

func emitModuleDoc(spec CatalogSpec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# ``%s``\n\n", spec.ModuleName)
	fmt.Fprintf(&b, "Version %s — generated by mochi/package3/swift/docs.\n\n", spec.Version)
	b.WriteString("## Overview\n\n")
	fmt.Fprintf(&b, "This documentation covers the public API of `%s`.\n\n", spec.ModuleName)
	if len(spec.Comments) > 0 {
		b.WriteString("## Topics\n\n")
		b.WriteString("### Functions\n\n")
		for _, c := range spec.Comments {
			if c.Kind == "function" {
				fmt.Fprintf(&b, "- ``%s/%s``\n", spec.ModuleName, c.Name)
			}
		}
	}
	return b.String()
}

func emitSymbolDoc(moduleName string, c DocComment) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# ``%s/%s``\n\n", moduleName, c.Name)
	if c.Summary != "" {
		b.WriteString(c.Summary)
		b.WriteString("\n\n")
	}
	if len(c.Params) > 0 {
		b.WriteString("## Parameters\n\n")
		for _, p := range c.Params {
			fmt.Fprintf(&b, "- `%s`: %s\n", p.Name, p.Description)
		}
		b.WriteString("\n")
	}
	if c.Returns != "" {
		b.WriteString("## Return Value\n\n")
		b.WriteString(c.Returns)
		b.WriteString("\n\n")
	}
	if c.Discussion != "" {
		b.WriteString("## Discussion\n\n")
		b.WriteString(c.Discussion)
		b.WriteString("\n")
	}
	return b.String()
}
