// Package library is the MEP-69 phase 9 publish-direction emit layer. It
// owns the lowering of a Mochi package's Swift-targetted public surface into a
// publishable Swift package with @_cdecl exports. The emitted package includes:
//
//   - Package.swift with swift-tools-version: 5.9
//   - Sources/MochiExports/MochiExports.swift with @_cdecl exports
//   - README.md
package library

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// SwiftFunction describes one exported Swift function.
type SwiftFunction struct {
	// Name is the Swift/Mochi function name.
	Name string
	// ParamTypes is the list of Swift parameter types.
	ParamTypes []string
	// ReturnType is the Swift return type.
	ReturnType string
}

// SwiftPackage is the Mochi package surface to emit as a Swift package.
type SwiftPackage struct {
	// Name is the Swift package name.
	Name string
	// Version is the package version string.
	Version string
	// Functions is the list of exported functions.
	Functions []SwiftFunction
}

// EmitPackage writes a Swift package directory to outDir. It creates:
//   - outDir/Package.swift
//   - outDir/Sources/MochiExports/MochiExports.swift
//   - outDir/README.md
func EmitPackage(pkg *SwiftPackage, outDir string) error {
	if err := os.MkdirAll(filepath.Join(outDir, "Sources", "MochiExports"), 0o755); err != nil {
		return fmt.Errorf("library: mkdir: %w", err)
	}

	if err := os.WriteFile(
		filepath.Join(outDir, "Package.swift"),
		[]byte(renderPackageSwift(pkg)),
		0o644,
	); err != nil {
		return fmt.Errorf("library: write Package.swift: %w", err)
	}

	if err := os.WriteFile(
		filepath.Join(outDir, "Sources", "MochiExports", "MochiExports.swift"),
		[]byte(renderExports(pkg)),
		0o644,
	); err != nil {
		return fmt.Errorf("library: write MochiExports.swift: %w", err)
	}

	if err := os.WriteFile(
		filepath.Join(outDir, "README.md"),
		[]byte(renderReadme(pkg)),
		0o644,
	); err != nil {
		return fmt.Errorf("library: write README.md: %w", err)
	}

	return nil
}

// renderPackageSwift renders a Package.swift for the given package.
func renderPackageSwift(pkg *SwiftPackage) string {
	var sb strings.Builder
	sb.WriteString("// swift-tools-version: 5.9\n")
	sb.WriteString("// Auto-generated by mochi swift bridge. DO NOT EDIT.\n")
	sb.WriteString("import PackageDescription\n\n")
	sb.WriteString("let package = Package(\n")
	sb.WriteString(fmt.Sprintf("    name: %q,\n", pkg.Name))
	sb.WriteString("    platforms: [\n")
	sb.WriteString("        .macOS(.v13),\n")
	sb.WriteString("    ],\n")
	sb.WriteString("    products: [\n")
	sb.WriteString(fmt.Sprintf("        .library(name: %q, targets: [%q]),\n", pkg.Name, "MochiExports"))
	sb.WriteString("    ],\n")
	sb.WriteString("    targets: [\n")
	sb.WriteString("        .target(\n")
	sb.WriteString(fmt.Sprintf("            name: %q,\n", "MochiExports"))
	sb.WriteString("            path: \"Sources/MochiExports\"\n")
	sb.WriteString("        ),\n")
	sb.WriteString("    ]\n")
	sb.WriteString(")\n")
	return sb.String()
}

// renderExports renders the MochiExports.swift file with @_cdecl exports.
func renderExports(pkg *SwiftPackage) string {
	var sb strings.Builder
	sb.WriteString("// Auto-generated by mochi swift bridge. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Package: %s %s\n\n", pkg.Name, pkg.Version))
	sb.WriteString("import Foundation\n\n")

	for _, fn := range pkg.Functions {
		cSymbol := "__mochi_" + fn.Name
		sb.WriteString(fmt.Sprintf("@_cdecl(%q)\n", cSymbol))
		sb.WriteString(fmt.Sprintf("public func %s(", cSymbol))

		// Build param list with c-compatible types
		var params []string
		for i, pt := range fn.ParamTypes {
			cType := toCType(pt)
			params = append(params, fmt.Sprintf("_ p%d: %s", i, cType))
		}
		sb.WriteString(strings.Join(params, ", "))
		retCType := toCType(fn.ReturnType)
		sb.WriteString(fmt.Sprintf(") -> %s {\n", retCType))

		// Build forwarding call
		var args []string
		for i, pt := range fn.ParamTypes {
			if pt == "String" {
				args = append(args, fmt.Sprintf("String(cString: p%d!)", i))
			} else {
				args = append(args, fmt.Sprintf("p%d", i))
			}
		}
		callExpr := fmt.Sprintf("%s(%s)", fn.Name, strings.Join(args, ", "))
		if fn.ReturnType == "String" {
			sb.WriteString(fmt.Sprintf("    let r = %s\n", callExpr))
			sb.WriteString("    return strdup(r)\n")
		} else if fn.ReturnType == "Void" || fn.ReturnType == "" {
			sb.WriteString(fmt.Sprintf("    %s\n", callExpr))
		} else {
			sb.WriteString(fmt.Sprintf("    return %s\n", callExpr))
		}
		sb.WriteString("}\n\n")
	}

	return sb.String()
}

// toCType maps a Swift type to its C-compatible type string.
func toCType(swiftType string) string {
	switch swiftType {
	case "String":
		return "UnsafeMutablePointer<CChar>?"
	case "Bool":
		return "CBool"
	case "Int", "Int64":
		return "Int64"
	case "Int32":
		return "Int32"
	case "Int16":
		return "Int16"
	case "Int8":
		return "Int8"
	case "UInt", "UInt64":
		return "UInt64"
	case "UInt32":
		return "UInt32"
	case "Double", "Float64":
		return "Double"
	case "Float", "Float32":
		return "Float"
	case "Void", "":
		return "Void"
	default:
		return swiftType
	}
}

// renderReadme renders a README.md for the package.
func renderReadme(pkg *SwiftPackage) string {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("# %s\n\n", pkg.Name))
	sb.WriteString("Auto-generated Swift package bridge by [Mochi](https://mochilang.com).\n\n")
	sb.WriteString(fmt.Sprintf("Version: %s\n\n", pkg.Version))
	sb.WriteString("## Exported Functions\n\n")
	for _, fn := range pkg.Functions {
		sb.WriteString(fmt.Sprintf("- `%s`\n", fn.Name))
	}
	return sb.String()
}
