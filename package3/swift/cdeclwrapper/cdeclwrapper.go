// Package cdeclwrapper emits @_cdecl Swift bridge files. Each public function
// in a WrapperSpec is lowered to a @_cdecl wrapper that uses only C-compatible
// types, enabling Mochi's CGo bridge to call the functions as C symbols.
//
// Type mapping rules:
//   - String params -> UnsafePointer<CChar>
//   - String return  -> UnsafeMutablePointer<CChar> (caller owns; uses strdup)
//   - Numeric types  -> direct cast
//   - Bool           -> CBool
//   - Async/Closure  -> skip, emit comment
package cdeclwrapper

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mochi/package3/swift/emit"
	"mochi/package3/swift/typemap"
)

// WrapperSpec describes the @_cdecl wrapper file to emit.
type WrapperSpec struct {
	Module    string
	Functions []emit.MappedFn
}

// EmitBridgeFile writes a Swift source file containing @_cdecl wrappers for
// all functions in spec to outPath.
func EmitBridgeFile(spec WrapperSpec, outPath string) error {
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("cdeclwrapper: mkdir: %w", err)
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by mochi swift bridge. DO NOT EDIT.\n")
	sb.WriteString(fmt.Sprintf("// Module: %s\n\n", spec.Module))
	sb.WriteString("import Foundation\n\n")

	for _, fn := range spec.Functions {
		rendered, skip := renderWrapper(fn)
		if skip != "" {
			sb.WriteString(fmt.Sprintf("// SKIPPED %s: %s\n", fn.SwiftName, skip))
			continue
		}
		sb.WriteString(rendered)
		sb.WriteByte('\n')
	}

	return os.WriteFile(outPath, []byte(sb.String()), 0o644)
}

// renderWrapper renders a single @_cdecl wrapper for fn.
// Returns (rendered, "") on success or ("", skipReason) if the function must
// be skipped.
func renderWrapper(fn emit.MappedFn) (string, string) {
	// Async functions cannot be expressed as @_cdecl
	if fn.IsAsync {
		return "", "async function cannot be a @_cdecl wrapper (SkipClosure)"
	}

	// Check return type compatibility
	retCType, ok := toCType(fn.Return)
	if !ok {
		return "", fmt.Sprintf("return type %q cannot be lowered to C", fn.Return.MochiType)
	}

	// Check all param types
	var cParams []string
	var callArgs []string
	for _, p := range fn.Params {
		cType, ok := toCType(p.Mapping)
		if !ok {
			return "", fmt.Sprintf("param %q type %q cannot be lowered to C", p.Name, p.Mapping.MochiType)
		}
		cParams = append(cParams, fmt.Sprintf("_ %s: %s", p.Name, cType))
		callArgs = append(callArgs, toCallArg(p.Name, p.Mapping))
	}

	// Build the wrapper
	paramStr := strings.Join(cParams, ", ")
	callArgStr := strings.Join(callArgs, ", ")

	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("@_cdecl(%q)\n", cSymbolName(fn.SwiftName)))
	sb.WriteString(fmt.Sprintf("public func __mochi_%s(%s) -> %s {\n",
		fn.SwiftName, paramStr, retCType))

	// Build the call and return
	callExpr := fmt.Sprintf("%s(%s)", fn.SwiftName, buildCallExpr(fn, callArgStr))
	if fn.IsThrowing {
		sb.WriteString("  guard let result = try? " + callExpr + " else { return " + zeroValue(fn.Return) + " }\n")
		sb.WriteString("  return " + wrapReturn("result", fn.Return) + "\n")
	} else {
		sb.WriteString("  let result = " + callExpr + "\n")
		sb.WriteString("  return " + wrapReturn("result", fn.Return) + "\n")
	}

	sb.WriteString("}\n")
	return sb.String(), ""
}

// toCType returns the C-compatible Swift type string for a Mapping.
// Returns ("", false) if the type cannot be lowered.
func toCType(m *typemap.Mapping) (string, bool) {
	if m == nil {
		return "Void", true
	}
	switch m.Kind {
	case typemap.KindUnit:
		return "Void", true
	case typemap.KindBool:
		return "CBool", true
	case typemap.KindInt:
		return swiftCIntType(m.MochiType), true
	case typemap.KindFloat:
		switch m.MochiType {
		case "f32":
			return "Float", true
		case "f64":
			return "Double", true
		}
	case typemap.KindString:
		return "UnsafeMutablePointer<CChar>?", true
	case typemap.KindSkip:
		return "", false
	}
	return "", false
}

// swiftCIntType maps Mochi integer type names to Swift C-compatible types.
func swiftCIntType(mochiType string) string {
	switch mochiType {
	case "i8":
		return "Int8"
	case "i16":
		return "Int16"
	case "i32":
		return "Int32"
	case "i64":
		return "Int64"
	case "u8":
		return "UInt8"
	case "u16":
		return "UInt16"
	case "u32":
		return "UInt32"
	case "u64":
		return "UInt64"
	default:
		return "Int64"
	}
}

// toCallArg converts a C-side parameter to the Swift-side argument for the
// underlying function call.
func toCallArg(name string, m *typemap.Mapping) string {
	if m.Kind == typemap.KindString {
		return fmt.Sprintf("String(cString: %s!)", name)
	}
	return name
}

// buildCallExpr builds the call expression with labelled args.
func buildCallExpr(fn emit.MappedFn, callArgStr string) string {
	// For Swift functions with named labels we use positional form here since
	// the @_cdecl wrapper calls the Swift function directly.
	_ = callArgStr
	var args []string
	for _, p := range fn.Params {
		args = append(args, toCallArg(p.Name, p.Mapping))
	}
	return strings.Join(args, ", ")
}

// wrapReturn wraps the result expression for return.
func wrapReturn(expr string, m *typemap.Mapping) string {
	if m == nil || m.Kind == typemap.KindUnit {
		return ""
	}
	if m.Kind == typemap.KindString {
		// Return strdup equivalent: convert to UnsafeMutablePointer<CChar>
		return fmt.Sprintf("strdup(%s)", expr)
	}
	return expr
}

// zeroValue returns a sensible zero/nil for error-path returns.
func zeroValue(m *typemap.Mapping) string {
	if m == nil || m.Kind == typemap.KindUnit {
		return "()"
	}
	switch m.Kind {
	case typemap.KindBool:
		return "false"
	case typemap.KindInt:
		return "0"
	case typemap.KindFloat:
		return "0.0"
	case typemap.KindString:
		return "nil"
	}
	return "nil"
}

// cSymbolName returns the C symbol name for a Swift function.
func cSymbolName(swiftName string) string {
	return "__mochi_" + swiftName
}
