// Package concurrency bridges Swift AsyncSequence to Mochi stream<T>.
// The generated Swift wrapper uses `for await x in seq { emit(stream, x) }`
// inside a Task, and a DispatchGroup to synchronise completion.
package concurrency

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"mochi/package3/swift/typemap"
)

// SequenceSpec describes one AsyncSequence to bridge.
type SequenceSpec struct {
	// MochiName is the @_cdecl exported symbol name.
	MochiName string
	// SwiftSequenceName is the Swift AsyncSequence type name.
	SwiftSequenceName string
	// Module is the Swift module.
	Module string
	// ElementKind is the Mochi kind of each emitted element.
	ElementKind typemap.Kind
}

// EmitAsyncSequenceBridge writes a Swift file that bridges AsyncSequence
// to Mochi stream<T> using a callback-based C interface.
func EmitAsyncSequenceBridge(specs []SequenceSpec, outPath string) error {
	sw := buildAsyncSequenceBridge(specs)
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("concurrency: mkdir: %w", err)
	}
	return os.WriteFile(outPath, []byte(sw), 0o644)
}

func buildAsyncSequenceBridge(specs []SequenceSpec) string {
	var b strings.Builder
	b.WriteString("// Generated by mochi/package3/swift/concurrency; do not edit.\n")
	b.WriteString("import Foundation\n\n")
	for _, spec := range specs {
		b.WriteString(emitSequenceWrapper(spec))
		b.WriteString("\n")
	}
	return b.String()
}

func emitSequenceWrapper(spec SequenceSpec) string {
	var b strings.Builder
	elemType := kindToSwiftType(spec.ElementKind)
	callbackType := fmt.Sprintf("@convention(c) (%s) -> Void", kindToCType(spec.ElementKind))

	fmt.Fprintf(&b, "@_cdecl(%q)\n", spec.MochiName)
	fmt.Fprintf(&b, "public func %s(\n", spec.MochiName)
	fmt.Fprintf(&b, "    _ sequence: %s,\n", spec.SwiftSequenceName)
	fmt.Fprintf(&b, "    _ emit: %s\n", callbackType)
	b.WriteString(") {\n")
	b.WriteString("    let group = DispatchGroup()\n")
	b.WriteString("    group.enter()\n")
	b.WriteString("    Task {\n")
	fmt.Fprintf(&b, "        for await element: %s in sequence {\n", elemType)
	b.WriteString("            emit(element)\n")
	b.WriteString("        }\n")
	b.WriteString("        group.leave()\n")
	b.WriteString("    }\n")
	b.WriteString("    group.wait()\n")
	b.WriteString("}\n")
	return b.String()
}

func kindToSwiftType(k typemap.Kind) string {
	switch k {
	case typemap.KindInt:
		return "Int"
	case typemap.KindFloat:
		return "Double"
	case typemap.KindBool:
		return "Bool"
	case typemap.KindString:
		return "String"
	default:
		return "Int"
	}
}

func kindToCType(k typemap.Kind) string {
	switch k {
	case typemap.KindInt:
		return "CLongLong"
	case typemap.KindFloat:
		return "CDouble"
	case typemap.KindBool:
		return "CBool"
	case typemap.KindString:
		return "UnsafePointer<CChar>"
	default:
		return "CLongLong"
	}
}
