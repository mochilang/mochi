// Package gemspec emits a Ruby .gemspec file from the [ruby.publish] section
// of mochi.toml. The emitted gemspec is then passed to `gem build` by the
// MEP-76 publish flow.
//
// Phase 10 of MEP-76 completes this package.
// See [website/docs/research/0076/06-rubygems-publish-flow.md] for the
// gemspec field mapping.
package gemspec

import (
	"fmt"
	"strings"
)

// PublishConfig holds the publish-side fields from mochi.toml.
type PublishConfig struct {
	// From [package]
	Name        string
	Version     string
	Description string // used as both summary (truncated) and description
	Authors     []string
	License     string // SPDX expression, e.g. "Apache-2.0"
	Homepage    string

	// From [ruby.publish]
	GemName     string // overrides Name if set
	Summary     string // short summary; if empty, first sentence of Description
	Metadata    map[string]string
	RuntimeDeps []GemDep // from [ruby-dependencies]
}

// GemDep is one runtime dependency to declare in the gemspec.
type GemDep struct {
	Name       string
	Constraint string // e.g. "~> 1.16", ">= 2.0"
}

// Emit returns the content of a .gemspec file for the given config.
func Emit(cfg PublishConfig) string {
	var sb strings.Builder
	sb.WriteString("# frozen_string_literal: true\n")
	sb.WriteString("# Auto-generated by mochi pkg publish (MEP-76). Do not edit.\n\n")
	sb.WriteString("Gem::Specification.new do |spec|\n")

	gemName := cfg.GemName
	if gemName == "" {
		gemName = cfg.Name
	}
	fmt.Fprintf(&sb, "  spec.name          = %q\n", gemName)
	fmt.Fprintf(&sb, "  spec.version       = %q\n", cfg.Version)
	fmt.Fprintf(&sb, "  spec.authors       = [%s]\n", quotedList(cfg.Authors))

	summary := cfg.Summary
	if summary == "" {
		summary = firstSentence(cfg.Description)
	}
	fmt.Fprintf(&sb, "  spec.summary       = %q\n", summary)
	if cfg.Description != "" && cfg.Description != summary {
		fmt.Fprintf(&sb, "  spec.description   = %q\n", cfg.Description)
	}
	if cfg.Homepage != "" {
		fmt.Fprintf(&sb, "  spec.homepage      = %q\n", cfg.Homepage)
	}
	if cfg.License != "" {
		fmt.Fprintf(&sb, "  spec.license       = %q\n", cfg.License)
	}

	sb.WriteString("\n  spec.files         = Dir[\"lib/**/*.rb\", \"sig/**/*.rbs\"]\n")
	sb.WriteString("  spec.require_paths = [\"lib\"]\n")

	if len(cfg.Metadata) > 0 {
		sb.WriteString("\n  spec.metadata = {\n")
		for k, v := range cfg.Metadata {
			fmt.Fprintf(&sb, "    %q => %q,\n", k, v)
		}
		sb.WriteString("  }\n")
	}

	if len(cfg.RuntimeDeps) > 0 {
		sb.WriteByte('\n')
		for _, dep := range cfg.RuntimeDeps {
			fmt.Fprintf(&sb, "  spec.add_runtime_dependency %q, %q\n", dep.Name, dep.Constraint)
		}
	}

	sb.WriteString("end\n")
	return sb.String()
}

func quotedList(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

func firstSentence(s string) string {
	for i, r := range s {
		if r == '.' || r == '!' || r == '?' {
			return s[:i+1]
		}
	}
	if len(s) > 80 {
		return s[:80]
	}
	return s
}
