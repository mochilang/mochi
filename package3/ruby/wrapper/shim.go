// Package wrapper emits the two shim files for each imported Ruby gem:
//
//   - shim.rb: a Ruby module that requires the gem and forwards public
//     method calls. Because MEP-56 already transpiles Mochi to Ruby, no
//     C FFI layer is needed; the shim is plain Ruby require + delegation.
//
//   - shim.mochi: a corpus of `extern fn` declarations that expose the
//     gem's translated surface to Mochi source files.
//
// Phase 6 of MEP-76 completes this package.
// See [website/docs/research/0076/01-language-surface.md] §"Shim file mechanics".
package wrapper

import (
	"fmt"
	"strings"

	pkgerr "mochi/package3/ruby/errors"
	"mochi/package3/ruby/rbs"
	"mochi/package3/ruby/typemap"
)

// ShimResult holds the generated shim files for one gem plus the skip report.
type ShimResult struct {
	GemName    string
	Version    string
	RubyShim   string           // content of shim.rb
	MochiShim  string           // content of shim.mochi
	Skipped    []*pkgerr.SkipReport
}

// GenerateShims produces both shim files from a gem's API surface.
func GenerateShims(surface *rbs.GemSurface) (*ShimResult, error) {
	res := &ShimResult{
		GemName: surface.Gem,
		Version: surface.Version,
	}

	var rb strings.Builder
	var mochi strings.Builder

	// Ruby shim header.
	fmt.Fprintf(&rb, "# frozen_string_literal: true\n")
	fmt.Fprintf(&rb, "# Auto-generated by mochi pkg lock (MEP-76). Do not edit.\n")
	fmt.Fprintf(&rb, "require %q\n\n", surface.Gem)
	fmt.Fprintf(&rb, "module MochiWrap\n")
	fmt.Fprintf(&rb, "  module %s\n", rubyModuleName(surface.Gem))

	// Mochi shim header.
	fmt.Fprintf(&mochi, "// Auto-generated by mochi pkg lock (MEP-76). Do not edit.\n")
	fmt.Fprintf(&mochi, "// Gem: %s@%s  RBS source: %s\n\n", surface.Gem, surface.Version, sourceLabel(surface.Source))

	for _, cls := range surface.Classes {
		for _, method := range cls.Methods {
			if len(method.Types) == 0 {
				continue
			}
			// Use the first overload for the primary translation.
			sig := method.Types[0]
			translated, skip := translateMethod(surface.Gem, cls.Name+"."+method.Name, sig)
			if skip != nil {
				res.Skipped = append(res.Skipped, skip)
				continue
			}
			// Ruby shim: a module_function that delegates to the gem class.
			emitRubyMethod(&rb, cls.Name, method.Name, sig)
			// Mochi extern fn declaration.
			fmt.Fprintf(&mochi, "%s\n", translated)
		}
	}

	fmt.Fprintf(&rb, "  end\nend\n")
	res.RubyShim = rb.String()
	res.MochiShim = mochi.String()
	return res, nil
}

// translateMethod converts one RBS method signature to a Mochi extern fn line.
// Returns ("", SkipReport) if any parameter or return type is out of table.
func translateMethod(gem, item string, sig rbs.MethodType) (string, *pkgerr.SkipReport) {
	var params []string
	for _, p := range sig.Params {
		mt, skip := typemap.Translate(p.Type, gem, item)
		if skip != nil {
			return "", skip
		}
		params = append(params, p.Name+": "+mt)
	}
	ret, skip := typemap.Translate(sig.Return, gem, item)
	if skip != nil {
		return "", skip
	}
	name := strings.ReplaceAll(item, ".", "_")
	name = strings.ReplaceAll(name, "::", "_")
	paramStr := strings.Join(params, ", ")
	return fmt.Sprintf("extern fun %s(%s): %s from ruby %q", name, paramStr, ret, item), nil
}

func emitRubyMethod(sb *strings.Builder, className, methodName string, sig rbs.MethodType) {
	var paramNames []string
	for _, p := range sig.Params {
		paramNames = append(paramNames, p.Name)
	}
	paramList := strings.Join(paramNames, ", ")
	if paramList != "" {
		paramList = "(" + paramList + ")"
	}
	fmt.Fprintf(sb, "    def self.%s%s\n", methodName, paramList)
	fmt.Fprintf(sb, "      %s.%s%s\n", className, methodName, paramList)
	fmt.Fprintf(sb, "    end\n")
}

func rubyModuleName(gem string) string {
	parts := strings.Split(gem, "-")
	var out strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			out.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return out.String()
}

func sourceLabel(s rbs.SurfaceSource) string {
	switch s {
	case rbs.SourceBundled:
		return "bundled"
	case rbs.SourceGemRBSCollection:
		return "gem_rbs_collection"
	case rbs.SourceYARD:
		return "yard"
	default:
		return "none"
	}
}
