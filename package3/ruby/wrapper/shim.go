// Package wrapper emits the two shim files for each imported Ruby gem:
//
//   - shim.rb: a Ruby module that requires the gem and forwards public
//     method calls. Because MEP-56 already transpiles Mochi to Ruby, no
//     C FFI layer is needed; the shim is plain Ruby require + delegation.
//
//   - shim.mochi: a corpus of `extern fn` declarations that expose the
//     gem's translated surface to Mochi source files.
//
// Phase 6 of MEP-76 completes this package.
// See [website/docs/research/0076/01-language-surface.md] §"Shim file mechanics".
package wrapper

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	pkgerr "mochi/package3/ruby/errors"
	"mochi/package3/ruby/rbs"
	"mochi/package3/ruby/typemap"
)

// ShimConfig carries the per-gem configuration for shim generation.
type ShimConfig struct {
	Gem     string // gem name (overrides surface.Gem when non-empty)
	Version string // gem version (overrides surface.Version when non-empty)
	Alias   string // Mochi import alias (informational only)
	WrapDir string // destination directory for WriteShims (informational only)
}

// ShimResult holds the generated shim files for one gem plus the skip report.
type ShimResult struct {
	GemName      string
	Version      string
	RubyShim     string // content of shim.rb
	MochiShim    string // content of shim.mochi
	Skipped      []*pkgerr.SkipReport
	SkipCount    int
	SuccessCount int
}

// GenerateShims produces both shim files from a gem's API surface.
func GenerateShims(surface *rbs.GemSurface, cfg ShimConfig) (*ShimResult, error) {
	gemName := cfg.Gem
	if gemName == "" {
		gemName = surface.Gem
	}
	version := cfg.Version
	if version == "" {
		version = surface.Version
	}

	res := &ShimResult{
		GemName: gemName,
		Version: version,
	}

	var rb strings.Builder
	var mochiMethods strings.Builder

	fmt.Fprintf(&rb, "# frozen_string_literal: true\n")
	fmt.Fprintf(&rb, "# Auto-generated by mochi pkg lock (MEP-76). Do not edit.\n")
	fmt.Fprintf(&rb, "require %q\n\n", gemName)
	fmt.Fprintf(&rb, "module MochiWrap\n")
	fmt.Fprintf(&rb, "  module %s\n", rubyModuleName(gemName))

	for _, cls := range surface.Classes {
		allMethods := append(cls.Methods, cls.Attrs...)
		for _, method := range allMethods {
			if len(method.Types) == 0 {
				res.Skipped = append(res.Skipped, &pkgerr.SkipReport{
					Gem:     gemName,
					Item:    cls.Name + "#" + method.Name,
					Reason:  pkgerr.SkipNativeExtension,
					RBSType: "no overloads",
				})
				res.SkipCount++
				continue
			}
			sig := method.Types[0]
			translated, skip := typemap.TranslateMethod(gemName, method, cls.Name)
			if skip != nil {
				res.Skipped = append(res.Skipped, skip)
				res.SkipCount++
				continue
			}
			emitRubyMethod(&rb, cls.Name, method.Name, method.Kind, sig)
			fmt.Fprintf(&mochiMethods, "%s\n", translated)
			res.SuccessCount++
		}
	}

	fmt.Fprintf(&rb, "  end\nend\n")
	res.RubyShim = rb.String()

	var mochi strings.Builder
	fmt.Fprintf(&mochi, "// Auto-generated by mochi pkg lock (MEP-76). Do not edit.\n")
	fmt.Fprintf(&mochi, "// Gem: %s@%s  RBS source: %s  skip: %d/%d\n\n",
		gemName, version, sourceLabel(surface.Source),
		res.SkipCount, res.SkipCount+res.SuccessCount)
	mochi.WriteString(mochiMethods.String())
	res.MochiShim = mochi.String()

	return res, nil
}

// WriteShims writes shim.rb and shim.mochi into <dir>/<gem>/.
func WriteShims(res *ShimResult, dir string) error {
	gemDir := filepath.Join(dir, res.GemName)
	if err := os.MkdirAll(gemDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(gemDir, "shim.rb"), []byte(res.RubyShim), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(gemDir, "shim.mochi"), []byte(res.MochiShim), 0o644)
}

func emitRubyMethod(sb *strings.Builder, className, methodName string, kind rbs.MethodKind, sig rbs.MethodType) {
	fnName := methodFnName(className, methodName)
	var paramNames []string
	if kind == rbs.MethodInstance {
		paramNames = append(paramNames, "__recv")
	}
	for _, p := range sig.Params {
		paramNames = append(paramNames, p.Name)
	}
	paramList := strings.Join(paramNames, ", ")
	fmt.Fprintf(sb, "    def self.%s(%s)\n", fnName, paramList)
	if kind == rbs.MethodInstance {
		callParams := make([]string, 0, len(sig.Params))
		for _, p := range sig.Params {
			callParams = append(callParams, p.Name)
		}
		fmt.Fprintf(sb, "      __recv.%s(%s)\n", methodName, strings.Join(callParams, ", "))
	} else {
		callParams := make([]string, 0, len(sig.Params))
		for _, p := range sig.Params {
			callParams = append(callParams, p.Name)
		}
		fmt.Fprintf(sb, "      %s.%s(%s)\n", className, methodName, strings.Join(callParams, ", "))
	}
	fmt.Fprintf(sb, "    end\n")
}

func methodFnName(className, methodName string) string {
	classPart := strings.ToLower(className)
	classPart = strings.ReplaceAll(classPart, "::", "_")
	classPart = strings.ReplaceAll(classPart, ".", "_")
	return classPart + "_" + methodName
}

func rubyModuleName(gem string) string {
	parts := strings.Split(gem, "-")
	var out strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			out.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return out.String()
}

func sourceLabel(s rbs.SurfaceSource) string {
	switch s {
	case rbs.SourceBundled:
		return "bundled"
	case rbs.SourceGemRBSCollection:
		return "gem_rbs_collection"
	case rbs.SourceYARD:
		return "yard"
	default:
		return "none"
	}
}
