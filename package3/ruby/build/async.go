// Package build orchestrates the Bundler-based build for Mochi programs that
// use `import ruby "..."` declarations. It synthesises a Gemfile from the
// resolved [[ruby-package]] entries in mochi.lock, runs `bundle install
// --deployment --frozen`, and injects the BUNDLE_GEMFILE + BUNDLE_PATH
// environment variables into the MEP-56 Ruby emit pipeline.
//
// Phase 8 of MEP-76 completes the Bundler orchestration (see build.go).
// Phase 13 of MEP-76 adds the async bridge configuration (see async.go).
//
// See [website/docs/research/0076/09-bundler-lockfile.md] for the Bundler
// orchestration strategy.
package build

import (
	"fmt"
	"strings"
)

// AsyncFramework is the Ruby async concurrency model to use for gem calls
// that return Fiber-based async values.
type AsyncFramework int

const (
	// AsyncNone uses synchronous calls only. This is the default.
	AsyncNone AsyncFramework = iota
	// AsyncFiber uses the Ruby Fiber::Scheduler interface (Ruby 3.1+).
	AsyncFiber
	// AsyncAsyncGem uses the socketry/async gem for structured concurrency.
	AsyncAsyncGem
	// AsyncRactor uses Ruby Ractors for parallelism (Ruby 3.0+, experimental).
	AsyncRactor
)

// AsyncConfig holds the [ruby.async] manifest settings parsed from mochi.toml.
type AsyncConfig struct {
	// Framework selects the async concurrency model.
	Framework AsyncFramework
	// RactorSafe, when true, asserts that all imported gems are Ractor-safe.
	// The emitter relies on this assertion; it does not verify it at compile time.
	RactorSafe bool
	// FiberTimeout is the number of seconds to wait before a Fiber.yield times
	// out. Zero means no timeout.
	FiberTimeout int
}

// ParseAsyncFramework converts a string from mochi.toml to an AsyncFramework
// constant. Accepted values: "", "none", "fiber", "async", "ractor".
// An empty string is treated as "none". Returns an error for any other value.
func ParseAsyncFramework(s string) (AsyncFramework, error) {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "", "none":
		return AsyncNone, nil
	case "fiber":
		return AsyncFiber, nil
	case "async":
		return AsyncAsyncGem, nil
	case "ractor":
		return AsyncRactor, nil
	default:
		return AsyncNone, fmt.Errorf(
			"unknown async framework %q: expected one of none, fiber, async, ractor", s)
	}
}

// GenerateAsyncBootstrap returns Ruby code to inject at the top of the
// MEP-56-emitted .rb file to configure the chosen async framework.
//
// For AsyncNone an empty string is returned (no injection needed).
// For AsyncFiber the output sets up a minimal Fiber::Scheduler.
// For AsyncAsyncGem the output bootstraps the socketry/async Async{} wrapper.
// For AsyncRactor the output includes Ractor.make_shareable boilerplate and a
// prominent warning comment because Ractor support is still experimental in
// the Ruby ecosystem.
func GenerateAsyncBootstrap(cfg AsyncConfig) string {
	switch cfg.Framework {
	case AsyncNone:
		return ""

	case AsyncFiber:
		var sb strings.Builder
		sb.WriteString("# frozen_string_literal: true\n")
		sb.WriteString("# Async bootstrap: Fiber::Scheduler (Ruby 3.1+)\n")
		sb.WriteString("# Auto-generated by mochi build (MEP-76). Do not edit.\n")
		sb.WriteString("require \"fiber\"\n\n")
		sb.WriteString("# Install a minimal Fiber scheduler for non-blocking gem calls.\n")
		sb.WriteString("# Replace with a full scheduler (e.g. Async::Scheduler) for production use.\n")
		if cfg.FiberTimeout > 0 {
			fmt.Fprintf(&sb, "MOCHI_FIBER_TIMEOUT = %d # seconds\n\n", cfg.FiberTimeout)
		}
		sb.WriteString("unless Fiber.current.respond_to?(:scheduler_set)\n")
		sb.WriteString("  # No-op scheduler: lets the runtime install its own.\n")
		sb.WriteString("  Fiber.set_scheduler(nil)\n")
		sb.WriteString("end\n")
		return sb.String()

	case AsyncAsyncGem:
		var sb strings.Builder
		sb.WriteString("# frozen_string_literal: true\n")
		sb.WriteString("# Async bootstrap: socketry/async gem\n")
		sb.WriteString("# Auto-generated by mochi build (MEP-76). Do not edit.\n")
		sb.WriteString("require \"async\"\n\n")
		sb.WriteString("# All gem calls that return async values run inside an Async{} task.\n")
		sb.WriteString("# The reactor is started once at program entry and reused throughout.\n")
		sb.WriteString("MOCHI_ASYNC_REACTOR = Async::Reactor.new\n")
		sb.WriteString("\n")
		sb.WriteString("def mochi_async_run(&block)\n")
		sb.WriteString("  MOCHI_ASYNC_REACTOR.async(&block)\n")
		sb.WriteString("end\n")
		return sb.String()

	case AsyncRactor:
		var sb strings.Builder
		sb.WriteString("# frozen_string_literal: true\n")
		sb.WriteString("# Async bootstrap: Ractor (Ruby 3.0+, EXPERIMENTAL)\n")
		sb.WriteString("# Auto-generated by mochi build (MEP-76). Do not edit.\n")
		sb.WriteString("#\n")
		sb.WriteString("# WARNING: Ractor support is experimental. Not all gems are Ractor-safe.\n")
		sb.WriteString("# You have asserted (ractor_safe = true) that every imported gem is safe.\n")
		sb.WriteString("# If this assertion is wrong the program may deadlock or raise Ractor::Error.\n")
		if !cfg.RactorSafe {
			sb.WriteString("#\n")
			sb.WriteString("# WARNING: ractor_safe is NOT set to true. Proceed with caution.\n")
		}
		sb.WriteString("\n")
		sb.WriteString("# Freeze shared objects before passing them to Ractors.\n")
		sb.WriteString("Ractor.make_shareable(MOCHI_RACTOR_POOL = [].freeze)\n")
		sb.WriteString("\n")
		sb.WriteString("def mochi_ractor_run(name, &block)\n")
		sb.WriteString("  Ractor.new(name: name, &block)\n")
		sb.WriteString("end\n")
		return sb.String()

	default:
		return ""
	}
}
