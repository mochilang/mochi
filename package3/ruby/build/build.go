// Package build orchestrates the Bundler-based build for Mochi programs that
// use `import ruby "..."` declarations. It synthesises a Gemfile from the
// resolved [[ruby-package]] entries in mochi.lock, runs `bundle install
// --deployment --frozen`, and injects the BUNDLE_GEMFILE + BUNDLE_PATH
// environment variables into the MEP-56 Ruby emit pipeline.
//
// Phase 8 of MEP-76 completes this package.
// See [website/docs/research/0076/09-bundler-lockfile.md] for the Bundler
// orchestration strategy.
package build

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// RubyDep is one resolved gem dependency from mochi.lock [[ruby-package]].
type RubyDep struct {
	Name     string
	Version  string
	Platform string // "" for universal
}

// BundleConfig holds the parameters for a Bundler build.
type BundleConfig struct {
	// WorkDir is the directory where .mochi-ruby/ will be created.
	WorkDir string
	// Deps is the list of resolved gems to include in the Gemfile.
	Deps []RubyDep
	// BundlerVersion pins the bundler version used. "" means system default.
	BundlerVersion string
	// RubyVersion is the required Ruby version declared in mochi.toml [ruby].
	RubyVersion string
}

// Prepare writes the synthetic Gemfile, runs bundle install, and returns the
// environment variables to set when invoking the MEP-56 Ruby emit pipeline.
func Prepare(cfg BundleConfig) (map[string]string, error) {
	rubyDir := filepath.Join(cfg.WorkDir, ".mochi-ruby")
	if err := os.MkdirAll(rubyDir, 0o755); err != nil {
		return nil, fmt.Errorf("create .mochi-ruby: %w", err)
	}

	gemfilePath := filepath.Join(rubyDir, "Gemfile")
	if err := writeGemfile(gemfilePath, cfg); err != nil {
		return nil, err
	}

	vendorPath := filepath.Join(rubyDir, "vendor", "bundle")
	args := []string{
		"install",
		"--deployment",
		"--frozen",
		"--gemfile", gemfilePath,
		"--path", vendorPath,
		"--without", "development test",
	}
	if cfg.BundlerVersion != "" {
		// Run via `bundle _<version>_` to pin the Bundler version.
		args = append([]string{"_" + cfg.BundlerVersion + "_"}, args...)
	}
	cmd := exec.Command("bundle", args...)
	cmd.Env = append(os.Environ(), "BUNDLE_GEMFILE="+gemfilePath)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return nil, fmt.Errorf("bundle install failed: %w\n%s", err, out)
	}

	return map[string]string{
		"BUNDLE_GEMFILE": gemfilePath,
		"BUNDLE_PATH":    vendorPath,
	}, nil
}

// writeGemfile writes a synthetic Gemfile for the resolved deps.
func writeGemfile(path string, cfg BundleConfig) error {
	var sb strings.Builder
	sb.WriteString("# frozen_string_literal: true\n")
	sb.WriteString("# Auto-generated by mochi build (MEP-76). Do not edit.\n")
	sb.WriteString("source \"https://rubygems.org\"\n\n")

	if cfg.RubyVersion != "" {
		fmt.Fprintf(&sb, "ruby \">= %s\"\n\n", cfg.RubyVersion)
	}

	for _, dep := range cfg.Deps {
		if dep.Platform != "" {
			fmt.Fprintf(&sb, "gem %q, %q, platforms: [%s]\n",
				dep.Name, dep.Version, platformToRuby(dep.Platform))
		} else {
			fmt.Fprintf(&sb, "gem %q, %q\n", dep.Name, dep.Version)
		}
	}
	return os.WriteFile(path, []byte(sb.String()), 0o644)
}

// platformToRuby converts a RubyGems platform string to the Ruby platform
// symbol used in Gemfile platform: constraints.
func platformToRuby(platform string) string {
	switch {
	case strings.Contains(platform, "linux"):
		return ":linux"
	case strings.Contains(platform, "darwin"):
		return ":darwin"
	case strings.Contains(platform, "mingw"):
		return ":mingw, :x64_mingw"
	default:
		return ":ruby"
	}
}
