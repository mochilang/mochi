// Package build is the MEP-67 bridge build-orchestration package. Phase 0
// lands the skeleton: the Driver struct (WorkDir / CacheDir), the Workspace
// type that models the Maven workspace topology, and the POM renderer.
// Later phases extend this package with Maven Central fetch, reflection,
// wrapper synthesis, javac invocation, and publish flow.
package build

import (
	"fmt"
	"sort"
	"strings"
)

// Workspace models the Maven multi-module workspace the bridge synthesises at
// build time. A workspace has a root pom.xml and zero or more member modules
// (wrapper modules for each imported Java dep, and the user's top-level module).
type Workspace struct {
	// GroupID is the Maven groupId for the workspace root.
	GroupID string
	// ArtifactID is the Maven artifactId for the workspace root.
	ArtifactID string
	// Version is the workspace version.
	Version string
	// Members is the ordered list of module members.
	Members []WorkspaceMember
}

// WorkspaceMember describes a single Maven module that participates in the
// workspace. The Path is relative to the workspace root.
type WorkspaceMember struct {
	// Name is the module name.
	Name string
	// Path is the directory relative to the workspace root.
	Path string
	// Kind classifies the member's role.
	Kind WorkspaceMemberKind
}

// WorkspaceMemberKind classifies a workspace member's role.
type WorkspaceMemberKind int

const (
	// MemberUser is the user's Mochi-emitted top-level module.
	MemberUser WorkspaceMemberKind = iota
	// MemberWrapper is a synthesised Java wrapper module.
	MemberWrapper
)

// String renders the kind as a short token for diagnostics.
func (k WorkspaceMemberKind) String() string {
	switch k {
	case MemberUser:
		return "user"
	case MemberWrapper:
		return "wrapper"
	default:
		return "unknown"
	}
}

// DefaultWorkspace returns a Workspace with the bridge's recommended defaults.
func DefaultWorkspace() *Workspace {
	return &Workspace{
		GroupID:    "dev.mochi",
		ArtifactID: "java-bridge-workspace",
		Version:    "0.1.0-SNAPSHOT",
	}
}

// AddMember inserts a member module into the workspace, keeping paths sorted
// for deterministic POM output.
func (w *Workspace) AddMember(m WorkspaceMember) {
	for _, existing := range w.Members {
		if existing.Path == m.Path {
			return
		}
	}
	w.Members = append(w.Members, m)
	sort.Slice(w.Members, func(i, j int) bool {
		return w.Members[i].Path < w.Members[j].Path
	})
}

// AddSharedDep is a no-op placeholder for API symmetry with the Rust bridge.
// Maven dependency management uses per-module pom.xml, not a workspace-level
// dependency table.
func (w *Workspace) AddSharedDep(_, _ string) {}

// Validate checks the workspace for structural problems.
func (w *Workspace) Validate() error {
	if w.GroupID == "" {
		return fmt.Errorf("workspace: GroupID is empty")
	}
	if w.ArtifactID == "" {
		return fmt.Errorf("workspace: ArtifactID is empty")
	}
	if w.Version == "" {
		return fmt.Errorf("workspace: Version is empty")
	}
	seen := map[string]struct{}{}
	for _, m := range w.Members {
		if m.Name == "" {
			return fmt.Errorf("workspace: member at path %q has empty Name", m.Path)
		}
		if m.Path == "" {
			return fmt.Errorf("workspace: member %q has empty Path", m.Name)
		}
		if _, dup := seen[m.Path]; dup {
			return fmt.Errorf("workspace: duplicate member path %q", m.Path)
		}
		seen[m.Path] = struct{}{}
	}
	return nil
}

// RenderRootPOM returns the workspace root pom.xml as a string. The output is
// deterministic: modules are listed in alphabetical order by path.
//
// The rendered POM uses packaging=pom (aggregator), suitable for a Maven
// multi-module project root. It does not carry any dependencies itself.
func (w *Workspace) RenderRootPOM() string {
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>`)
	b.WriteString("\n")
	b.WriteString("<!-- Auto-generated by MEP-67 bridge. Do not edit by hand. -->\n")
	b.WriteString("<!-- Regenerate via `mochi pkg lock`. -->\n")
	b.WriteString(`<project xmlns="http://maven.apache.org/POM/4.0.0"`)
	b.WriteString("\n")
	b.WriteString(`         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"`)
	b.WriteString("\n")
	b.WriteString(`         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">`)
	b.WriteString("\n")
	b.WriteString("  <modelVersion>4.0.0</modelVersion>\n")
	fmt.Fprintf(&b, "  <groupId>%s</groupId>\n", xmlEscape(w.GroupID))
	fmt.Fprintf(&b, "  <artifactId>%s</artifactId>\n", xmlEscape(w.ArtifactID))
	fmt.Fprintf(&b, "  <version>%s</version>\n", xmlEscape(w.Version))
	b.WriteString("  <packaging>pom</packaging>\n")
	if len(w.Members) > 0 {
		b.WriteString("  <modules>\n")
		for _, m := range w.Members {
			fmt.Fprintf(&b, "    <module>%s</module>\n", xmlEscape(m.Path))
		}
		b.WriteString("  </modules>\n")
	}
	b.WriteString("</project>\n")
	return b.String()
}

// xmlEscape escapes special XML characters in attribute and element content.
func xmlEscape(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	s = strings.ReplaceAll(s, `"`, "&quot;")
	return s
}
