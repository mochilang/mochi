package build

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestPhase0Skeleton is the per-phase sentinel test. The CI gate for phase
// 0 LANDED requires this test to pass on every supported host.
//
// Sub-tests:
//   - end_to_end: Driver allocates work-dir, writes workspace root pom.xml,
//     re-reads it, the POM has expected XML elements, cleanup removes work-dir.
//   - package_layout: the package3/java/ tree exists at expected paths.
//   - default_workspace_invariants: Validate passes, RenderRootPOM has expected elements.
func TestPhase0Skeleton(t *testing.T) {
	t.Run("end_to_end", func(t *testing.T) {
		d := NewDriver(Options{NoCache: true})
		defer d.Cleanup()

		w, err := d.PrepareWorkspace()
		if err != nil {
			t.Fatalf("PrepareWorkspace: %v", err)
		}
		w.AddMember(WorkspaceMember{Name: "mochi-user", Path: "mochi_user", Kind: MemberUser})
		w.AddMember(WorkspaceMember{Name: "java-wrap-guava", Path: "java_wrap/guava", Kind: MemberWrapper})

		root, err := d.WriteWorkspaceRoot(w)
		if err != nil {
			t.Fatalf("WriteWorkspaceRoot: %v", err)
		}
		pomBytes, err := os.ReadFile(filepath.Join(root, "pom.xml"))
		if err != nil {
			t.Fatalf("read pom.xml: %v", err)
		}
		pom := string(pomBytes)
		wantBits := []string{
			"<?xml version",
			"<packaging>pom</packaging>",
			"<module>java_wrap/guava</module>",
			"<module>mochi_user</module>",
		}
		for _, bit := range wantBits {
			if !strings.Contains(pom, bit) {
				t.Errorf("pom.xml missing %q\n--- output ---\n%s", bit, pom)
			}
		}

		work := d.WorkDir()
		if err := d.Cleanup(); err != nil {
			t.Fatalf("Cleanup: %v", err)
		}
		if _, err := os.Stat(work); !os.IsNotExist(err) {
			t.Errorf("work-dir not removed by Cleanup: %v", err)
		}
	})

	t.Run("package_layout", func(t *testing.T) {
		here, err := os.Getwd()
		if err != nil {
			t.Fatalf("Getwd: %v", err)
		}
		pkgRoot := filepath.Dir(here)
		expected := []string{
			"README.md",
			"build/driver.go",
			"build/workspace.go",
			"errors/errors.go",
		}
		for _, rel := range expected {
			path := filepath.Join(pkgRoot, rel)
			info, err := os.Stat(path)
			if err != nil {
				t.Errorf("expected file %s missing: %v", rel, err)
				continue
			}
			if info.IsDir() {
				t.Errorf("expected file %s is a directory", rel)
			}
		}
	})

	t.Run("default_workspace_invariants", func(t *testing.T) {
		w := DefaultWorkspace()
		if err := w.Validate(); err != nil {
			t.Errorf("DefaultWorkspace().Validate() = %v; want nil", err)
		}
		pom := w.RenderRootPOM()
		if !strings.Contains(pom, "Auto-generated by MEP-67") {
			t.Errorf("DefaultWorkspace render missing header")
		}
		if !strings.Contains(pom, "<packaging>pom</packaging>") {
			t.Errorf("DefaultWorkspace render missing packaging=pom")
		}
		if !strings.Contains(pom, "<modelVersion>4.0.0</modelVersion>") {
			t.Errorf("DefaultWorkspace render missing modelVersion")
		}
	})
}
