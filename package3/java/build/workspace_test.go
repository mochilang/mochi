package build

import (
	"strings"
	"testing"
)

func TestDefaultWorkspace(t *testing.T) {
	w := DefaultWorkspace()
	if w == nil {
		t.Fatal("DefaultWorkspace returned nil")
	}
	if w.GroupID == "" {
		t.Error("GroupID is empty")
	}
	if w.ArtifactID == "" {
		t.Error("ArtifactID is empty")
	}
	if w.Version == "" {
		t.Error("Version is empty")
	}
}

func TestWorkspaceValidate(t *testing.T) {
	w := DefaultWorkspace()
	if err := w.Validate(); err != nil {
		t.Errorf("DefaultWorkspace().Validate() = %v; want nil", err)
	}
}

func TestWorkspaceValidateEmpty(t *testing.T) {
	w := &Workspace{}
	if err := w.Validate(); err == nil {
		t.Error("empty Workspace should fail Validate")
	}
}

func TestWorkspaceAddMember(t *testing.T) {
	w := DefaultWorkspace()
	w.AddMember(WorkspaceMember{Name: "wrap-guava", Path: "java_wrap/guava", Kind: MemberWrapper})
	w.AddMember(WorkspaceMember{Name: "mochi-user", Path: "mochi_user", Kind: MemberUser})
	// duplicate should be ignored
	w.AddMember(WorkspaceMember{Name: "wrap-guava", Path: "java_wrap/guava", Kind: MemberWrapper})
	if len(w.Members) != 2 {
		t.Errorf("expected 2 members, got %d", len(w.Members))
	}
	// should be sorted by path
	if w.Members[0].Path != "java_wrap/guava" {
		t.Errorf("Members[0].Path = %q; want java_wrap/guava", w.Members[0].Path)
	}
}

func TestWorkspaceValidateDuplicatePath(t *testing.T) {
	w := DefaultWorkspace()
	w.Members = []WorkspaceMember{
		{Name: "a", Path: "modules/a", Kind: MemberUser},
		{Name: "b", Path: "modules/a", Kind: MemberWrapper},
	}
	if err := w.Validate(); err == nil {
		t.Error("duplicate path should fail Validate")
	}
}

func TestRenderRootPOM(t *testing.T) {
	w := DefaultWorkspace()
	w.AddMember(WorkspaceMember{Name: "wrap-guava", Path: "java_wrap/guava", Kind: MemberWrapper})
	w.AddMember(WorkspaceMember{Name: "mochi-user", Path: "mochi_user", Kind: MemberUser})
	pom := w.RenderRootPOM()

	wantBits := []string{
		"<?xml version",
		"<project ",
		"<modelVersion>4.0.0</modelVersion>",
		"<groupId>dev.mochi</groupId>",
		"<packaging>pom</packaging>",
		"<module>java_wrap/guava</module>",
		"<module>mochi_user</module>",
		"Auto-generated by MEP-67",
	}
	for _, bit := range wantBits {
		if !strings.Contains(pom, bit) {
			t.Errorf("POM missing %q\n--- output ---\n%s", bit, pom)
		}
	}
}

func TestRenderRootPOMNoMembers(t *testing.T) {
	w := DefaultWorkspace()
	pom := w.RenderRootPOM()
	if strings.Contains(pom, "<modules>") {
		t.Errorf("POM should not have <modules> when there are no members")
	}
}

func TestMemberKindString(t *testing.T) {
	if MemberUser.String() != "user" {
		t.Errorf("MemberUser.String() = %q; want user", MemberUser.String())
	}
	if MemberWrapper.String() != "wrapper" {
		t.Errorf("MemberWrapper.String() = %q; want wrapper", MemberWrapper.String())
	}
}
