package wrapper

// runtimePrologue is the static FFI runtime that every wrapper crate
// includes verbatim at the top of src/lib.rs. The definitions match
// the FFIRepr() rendering in package3/rust/typemap: MochiString and
// MochiSlice are { ptr, len } pairs sized for the host pointer width;
// MochiOption / MochiResult / MochiTuple / MochiHandle are tagged
// or opaque pointers that later phases fill in (phase 11 for async,
// phase 12 for monomorphised compounds).
//
// The prologue is intentionally compact and #[repr(C)] throughout so
// that bindgen / cbindgen consumers see a stable ABI. The body is
// kept #![allow]-clean so the generated crate compiles under
// -Dwarnings.
const runtimePrologue = `// Auto-generated by mochi/package3/rust/wrapper. Do not edit.
#![allow(non_camel_case_types)]
#![allow(non_snake_case)]
#![allow(unused_imports)]
#![allow(dead_code)]

#[repr(C)]
pub struct MochiString {
    pub ptr: *const u8,
    pub len: usize,
}

#[repr(C)]
pub struct MochiSlice {
    pub ptr: *const u8,
    pub len: usize,
    pub elem_size: usize,
}

#[repr(C)]
pub struct MochiOption {
    pub present: bool,
    pub value: *mut u8,
}

#[repr(C)]
pub struct MochiResult {
    pub is_ok: bool,
    pub ok: *mut u8,
    pub err: *mut u8,
}

#[repr(C)]
pub struct MochiTuple {
    pub arity: usize,
    pub fields: *mut u8,
}

#[repr(C)]
pub struct MochiMap {
    pub len: usize,
    pub keys: *mut u8,
    pub values: *mut u8,
}

#[repr(C)]
pub struct MochiHandle {
    pub raw: *mut core::ffi::c_void,
    pub drop_fn: Option<unsafe extern "C" fn(*mut core::ffi::c_void)>,
}

#[inline]
unsafe fn mochi_string_to_str<'a>(s: MochiString) -> &'a str {
    let bytes = core::slice::from_raw_parts(s.ptr, s.len);
    core::str::from_utf8_unchecked(bytes)
}

#[inline]
fn mochi_string_from_owned(s: String) -> MochiString {
    let boxed = s.into_boxed_str();
    let len = boxed.len();
    let raw = Box::leak(boxed) as *const str as *const u8;
    MochiString { ptr: raw, len }
}

#[no_mangle]
pub unsafe extern "C" fn mochi_string_free(s: MochiString) {
    if s.ptr.is_null() || s.len == 0 {
        return;
    }
    let slice = core::slice::from_raw_parts_mut(s.ptr as *mut u8, s.len);
    let _ = Box::from_raw(slice as *mut [u8]);
}
`
