package build

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestPhase0Skeleton is the per-phase sentinel test. The CI gate for phase
// 0 LANDED requires this test to pass on every supported host.
//
// Sub-tests:
//   - end_to_end: Driver allocates work-dir, writes workspace root,
//     re-reads it, the manifest parses to expected content, cleanup
//     removes the work-dir.
//   - package_layout: the package3/rust/ tree exists at the expected
//     paths and has the documented Go packages.
func TestPhase0Skeleton(t *testing.T) {
	t.Run("end_to_end", func(t *testing.T) {
		d := NewDriver(Options{NoCache: true})
		defer d.Cleanup()

		w, err := d.PrepareWorkspace()
		if err != nil {
			t.Fatalf("PrepareWorkspace: %v", err)
		}
		w.AddMember(WorkspaceMember{Name: "mochi_user", Path: "mochi_user", Kind: MemberUser})
		w.AddMember(WorkspaceMember{Name: "rust_wrap_serde", Path: "rust_wrap/serde", Kind: MemberWrapper})
		w.AddSharedDep("serde", "1.0")

		root, err := d.WriteWorkspaceRoot(w)
		if err != nil {
			t.Fatalf("WriteWorkspaceRoot: %v", err)
		}
		manifestBytes, err := os.ReadFile(filepath.Join(root, "Cargo.toml"))
		if err != nil {
			t.Fatalf("read Cargo.toml: %v", err)
		}
		manifest := string(manifestBytes)
		wantBits := []string{
			"[workspace]",
			`resolver = "2"`,
			`"mochi_user"`,
			`"rust_wrap/serde"`,
			`mochi-runtime = "0.6"`,
			`serde = "1.0"`,
			"[profile.release]",
			`panic = "abort"`,
		}
		for _, bit := range wantBits {
			if !strings.Contains(manifest, bit) {
				t.Errorf("manifest missing %q\n--- output ---\n%s", bit, manifest)
			}
		}

		work := d.WorkDir()
		if err := d.Cleanup(); err != nil {
			t.Fatalf("Cleanup: %v", err)
		}
		if _, err := os.Stat(work); !os.IsNotExist(err) {
			t.Errorf("work-dir not removed by Cleanup: %v", err)
		}
	})

	t.Run("package_layout", func(t *testing.T) {
		// Locate package3/rust/ relative to this test source file. The
		// test runs from package3/rust/build/, so the package root is
		// one directory up.
		here, err := os.Getwd()
		if err != nil {
			t.Fatalf("Getwd: %v", err)
		}
		pkgRoot := filepath.Dir(here)
		expected := []string{
			"README.md",
			"build/driver.go",
			"build/workspace.go",
			"errors/errors.go",
		}
		for _, rel := range expected {
			path := filepath.Join(pkgRoot, rel)
			info, err := os.Stat(path)
			if err != nil {
				t.Errorf("expected file %s missing: %v", rel, err)
				continue
			}
			if info.IsDir() {
				t.Errorf("expected file %s is a directory", rel)
			}
		}
	})

	t.Run("default_workspace_invariants", func(t *testing.T) {
		w := DefaultWorkspace()
		if err := w.Validate(); err != nil {
			t.Errorf("DefaultWorkspace().Validate() = %v; want nil", err)
		}
		manifest := w.RenderRootCargoToml()
		if !strings.Contains(manifest, "Auto-generated by MEP-73") {
			t.Errorf("DefaultWorkspace render missing header")
		}
		if !strings.Contains(manifest, "[profile.release]") {
			t.Errorf("DefaultWorkspace render missing release profile")
		}
		if !strings.Contains(manifest, "[profile.dev]") {
			t.Errorf("DefaultWorkspace render missing dev profile")
		}
	})
}
