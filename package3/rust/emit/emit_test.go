func TestEmitDeterministic(t *testing.T) {
	c := wrapper.Synth("hex", "0.4.3", hexLikeSurface())
	first := Emit(c)
	for i := 0; i < 5; i++ {
		got := Emit(c)
		if got.ExternMochi != first.ExternMochi {
			t.Errorf("ExternMochi non-deterministic at iter %d", i)
		}
		if got.AliasMochi != first.AliasMochi {
			t.Errorf("AliasMochi non-deterministic at iter %d", i)
		}
	}
}

func TestEmitNoFunctions(t *testing.T) {
	c := &wrapper.Crate{Name: "mochi_wrap_empty", Upstream: "empty", UpstreamVersion: "0.0.0"}
	f := Emit(c)
	// Header is present but no extern fun / extern type lines.
	if !strings.Contains(f.ExternMochi, "// extern bindings for empty 0.0.0") {
		t.Errorf("missing header in empty extern: %q", f.ExternMochi)
	}
	if strings.Contains(f.ExternMochi, "extern fun ") {
		t.Errorf("empty crate should have no extern fun lines: %q", f.ExternMochi)
	}
	if strings.Contains(f.ExternMochi, "extern type ") {
		t.Errorf("empty crate should have no extern type lines: %q", f.ExternMochi)
	}
}

func TestEmitVoidReturn(t *testing.T) {
	// A function returning unit produces no `: T` clause and a
	// statement-call body (no `return`).
	surface := &rustdoc.ApiSurface{
		CrateName: "demo",
		Functions: []rustdoc.FunctionEntry{
			{
				ID:     "fn:tick",
				Path:   []string{"demo", "tick"},
				Inputs: nil,
				Output: nil,
			},
		},
	}
	c := wrapper.Synth("demo", "0.1.0", surface)
	f := Emit(c)
	if !strings.Contains(f.ExternMochi, "extern fun mochi_demo_tick()\n") {
		t.Errorf("ExternMochi unit-return shape wrong:\n%s", f.ExternMochi)
	}
	if !strings.Contains(f.AliasMochi, "fun tick() {\n  mochi_demo_tick()\n}\n") {
		t.Errorf("AliasMochi unit-return body wrong:\n%s", f.AliasMochi)
	}
}

func TestEmitMultiParam(t *testing.T) {
	// Two scalar params, scalar return.
	surface := &rustdoc.ApiSurface{
		CrateName: "demo",
		Functions: []rustdoc.FunctionEntry{
			{
				ID:   "fn:add",
				Path: []string{"demo", "add"},
				Inputs: []rustdoc.ParamEntry{
					{Name: "a", Type: rustdoc.Type{Primitive: "i32"}},
					{Name: "b", Type: rustdoc.Type{Primitive: "i32"}},
				},
				Output: &rustdoc.Type{Primitive: "i32"},
			},
		},
	}
	c := wrapper.Synth("demo", "0.1.0", surface)
	f := Emit(c)
	if !strings.Contains(f.ExternMochi, "extern fun mochi_demo_add(a: int, b: int): int") {
		t.Errorf("multi-param extern shape wrong:\n%s", f.ExternMochi)
	}
	if !strings.Contains(f.AliasMochi, "fun add(a: int, b: int): int {") {
		t.Errorf("multi-param alias shape wrong:\n%s", f.AliasMochi)
	}
	if !strings.Contains(f.AliasMochi, "  return mochi_demo_add(a, b)\n") {
		t.Errorf("multi-param alias call wrong:\n%s", f.AliasMochi)
	}
}

func TestMochiRenderScalars(t *testing.T) {
	cases := []struct {
		in   rustdoc.Type
		want string
	}{
		{rustdoc.Type{Primitive: "u8"}, "int"},
		{rustdoc.Type{Primitive: "u64"}, "int"},
		{rustdoc.Type{Primitive: "i32"}, "int"},
		{rustdoc.Type{Primitive: "i64"}, "int"},
		{rustdoc.Type{Primitive: "bool"}, "bool"},
		{rustdoc.Type{Primitive: "char"}, "int"},
		{rustdoc.Type{Primitive: "f32"}, "float"},
		{rustdoc.Type{Primitive: "f64"}, "float"},
	}
	for _, c := range cases {
		m, _, _ := mustMap(c.in)
		if got := MochiRender(*m); got != c.want {
			t.Errorf("MochiRender(%+v) = %q; want %q", c.in, got, c.want)
		}
	}
}

func TestMochiRenderListAndMap(t *testing.T) {
	str := rustdoc.Type{Primitive: "str"}
	u8 := rustdoc.Type{Primitive: "u8"}
	listStr := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:Vec_str", Path: "std::vec::Vec",
		Args: &rustdoc.GenericArgs{AngleBracketed: &rustdoc.AngleBracketedArgs{
			Args: []rustdoc.GenericArg{{Type: &str}},
		}},
	}}
	mapStrU8 := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:HashMap", Path: "std::collections::HashMap",
		Args: &rustdoc.GenericArgs{AngleBracketed: &rustdoc.AngleBracketedArgs{
			Args: []rustdoc.GenericArg{{Type: &str}, {Type: &u8}},
		}},
	}}
	m, _, _ := mustMap(listStr)
	if got := MochiRender(*m); got != "list<string>" {
		t.Errorf("list<str> -> %q; want list<string>", got)
	}
	m, _, _ = mustMap(mapStrU8)
	if got := MochiRender(*m); got != "map<string, int>" {
		t.Errorf("map<str,u8> -> %q; want map<string, int>", got)
	}
}

