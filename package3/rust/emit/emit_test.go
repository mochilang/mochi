// mustMap is a test helper that runs typemap.Map and fails the test
// on any refusal. We only use it on hand-crafted inputs that are
// known to map successfully.
func mustMap(t rustdoc.Type) (*typemap.Mapping, errors.SkipReason, string) {
	m, sr, det := typemap.Map(t, typemap.DirectionIn)
	return m, sr, det
}

// hexLikeSurface mirrors the surface used by wrapper's tests so we
// can exercise the same mapping fan-out from a higher level. The
// shape is:
//   - encode(data: &[u8]) -> String           -> bytes -> string
//   - decode(input: &str) -> Result<Vec<u8>, FromHexError>
//   - to_upper_hex(value: u8) -> char         -> int -> int
//
// Plus one walker SkipReport (generic) and one user-defined struct
// (FromHexError) reached through the decode return type.
func hexLikeSurface() *rustdoc.ApiSurface {
	str := rustdoc.Type{Primitive: "str"}
	u8 := rustdoc.Type{Primitive: "u8"}
	char := rustdoc.Type{Primitive: "char"}
	bytesSlice := rustdoc.Type{BorrowedRef: &rustdoc.BorrowedRefType{
		Lifetime: "'a",
		Type:     rustdoc.Type{Slice: &u8},
	}}
	strBorrow := rustdoc.Type{BorrowedRef: &rustdoc.BorrowedRefType{
		Lifetime: "'a",
		Type:     str,
	}}
	stringPath := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:String", Path: "std::string::String",
	}}
	vecU8 := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:Vec_u8", Path: "std::vec::Vec",
		Args: &rustdoc.GenericArgs{AngleBracketed: &rustdoc.AngleBracketedArgs{
			Args: []rustdoc.GenericArg{{Type: &u8}},
		}},
	}}
	fromHexError := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:FromHexError", Path: "hex::FromHexError",
	}}
	resultVecU8 := rustdoc.Type{ResolvedPath: &rustdoc.PathType{
		ID: "id:Result", Path: "core::result::Result",
		Args: &rustdoc.GenericArgs{AngleBracketed: &rustdoc.AngleBracketedArgs{
			Args: []rustdoc.GenericArg{{Type: &vecU8}, {Type: &fromHexError}},
		}},
	}}
	return &rustdoc.ApiSurface{
		CrateName:    "hex",
		CrateVersion: "0.4.3",
		Functions: []rustdoc.FunctionEntry{
			{
				ID:     "fn:encode",
				Path:   []string{"hex", "encode"},
				Inputs: []rustdoc.ParamEntry{{Name: "data", Type: bytesSlice}},
				Output: &stringPath,
			},
			{
				ID:     "fn:decode",
				Path:   []string{"hex", "decode"},
				Inputs: []rustdoc.ParamEntry{{Name: "input", Type: strBorrow}},
				Output: &resultVecU8,
			},
			{
				ID:     "fn:to_upper_hex",
				Path:   []string{"hex", "to_upper_hex"},
				Inputs: []rustdoc.ParamEntry{{Name: "value", Type: u8}},
				Output: &char,
			},
		},
		Skipped: []errors.SkipReport{
			{ItemPath: "hex::decode_to_slice", Reason: errors.SkipGeneric, Detail: "generic parameter T"},
		},
	}
}

func TestEmitExternHeader(t *testing.T) {
	c := wrapper.Synth("hex", "0.4.3", hexLikeSurface())
	f := Emit(c)
	for _, want := range []string{
		"// extern bindings for hex 0.4.3",
		"// generated by mochi/package3/rust/emit; do not edit.",
	} {
		if !strings.Contains(f.ExternMochi, want) {
			t.Errorf("ExternMochi missing %q\nfull:\n%s", want, f.ExternMochi)
		}
	}
}

