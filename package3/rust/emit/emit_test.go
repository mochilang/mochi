func TestEmitExternTypeDeclaration(t *testing.T) {
	c := wrapper.Synth("hex", "0.4.3", hexLikeSurface())
	f := Emit(c)
	if !strings.Contains(f.ExternMochi, "extern type FromHexError") {
		t.Errorf("ExternMochi missing FromHexError extern type:\n%s", f.ExternMochi)
	}
	// extern type comes before any extern fun declaration.
	tIdx := strings.Index(f.ExternMochi, "extern type FromHexError")
	fIdx := strings.Index(f.ExternMochi, "extern fun ")
	if tIdx < 0 || fIdx < 0 || tIdx > fIdx {
		t.Errorf("extern type must precede extern fun (typeIdx=%d fnIdx=%d)", tIdx, fIdx)
	}
}

