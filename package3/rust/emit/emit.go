package emit

import (
	"fmt"
	"sort"
	"strings"

	"mochi/package3/rust/wrapper"
)

// Files is the bundle of Mochi-side artefacts produced for a single
// wrapper crate. Both fields are deterministic byte streams suitable
// for direct on-disk write or content-hash addressing.
type Files struct {
	// ExternMochi is the body of `<crate>_extern.mochi`. It carries
	// the `extern type` and `extern fun` declarations bound to the
	// wrapper crate's #[no_mangle] symbols.
	ExternMochi string

	// AliasMochi is the body of `<crate>.mochi`. It re-exports each
	// extern under its short Mochi-facing name (the last segment of
	// the upstream rustdoc path).
	AliasMochi string
}

// Emit lowers a wrapper.Crate into its Mochi-side source files.
// Functions are emitted in walker order (the same order they appear
// in Crate.Functions). Both files share a banner header that records
// the upstream crate name and version, so users can grep the
// generated source for provenance.
func Emit(c *wrapper.Crate) Files {
	return Files{
		ExternMochi: emitExtern(c),
		AliasMochi:  emitAlias(c),
	}
}

func emitExtern(c *wrapper.Crate) string {
	var b strings.Builder
	writeHeader(&b, c, "extern bindings")
	b.WriteString("\n")
	for _, name := range collectTypeNames(c) {
		b.WriteString("extern type ")
		b.WriteString(name)
		b.WriteString("\n")
	}
	if len(c.Functions) == 0 {
		return b.String()
	}
	// Blank line between type decls and fn decls when both present.
	if hasAnyTypeName(c) {
		b.WriteString("\n")
	}
	for _, fn := range c.Functions {
		b.WriteString(emitExternFn(fn))
		b.WriteString("\n")
	}
	return b.String()
}

func emitAlias(c *wrapper.Crate) string {
	var b strings.Builder
	writeHeader(&b, c, "alias module")
	b.WriteString("\n")
	for _, fn := range c.Functions {
		b.WriteString(emitAliasFn(fn))
		b.WriteString("\n")
	}
	return b.String()
}

func writeHeader(b *strings.Builder, c *wrapper.Crate, kind string) {
	b.WriteString("// ")
	b.WriteString(kind)
	b.WriteString(" for ")
	b.WriteString(c.Upstream)
	b.WriteString(" ")
	b.WriteString(c.UpstreamVersion)
	b.WriteString("\n")
	b.WriteString("// generated by mochi/package3/rust/emit; do not edit.\n")
}

func emitExternFn(fn wrapper.SynthFn) string {
	var b strings.Builder
	b.WriteString("extern fun ")
	b.WriteString(fn.ExternName)
	b.WriteString("(")
	parts := make([]string, 0, len(fn.Params))
	for _, p := range fn.Params {
		parts = append(parts, fmt.Sprintf("%s: %s", p.Name, MochiRender(p.Mapping)))
	}
	b.WriteString(strings.Join(parts, ", "))
	b.WriteString(")")
	if fn.Return != nil {
		b.WriteString(": ")
		b.WriteString(MochiRender(*fn.Return))
	}
	b.WriteString("\n")
	return b.String()
}

// emitAliasFn renders the user-facing re-export. The alias is the
// last segment of the upstream rustdoc path (e.g. "encode" rather
// than "hex::encode"), and the body forwards positionally to the
// extern symbol.
func emitAliasFn(fn wrapper.SynthFn) string {
	short := shortName(fn.UpstreamPath)
	var b strings.Builder
	b.WriteString("fun ")
	b.WriteString(short)
	b.WriteString("(")
	parts := make([]string, 0, len(fn.Params))
	args := make([]string, 0, len(fn.Params))
	for _, p := range fn.Params {
		parts = append(parts, fmt.Sprintf("%s: %s", p.Name, MochiRender(p.Mapping)))
		args = append(args, p.Name)
	}
	b.WriteString(strings.Join(parts, ", "))
	b.WriteString(")")
	if fn.Return != nil {
		b.WriteString(": ")
		b.WriteString(MochiRender(*fn.Return))
	}
	b.WriteString(" {\n")
	call := fmt.Sprintf("%s(%s)", fn.ExternName, strings.Join(args, ", "))
	if fn.Return != nil {
		b.WriteString("  return ")
		b.WriteString(call)
		b.WriteString("\n")
	} else {
		b.WriteString("  ")
		b.WriteString(call)
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// collectTypeNames walks every Mapping in the crate and returns the
// sorted, deduplicated list of user-defined struct / enum / handle
// names that need a top-level `extern type` declaration.
func collectTypeNames(c *wrapper.Crate) []string {
	seen := map[string]struct{}{}
	for _, fn := range c.Functions {
		for _, p := range fn.Params {
			for _, n := range typeNames(p.Mapping) {
				seen[n] = struct{}{}
			}
		}
		if fn.Return != nil {
			for _, n := range typeNames(*fn.Return) {
				seen[n] = struct{}{}
			}
		}
	}
	out := make([]string, 0, len(seen))
	for n := range seen {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

func hasAnyTypeName(c *wrapper.Crate) bool {
	for _, fn := range c.Functions {
		for _, p := range fn.Params {
			if len(typeNames(p.Mapping)) > 0 {
				return true
			}
		}
		if fn.Return != nil && len(typeNames(*fn.Return)) > 0 {
			return true
		}
	}
	return false
}

// shortName returns the last "::"-separated segment of an upstream
// path. Used as the user-facing function name in the alias module.
func shortName(p string) string {
	i := strings.LastIndex(p, "::")
	if i < 0 {
		return p
	}
	return p[i+2:]
}

