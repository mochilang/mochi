// Package asyncbridge owns the MEP-73 Phase 11 async bridge: the
// process-wide tokio runtime singleton and the per-async-fn
// `block_on` wrapper body emitter. When an upstream crate exposes
// `async fn` items, the wrapper crate the bridge synthesises
// (package3/rust/wrapper) needs three pieces:
//
//  1. A `mochi_rt.rs` module that constructs a tokio runtime via
//     OnceCell on first use and exposes a `get_rt()` accessor.
//  2. A per-fn extern "C" wrapper whose body calls
//     `mochi_rt::get_rt().block_on(async { <upstream>(<args>).await })`.
//  3. A tokio dependency entry in the wrapper's Cargo.toml with
//     features matching `[rust.runtime] flavor` in mochi.toml.
//
// This package owns the deterministic text shape of (1), (2), and the
// Cargo.toml fragment for (3). The wrapper package calls into here
// at synth time; the build pipeline picks up the resulting tokio dep
// row when rendering Cargo.toml.
//
// The bridge is opt-out only: a crate that exposes no async-fn items
// produces no `mochi_rt.rs` and no tokio dep, so pure-sync crate
// imports pay zero compile-time and zero runtime cost. Importing any
// async-fn-exposing crate pulls the full tokio runtime into the
// final binary (the standard cost of any tokio-using Rust program).
package asyncbridge

import (
	"fmt"
	"strings"
)

// Flavor is the tokio runtime flavor. The default is current-thread to
// match MEP-53's single-thread principle; users opt into multi-thread
// via `[rust.runtime] flavor = "multi-thread"` in mochi.toml.
type Flavor int

const (
	// FlavorCurrentThread is `Builder::new_current_thread()`. Default.
	FlavorCurrentThread Flavor = iota
	// FlavorMultiThread is `Builder::new_multi_thread()`. Opt-in.
	FlavorMultiThread
)

// String implements fmt.Stringer.
func (f Flavor) String() string {
	switch f {
	case FlavorCurrentThread:
		return "current-thread"
	case FlavorMultiThread:
		return "multi-thread"
	default:
		return "unknown"
	}
}

// ParseFlavor maps the user-facing manifest string to a Flavor. Empty
// input defaults to FlavorCurrentThread. Unknown input returns an error.
func ParseFlavor(s string) (Flavor, error) {
	switch strings.TrimSpace(s) {
	case "", "current-thread":
		return FlavorCurrentThread, nil
	case "multi-thread":
		return FlavorMultiThread, nil
	default:
		return 0, fmt.Errorf("asyncbridge: unknown flavor %q (expected current-thread or multi-thread)", s)
	}
}

// TokioFeatures returns the cargo feature set the wrapper Cargo.toml
// must enable for the chosen flavor. Both flavors always need the
// `rt` and `macros` features; the multi-thread flavor additionally
// needs `rt-multi-thread`.
func (f Flavor) TokioFeatures() []string {
	switch f {
	case FlavorMultiThread:
		return []string{"rt", "rt-multi-thread", "macros"}
	default:
		return []string{"rt", "macros"}
	}
}

// MinTokioVersion is the floor version that ships
// `Builder::new_current_thread` + `Builder::new_multi_thread` + the
// stabilised `Runtime::block_on` signature the bridge depends on.
const MinTokioVersion = "1.42"

// RuntimeModule is the verbatim `mochi_rt.rs` body the wrapper crate
// includes when any synthesised function is async. The body matches
// the spec text at MEP-73 §3 (Async bridge): a single OnceCell
// Runtime, a lazy `get_rt()` accessor, and a `block_on` helper that
// hides the panic-on-poisoned-once-cell from per-fn bodies.
func RuntimeModule(f Flavor) string {
	builder := "tokio::runtime::Builder::new_current_thread()"
	if f == FlavorMultiThread {
		builder = "tokio::runtime::Builder::new_multi_thread()"
	}
	return fmt.Sprintf(`// Auto-generated by mochi/package3/rust/asyncbridge. Do not edit.
//
// Process-wide tokio runtime singleton. Constructed lazily on first
// async-fn call. Built with %s
// to match the [rust.runtime] flavor declared in mochi.toml.
use once_cell::sync::OnceCell;
use tokio::runtime::Runtime;

static MOCHI_RT: OnceCell<Runtime> = OnceCell::new();

pub fn get_rt() -> &'static Runtime {
    MOCHI_RT.get_or_init(|| {
        %s
            .enable_all()
            .build()
            .expect("mochi: failed to construct tokio runtime")
    })
}

#[inline]
pub fn block_on<F: core::future::Future>(fut: F) -> F::Output {
    get_rt().block_on(fut)
}
`, f, builder)
}

// FnBody renders the `extern "C" fn` body for an async upstream
// function. `upstreamPath` is the fully-qualified Rust path of the
// async fn (e.g. "tokio::time::sleep"); `args` is the in-order list
// of already-marshalled local bindings to pass through.
//
// The emitted body is:
//
//     mochi_rt::block_on(async { <upstream>(<args>).await })
//
// Callers (the wrapper package) marshal scalar / string inputs into
// `args` exactly as they do for sync fns; the only difference is the
// `.await` hop inside the `block_on` closure.
func FnBody(upstreamPath string, args []string) string {
	if upstreamPath == "" {
		return ""
	}
	return fmt.Sprintf("mochi_rt::block_on(async { %s(%s).await })", upstreamPath, strings.Join(args, ", "))
}

// CargoDepRow renders the wrapper-crate Cargo.toml `[dependencies]`
// row for the tokio dep. The row pins MinTokioVersion as the floor;
// callers compose it into the wrapper Cargo.toml renderer when the
// crate contains at least one async fn. The features list is sorted
// for byte-stable output.
func CargoDepRow(f Flavor) string {
	features := f.TokioFeatures()
	quoted := make([]string, len(features))
	for i, ft := range features {
		quoted[i] = fmt.Sprintf("%q", ft)
	}
	return fmt.Sprintf("tokio = { version = \"^%s\", features = [%s] }",
		MinTokioVersion, strings.Join(quoted, ", "))
}

// OnceCellDepRow renders the `once_cell` dep row the runtime module
// needs for the OnceCell-based runtime singleton.
func OnceCellDepRow() string {
	return `once_cell = "^1.20"`
}
