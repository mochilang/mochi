package emit

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// MochiFunction describes one exported Mochi function to expose as a NuGet library.
type MochiFunction struct {
	Name       string
	ParamTypes []string // Mochi type names e.g. "int64", "string"
	ReturnType string   // Mochi type name; "" means void
}

// MochiPackage describes a Mochi package being published as a NuGet library.
type MochiPackage struct {
	PackageID string
	Version   string
	Functions []MochiFunction
}

// EmitNuGetLibrary writes a NuGet-publishable C# project from a MochiPackage.
// The output layout under outDir:
//
//	<PackageId>/
//	  <PackageId>.csproj      — net8.0;net10.0, PublishAot=true, NativeLib=Static
//	  src/
//	    MochiExports.cs       — [UnmanagedCallersOnly] exports for each function
//	  <PackageId>.nuspec      — NuGet package manifest
func EmitNuGetLibrary(pkg *MochiPackage, outDir string) error {
	pkgDir := filepath.Join(outDir, pkg.PackageID)
	srcDir := filepath.Join(pkgDir, "src")
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		return fmt.Errorf("emit: mkdir: %w", err)
	}

	// Write .csproj
	csproj := emitLibraryCsproj(pkg)
	if err := os.WriteFile(filepath.Join(pkgDir, pkg.PackageID+".csproj"), []byte(csproj), 0o644); err != nil {
		return fmt.Errorf("emit: write csproj: %w", err)
	}

	// Write MochiExports.cs
	exports := emitExportsCS(pkg)
	if err := os.WriteFile(filepath.Join(srcDir, "MochiExports.cs"), []byte(exports), 0o644); err != nil {
		return fmt.Errorf("emit: write MochiExports.cs: %w", err)
	}

	// Write .nuspec
	nuspec := emitNuspec(pkg)
	if err := os.WriteFile(filepath.Join(pkgDir, pkg.PackageID+".nuspec"), []byte(nuspec), 0o644); err != nil {
		return fmt.Errorf("emit: write nuspec: %w", err)
	}

	return nil
}

func emitLibraryCsproj(pkg *MochiPackage) string {
	return fmt.Sprintf(`<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <AssemblyName>%s</AssemblyName>
    <TargetFrameworks>net8.0;net10.0</TargetFrameworks>
    <PublishAot>true</PublishAot>
    <NativeLib>Static</NativeLib>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <Nullable>enable</Nullable>
    <Version>%s</Version>
  </PropertyGroup>
</Project>
`, pkg.PackageID, pkg.Version)
}

func emitExportsCS(pkg *MochiPackage) string {
	var b strings.Builder
	b.WriteString("using System.Runtime.InteropServices;\n\n")
	b.WriteString("// Generated by mochi/package3/dotnet/emit; do not edit.\n")
	b.WriteString("namespace Mochi.Exports;\n\n")
	b.WriteString("public static class MochiExports\n{\n")
	for _, fn := range pkg.Functions {
		b.WriteString("    [UnmanagedCallersOnly]\n")
		csRet := mochiTypeToCSharp(fn.ReturnType)
		b.WriteString(fmt.Sprintf("    public static %s %s(", csRet, fn.Name))
		for i, pt := range fn.ParamTypes {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(fmt.Sprintf("%s p%d", mochiTypeToCSharp(pt), i))
		}
		b.WriteString(")\n    {\n")
		b.WriteString("        throw new NotImplementedException();\n")
		b.WriteString("    }\n\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func emitNuspec(pkg *MochiPackage) string {
	return fmt.Sprintf(`<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://schemas.microsoft.com/packaging/2013/05/nuspec.xsd">
  <metadata>
    <id>%s</id>
    <version>%s</version>
    <description>Mochi package %s exported as a NuGet library.</description>
    <authors>mochi</authors>
  </metadata>
</package>
`, pkg.PackageID, pkg.Version, pkg.PackageID)
}

// mochiTypeToCSharp maps Mochi type names to C# equivalents.
func mochiTypeToCSharp(mochiType string) string {
	switch mochiType {
	case "int", "int64":
		return "long"
	case "float", "float64":
		return "double"
	case "bool":
		return "bool"
	case "string":
		return "nint" // IntPtr for string pointer
	case "":
		return "void"
	default:
		return "nint"
	}
}
