// Package build is the TypeScript bridge workspace and bundler driver.
// Lands in MEP-72 Phase 8.
package build

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"mochi/package3/typescript/apisurface"
	"mochi/package3/typescript/typemap"
)

// Driver orchestrates the TypeScript bridge build.
type Driver struct {
	WorkDir string
	NodeBin string
	NpmBin  string
}

// BuildSpec describes a package to install and bridge.
type BuildSpec struct {
	PackageName string
	Version     string
	CacheDir    string
}

func (d *Driver) nodeBin() string {
	if d.NodeBin != "" {
		return d.NodeBin
	}
	return "node"
}

func (d *Driver) npmBin() string {
	if d.NpmBin != "" {
		return d.NpmBin
	}
	return "npm"
}

// PrepareWorkspace creates the workspace directory and package.json.
func (d *Driver) PrepareWorkspace(spec BuildSpec) error {
	if err := os.MkdirAll(d.WorkDir, 0o755); err != nil {
		return fmt.Errorf("build: mkdir workspace: %w", err)
	}
	pkgJSON := map[string]interface{}{
		"name":         "mochi-ts-bridge-workspace",
		"version":      "0.0.1",
		"type":         "module",
		"private":      true,
		"dependencies": map[string]string{spec.PackageName: spec.Version},
	}
	data, err := json.MarshalIndent(pkgJSON, "", "  ")
	if err != nil {
		return fmt.Errorf("build: marshal package.json: %w", err)
	}
	return os.WriteFile(filepath.Join(d.WorkDir, "package.json"), data, 0o644)
}

// InstallPackage runs npm install in the workspace.
func (d *Driver) InstallPackage(ctx context.Context, name, version string) error {
	pkg := name + "@" + version
	cmd := exec.CommandContext(ctx, d.npmBin(), "install", "--save-exact", pkg)
	cmd.Dir = d.WorkDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("build: npm install %s: %w\n%s", pkg, err, out)
	}
	return nil
}

// GenerateShim writes mochi_shim.mjs that re-exports wrapped functions.
func (d *Driver) GenerateShim(surface *apisurface.ApiSurface, mapped []typemap.MappedExport) error {
	var b strings.Builder
	b.WriteString("// mochi_shim.mjs — generated by mochi TypeScript bridge\n")
	fmt.Fprintf(&b, "import * as _pkg from %q;\n\n", surface.PackageName)
	for _, me := range mapped {
		if me.Skipped {
			continue
		}
		var paramNames []string
		for _, p := range me.Export.Params {
			paramNames = append(paramNames, p.Name)
		}
		params := strings.Join(paramNames, ", ")
		fmt.Fprintf(&b, "export function %s(%s) { return _pkg.%s(%s); }\n",
			me.MochiName, params, me.Export.Name, params)
	}
	return os.WriteFile(filepath.Join(d.WorkDir, "mochi_shim.mjs"), []byte(b.String()), 0o644)
}

// BuildNativeAddon compiles the N-API native addon and returns the .node path.
// Returns an error if node-gyp is not available; callers should fall back to
// the pure-JS shim path.
func (d *Driver) BuildNativeAddon(ctx context.Context) (string, error) {
	gypPath := filepath.Join(d.WorkDir, "binding.gyp")
	if err := os.WriteFile(gypPath, []byte(bindingGYP()), 0o644); err != nil {
		return "", fmt.Errorf("build: write binding.gyp: %w", err)
	}
	wrapperPath := filepath.Join(d.WorkDir, "mochi_napi.cpp")
	if err := os.WriteFile(wrapperPath, []byte(napiWrapper()), 0o644); err != nil {
		return "", fmt.Errorf("build: write napi wrapper: %w", err)
	}
	cmd := exec.CommandContext(ctx, d.nodeBin(), "-e", "require('node-gyp').cli.run()")
	cmd.Args = append(cmd.Args, "configure", "build", "--release")
	cmd.Dir = d.WorkDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("build: node-gyp build: %w\n%s", err, out)
	}
	nodePath := filepath.Join(d.WorkDir, "build", "Release", "mochi_napi.node")
	return nodePath, nil
}

func bindingGYP() string {
	return `{
  "targets": [{
    "target_name": "mochi_napi",
    "sources": ["mochi_napi.cpp"],
    "include_dirs": ["<!@(node -p \"require('node-addon-api').include\")"],
    "cflags!": ["-fno-exceptions"],
    "cflags_cc!": ["-fno-exceptions"]
  }]
}
`
}

func napiWrapper() string {
	return `// mochi_napi.cpp — N-API wrapper stub (MEP-72)
#include <napi.h>
Napi::Object Init(Napi::Env env, Napi::Object exports) { return exports; }
NODE_API_MODULE(mochi_napi, Init)
`
}
