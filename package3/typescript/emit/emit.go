// Package emit generates Mochi extern fn declarations and skip reports
// from a mapped TypeScript API surface. Lands in MEP-72 Phase 6.
package emit

import (
	"fmt"
	"os"
	"strings"

	"mochi/package3/typescript/apisurface"
	brerrors "mochi/package3/typescript/errors"
	"mochi/package3/typescript/typemap"
)

// EmitExterns writes a .mochi source file with extern fn declarations
// for all non-skipped exports.
func EmitExterns(surface *apisurface.ApiSurface, mapped []typemap.MappedExport, outPath string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// From npm package %q v%s\n", surface.PackageName, surface.Version)
	fmt.Fprintf(&b, "// Generated by mochi/package3/typescript/emit\n\n")

	for _, me := range mapped {
		if me.Skipped {
			continue
		}
		line := buildExternLine(me)
		b.WriteString(line)
		b.WriteByte('\n')
	}

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("emit: write externs %s: %w", outPath, err)
	}
	return nil
}

func buildExternLine(me typemap.MappedExport) string {
	var params []string
	for i, p := range me.Export.Params {
		var pt typemap.MapResult
		if i < len(me.ParamTypes) {
			pt = me.ParamTypes[i]
		}
		params = append(params, fmt.Sprintf("%s: %s", p.Name, renderType(pt)))
	}
	retStr := renderType(me.ReturnType)
	if len(params) == 0 {
		return fmt.Sprintf("extern ts fun %s(): %s", me.MochiName, retStr)
	}
	return fmt.Sprintf("extern ts fun %s(%s): %s", me.MochiName, strings.Join(params, ", "), retStr)
}

func renderType(r typemap.MapResult) string {
	switch r.Container {
	case "list":
		if len(r.Inner) > 0 {
			return fmt.Sprintf("list<%s>", r.Inner[0])
		}
		return "list<any>"
	case "map":
		if len(r.Inner) >= 2 {
			return fmt.Sprintf("map<%s, %s>", r.Inner[0], r.Inner[1])
		}
		return "map<any, any>"
	case "set":
		if len(r.Inner) > 0 {
			return fmt.Sprintf("set<%s>", r.Inner[0])
		}
		return "set<any>"
	case "option":
		if len(r.Inner) > 0 {
			return fmt.Sprintf("option[%s]", r.Inner[0])
		}
		return "option[any]"
	case "async":
		if len(r.Inner) > 0 {
			return fmt.Sprintf("async %s", r.Inner[0])
		}
		return "async unit"
	case "stream":
		if len(r.Inner) > 0 {
			return fmt.Sprintf("stream<%s>", r.Inner[0])
		}
		return "stream<any>"
	case "":
		if r.Type == "" {
			return "unit"
		}
		return string(r.Type)
	}
	return string(r.Type)
}

// EmitSkipped writes a SKIPPED.txt report.
func EmitSkipped(skipped []brerrors.SkipReport, outPath string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# TypeScript bridge: skipped exports\n")
	fmt.Fprintf(&b, "# Total: %d\n\n", len(skipped))
	for _, s := range skipped {
		line := fmt.Sprintf("%s\t%s", s.ItemPath, s.Reason)
		if s.Detail != "" {
			line += "\t" + s.Detail
		}
		b.WriteString(line)
		b.WriteByte('\n')
	}
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("emit: write skipped %s: %w", outPath, err)
	}
	return nil
}
