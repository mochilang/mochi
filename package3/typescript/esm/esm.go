// Package esm resolves ESM/CJS entry points from npm package.json exports maps.
// Lands in MEP-72 Phase 16.
package esm

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// EntryFormat classifies the module format.
type EntryFormat int

const (
	FormatESM  EntryFormat = iota
	FormatCJS
	FormatIIFE
)

func (f EntryFormat) String() string {
	switch f {
	case FormatESM:
		return "ESM"
	case FormatCJS:
		return "CJS"
	case FormatIIFE:
		return "IIFE"
	}
	return "unknown"
}

// EntryPoint is the resolved module entry point.
type EntryPoint struct {
	Path   string
	Format EntryFormat
}

type packageJSON struct {
	Name    string `json:"name"`
	Main    string `json:"main"`
	Module  string `json:"module"`
	Type    string `json:"type"`
	Exports json.RawMessage `json:"exports"`
}

// ResolveEntryPoint resolves the correct entry point for a package in pkgDir.
// Algorithm:
//  1. Check exports["."] for ESM (import) or CJS (require) condition.
//  2. Fallback to "module" field (ESM).
//  3. Fallback to "main" field (CJS).
func ResolveEntryPoint(pkgDir string) (EntryPoint, error) {
	data, err := os.ReadFile(filepath.Join(pkgDir, "package.json"))
	if err != nil {
		return EntryPoint{}, fmt.Errorf("esm: read package.json in %s: %w", pkgDir, err)
	}
	var pkg packageJSON
	if err := json.Unmarshal(data, &pkg); err != nil {
		return EntryPoint{}, fmt.Errorf("esm: parse package.json: %w", err)
	}

	// Try exports map.
	if len(pkg.Exports) > 0 {
		ep, err := resolveExports(pkg.Exports, pkgDir, pkg.Type == "module")
		if err == nil {
			return ep, nil
		}
	}

	// Fallback to "module" (ESM).
	if pkg.Module != "" {
		return EntryPoint{Path: filepath.Join(pkgDir, pkg.Module), Format: FormatESM}, nil
	}

	// Fallback to "main" (CJS or ESM based on type field).
	if pkg.Main != "" {
		format := FormatCJS
		if pkg.Type == "module" {
			format = FormatESM
		}
		return EntryPoint{Path: filepath.Join(pkgDir, pkg.Main), Format: format}, nil
	}

	// Default: index.js
	format := FormatCJS
	if pkg.Type == "module" {
		format = FormatESM
	}
	return EntryPoint{Path: filepath.Join(pkgDir, "index.js"), Format: format}, nil
}

func resolveExports(raw json.RawMessage, pkgDir string, isESM bool) (EntryPoint, error) {
	// exports can be: string, { ".": string }, { ".": { import: ..., require: ... } }
	var s string
	if err := json.Unmarshal(raw, &s); err == nil {
		format := FormatCJS
		if isESM || strings.HasSuffix(s, ".mjs") {
			format = FormatESM
		}
		return EntryPoint{Path: filepath.Join(pkgDir, s), Format: format}, nil
	}

	var obj map[string]json.RawMessage
	if err := json.Unmarshal(raw, &obj); err != nil {
		return EntryPoint{}, fmt.Errorf("esm: parse exports: %w", err)
	}

	dotExport, ok := obj["."]
	if !ok {
		return EntryPoint{}, fmt.Errorf("esm: no '.' export")
	}

	// dotExport can be a string or conditions map.
	var dotStr string
	if err := json.Unmarshal(dotExport, &dotStr); err == nil {
		format := FormatCJS
		if isESM || strings.HasSuffix(dotStr, ".mjs") {
			format = FormatESM
		}
		return EntryPoint{Path: filepath.Join(pkgDir, dotStr), Format: format}, nil
	}

	var conditions map[string]string
	if err := json.Unmarshal(dotExport, &conditions); err != nil {
		return EntryPoint{}, fmt.Errorf("esm: parse dot export conditions: %w", err)
	}

	// Prefer "import" (ESM) over "require" (CJS).
	if imp, ok := conditions["import"]; ok {
		return EntryPoint{Path: filepath.Join(pkgDir, imp), Format: FormatESM}, nil
	}
	if req, ok := conditions["require"]; ok {
		return EntryPoint{Path: filepath.Join(pkgDir, req), Format: FormatCJS}, nil
	}
	if def, ok := conditions["default"]; ok {
		format := FormatCJS
		if strings.HasSuffix(def, ".mjs") {
			format = FormatESM
		}
		return EntryPoint{Path: filepath.Join(pkgDir, def), Format: format}, nil
	}

	return EntryPoint{}, fmt.Errorf("esm: no usable condition in '.' export")
}

// WrapCJSForESM generates an ESM wrapper for a CJS entry point.
func WrapCJSForESM(cjsPath, outPath string) error {
	var b strings.Builder
	b.WriteString("// ESM wrapper for CJS module — generated by mochi/package3/typescript/esm\n")
	fmt.Fprintf(&b, "import { createRequire } from 'module';\n")
	fmt.Fprintf(&b, "const require = createRequire(import.meta.url);\n")
	fmt.Fprintf(&b, "const mod = require(%q);\n", cjsPath)
	b.WriteString("export default mod;\n")
	b.WriteString("export const { ...named } = mod;\n")
	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}
