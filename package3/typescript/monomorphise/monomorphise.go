// Package monomorphise generates concrete TypeScript shims for generic call sites.
// Lands in MEP-72 Phase 15.
package monomorphise

import (
	"fmt"
	"os"
	"strings"
)

// CallSite is one use of a generic TypeScript function with concrete type args.
type CallSite struct {
	FuncName string
	Module   string
	TypeArgs []string // e.g. ["string", "number"]
}

// ConcreteFunc is the result of expanding one generic call site.
type ConcreteFunc struct {
	MangledName string // e.g. "ts_pkg_wrap_string"
	OrigName    string
	Module      string
	TypeArgs    []string
	IsSkipped   bool
	SkipReason  string
}

var typeMap = map[string]string{
	"string":  "string",
	"number":  "number",
	"boolean": "boolean",
	"bigint":  "bigint",
	"int":     "number",
	"float":   "number",
	"bool":    "boolean",
}

// MonomorphiseAll expands all call sites into concrete function specs.
func MonomorphiseAll(sites []CallSite) ([]ConcreteFunc, error) {
	var out []ConcreteFunc
	for _, site := range sites {
		f, err := monomorphise(site)
		if err != nil {
			return nil, err
		}
		out = append(out, f)
	}
	return out, nil
}

func monomorphise(site CallSite) (ConcreteFunc, error) {
	f := ConcreteFunc{
		OrigName: site.FuncName,
		Module:   site.Module,
		TypeArgs: site.TypeArgs,
	}

	var suffixes []string
	for _, ta := range site.TypeArgs {
		mapped, ok := typeMap[strings.ToLower(ta)]
		if !ok {
			f.IsSkipped = true
			f.SkipReason = fmt.Sprintf("unsupported type argument %q", ta)
			f.MangledName = mangledName(site)
			return f, nil
		}
		suffixes = append(suffixes, tsTypeToSuffix(mapped))
	}

	f.MangledName = mangledName(site) + "_" + strings.Join(suffixes, "_")
	return f, nil
}

func mangledName(site CallSite) string {
	mod := strings.ReplaceAll(site.Module, "/", "_")
	mod = strings.ReplaceAll(mod, "@", "")
	mod = strings.ReplaceAll(mod, "-", "_")
	return "ts_" + mod + "_" + site.FuncName
}

func tsTypeToSuffix(ts string) string {
	switch ts {
	case "string":
		return "String"
	case "number":
		return "Number"
	case "boolean":
		return "Boolean"
	case "bigint":
		return "BigInt"
	default:
		return strings.Title(ts)
	}
}

// EmitMonomorphicShims writes concrete wrapper functions to outPath.
func EmitMonomorphicShims(funcs []ConcreteFunc, origModule string, outPath string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Monomorphic shims for %s — generated by mochi/package3/typescript/monomorphise\n\n", origModule)
	fmt.Fprintf(&b, "import * as _pkg from %q;\n\n", origModule)

	for _, f := range funcs {
		if f.IsSkipped {
			fmt.Fprintf(&b, "// SKIP %s: %s\n", f.MangledName, f.SkipReason)
			continue
		}
		var typeArgStr string
		if len(f.TypeArgs) > 0 {
			typeArgStr = "<" + strings.Join(f.TypeArgs, ", ") + ">"
		}
		fmt.Fprintf(&b, "export function %s(...args) { return _pkg.%s%s(...args); }\n",
			f.MangledName, f.OrigName, typeArgStr)
	}

	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}
