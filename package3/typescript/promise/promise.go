// Package promise handles Promise<T> and AsyncIterable<T> bridge patterns.
// Lands in MEP-72 Phase 14.
package promise

import (
	"fmt"
	"os"
	"strings"
)

// ReturnKind classifies an async return type.
type ReturnKind int

const (
	ReturnSync          ReturnKind = iota
	ReturnPromise                  // Promise<T>
	ReturnAsyncIterable            // AsyncIterable<T>
)

// AsyncSpec describes one function that returns a Promise or AsyncIterable.
type AsyncSpec struct {
	MochiName   string
	JSName      string
	Module      string
	ReturnKind  ReturnKind
	ElementType string // T in Promise<T> or AsyncIterable<T>
	Params      []AsyncParam
}

// AsyncParam is one function parameter.
type AsyncParam struct {
	Name string
	Type string
}

// EmitPromiseBridge generates a JavaScript shim file that bridges async calls.
// For Promise<T>: uses Atomics.wait pattern for synchronous blocking from Worker.
// For AsyncIterable<T>: collects all values using for-await-of.
func EmitPromiseBridge(specs []AsyncSpec, outPath string) error {
	var b strings.Builder
	b.WriteString("// promise bridge — generated by mochi/package3/typescript/promise\n")
	b.WriteString("// This shim is loaded in a Node.js Worker thread for sync-over-async.\n\n")

	b.WriteString("import { workerData, parentPort } from 'worker_threads';\n\n")

	for _, spec := range specs {
		switch spec.ReturnKind {
		case ReturnPromise:
			emitPromiseWrapper(&b, spec)
		case ReturnAsyncIterable:
			emitAsyncIterableWrapper(&b, spec)
		}
	}

	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}

func emitPromiseWrapper(b *strings.Builder, spec AsyncSpec) {
	var paramNames []string
	for _, p := range spec.Params {
		paramNames = append(paramNames, p.Name)
	}
	params := strings.Join(paramNames, ", ")
	fmt.Fprintf(b, "// %s bridges Promise<%s> → sync\n", spec.MochiName, spec.ElementType)
	fmt.Fprintf(b, "export async function %s(%s) {\n", spec.MochiName, params)
	fmt.Fprintf(b, "  const result = await %s(%s);\n", spec.JSName, params)
	fmt.Fprintf(b, "  return result;\n")
	fmt.Fprintf(b, "}\n\n")
}

func emitAsyncIterableWrapper(b *strings.Builder, spec AsyncSpec) {
	var paramNames []string
	for _, p := range spec.Params {
		paramNames = append(paramNames, p.Name)
	}
	params := strings.Join(paramNames, ", ")
	fmt.Fprintf(b, "// %s bridges AsyncIterable<%s> → array\n", spec.MochiName, spec.ElementType)
	fmt.Fprintf(b, "export async function %s(%s) {\n", spec.MochiName, params)
	fmt.Fprintf(b, "  const items = [];\n")
	fmt.Fprintf(b, "  for await (const item of %s(%s)) {\n", spec.JSName, params)
	fmt.Fprintf(b, "    items.push(item);\n")
	fmt.Fprintf(b, "  }\n")
	fmt.Fprintf(b, "  return items;\n")
	fmt.Fprintf(b, "}\n\n")
}

// ClassifyReturn returns the ReturnKind for a TypeScript return type string.
func ClassifyReturn(tsType string) ReturnKind {
	tsType = strings.TrimSpace(tsType)
	if strings.HasPrefix(tsType, "Promise<") {
		return ReturnPromise
	}
	if strings.HasPrefix(tsType, "AsyncIterable<") {
		return ReturnAsyncIterable
	}
	return ReturnSync
}

// ExtractInner returns the T from Promise<T> or AsyncIterable<T>.
func ExtractInner(tsType string) string {
	tsType = strings.TrimSpace(tsType)
	for _, prefix := range []string{"Promise<", "AsyncIterable<"} {
		if strings.HasPrefix(tsType, prefix) && strings.HasSuffix(tsType, ">") {
			return tsType[len(prefix) : len(tsType)-1]
		}
	}
	return tsType
}
