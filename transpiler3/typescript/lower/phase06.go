// Phase 6 closures and higher-order functions.
//
// Mochi has a uniform first-class fun surface: `fun(x: int): int =>
// x * 2` is an expression of type `fun(int): int`. The aotir IR
// closure-converts every such expression into a lifted top-level
// `aotir.Function` (named `__anon_<n>` by the C lowerer) plus a
// `FunLit` node that names it. Capturing closures additionally
// carry a `FunCapture` list and the C lowerer emits a
// `ClosureEnvStmt` that allocates the env struct.
//
// The TypeScript transpiler does NOT inherit any of that scaffolding.
// JavaScript closures close over their enclosing lexical scope for
// free, so:
//
//   - Lifted `__anon_<n>` functions are not emitted as top-level
//     TypeScript functions. Instead, every `FunLit` site inlines
//     the lifted function's body as an arrow expression `(...) => {
//     ... }` directly in place. The user-visible TS source therefore
//     keeps the function literal at its source location, which also
//     matches a hand-written TS closure.
//
//   - `ClosureEnvStmt` is dropped entirely (it has no TypeScript
//     surface). The C lowerer emits one of these immediately before
//     each capturing FunLit so the C output can `malloc` the env
//     struct; the TS lowerer treats it as a no-op statement.
//
//   - Free-variable references inside the lifted body carry the
//     literal name `__e->X` in `VarRef.Name` (the C lowerer
//     rewrites the identifier into env-struct access at lower time).
//     When the TS lowerer walks the inlined body it strips the
//     `__e->` prefix so the identifier becomes a bare `X`, which
//     resolves through JS lexical scope back to the captured
//     variable in the enclosing function.
//
//   - `__shim_<name>` wrappers (Phase 5.2: a bare function name
//     used as a fun-typed value) are also elided. The shim's only
//     job is to fit the C closure ABI; in TS a regular function
//     binding `mochi__foo` is already a first-class value, so
//     `FunLit{FuncName: "__shim_foo"}` lowers to the bare ident
//     `mochi__foo`. No shim function is emitted.
//
//   - `FunCallExpr{Callee, Args}` lowers to a TS call expression
//     `callee(args)`. When the callee is an ArrowExpr literal
//     (rare in practice but the IR permits it), the printer wraps
//     it in parens so the leading `(` of the arrow doesn't get
//     misread as a grouping operator on its own.
//
// Type rendering for `TypeFun` slots follows the TS function-type
// syntax `(p0: T0, p1: T1) => R`. A `void`-returning closure renders
// as `(p0: T0) => void`. The lowerer always emits the full
// annotation, never an implicit `any`-typed slot, so `tsc --strict`
// can prove the call sites without inference.
package lower

import (
	"fmt"
	"strings"

	"mochi/transpiler3/c/aotir"
	"mochi/transpiler3/typescript/tstree"
)

// shimEnvPrefix is the captured-name prefix the C lowerer stamps
// into VarRef.Name for variables read through the env struct. The TS
// lowerer strips it so the identifier resolves via lexical scope.
const shimEnvPrefix = "__e->"

// stripEnvPrefix removes the C lowerer's `__e->` capture prefix
// from a VarRef.Name. Names without the prefix are returned
// unchanged. The result is the original Mochi-source identifier,
// which is already a valid TS identifier (the parser rejects
// non-identifier names earlier in the pipeline).
func stripEnvPrefix(name string) string {
	return strings.TrimPrefix(name, shimEnvPrefix)
}

// isLiftedFuncName reports whether n was generated by the C
// lowerer's closure-conversion pass: __anon_<n> for anonymous
// closure bodies, __shim_<name> for free-function references taken
// as fun-typed values. Both are filtered out of the top-level
// emit pass and reconstructed inline by the FunLit lowering.
func isLiftedFuncName(n string) bool {
	return strings.HasPrefix(n, "__anon_") || strings.HasPrefix(n, "__shim_")
}

// shimDelegate returns the underlying named function that a
// __shim_<name> wrapper forwards to. Its body is always a single
// `return mochi__<name>(args)` (or `mochi__<name>(args)` for void
// shims), so the TS side can skip the wrapper entirely and use
// `mochi__<name>` as the first-class value.
func shimDelegate(shimName string) string {
	suffix := strings.TrimPrefix(shimName, "__shim_")
	return "mochi__" + suffix
}

// tsTypeForFunSig renders a fun signature as the TS arrow-function
// type `(p0: T0, p1: T1) => R`. A zero-param signature renders as
// `() => R`. The renderer rejects non-scalar parameter and return
// types (Phase 5.0 IR contract); when later sub-phases widen the
// FunSig to records / lists / etc., this renderer will need the
// same side-channel arguments as tsTypeForLetSlot.
func tsTypeForFunSig(sig *aotir.FunSig) (string, error) {
	if sig == nil {
		return "", fmt.Errorf("ts lower: nil FunSig in TypeFun slot")
	}
	parts := make([]string, len(sig.ParamTypes))
	for i, pt := range sig.ParamTypes {
		ts, err := tsTypeFor(pt)
		if err != nil {
			return "", fmt.Errorf("ts lower: fun sig param %d: %w", i, err)
		}
		parts[i] = fmt.Sprintf("__p%d: %s", i, ts)
	}
	ret, err := tsTypeFor(sig.ReturnType)
	if err != nil {
		return "", fmt.Errorf("ts lower: fun sig return: %w", err)
	}
	return "(" + strings.Join(parts, ", ") + ") => " + ret, nil
}

// lowerFunLit converts an aotir FunLit (an anonymous closure
// literal) into a TS arrow expression. The lifted function's body
// is looked up by name in prog.Functions and lowered as if it were
// being inlined here; `__e->X` capture references are rewritten to
// bare `X` so JS lexical scope picks them up from the enclosing
// function's locals.
//
// For __shim_<name> wrappers the result is the bare identifier
// `mochi__<name>` (no arrow allocation). This matches the C
// lowerer's contract that __shim_* only exists to satisfy the C
// fat-pointer ABI; TS doesn't have one, so the wrapper is dead
// weight.
func (l *lowerer) lowerFunLit(e *aotir.FunLit) (tstree.Expr, error) {
	if e == nil {
		return nil, fmt.Errorf("ts lower: nil FunLit")
	}
	if strings.HasPrefix(e.FuncName, "__shim_") {
		return &tstree.IdentExpr{Name: shimDelegate(e.FuncName)}, nil
	}
	fn, ok := l.liftedByName[e.FuncName]
	if !ok {
		return nil, fmt.Errorf("ts lower: FunLit refers to unknown lifted function %q", e.FuncName)
	}
	if fn.Body == nil {
		return nil, fmt.Errorf("ts lower: lifted function %q has nil Body", fn.Name)
	}
	params := make([]tstree.FuncParam, 0, len(fn.Params))
	for _, p := range fn.Params {
		tn, err := paramType(p)
		if err != nil {
			return nil, fmt.Errorf("ts lower: closure %q param %q: %w", fn.Name, p.Name, err)
		}
		params = append(params, tstree.FuncParam{Name: p.Name, Type: tn})
	}
	ret, err := returnType(fn)
	if err != nil {
		return nil, fmt.Errorf("ts lower: closure %q return: %w", fn.Name, err)
	}
	body, err := l.lowerBlock(fn.Body.Statements)
	if err != nil {
		return nil, fmt.Errorf("ts lower: closure %q body: %w", fn.Name, err)
	}
	return &tstree.ArrowExpr{
		Params:     params,
		ReturnType: ret,
		Body:       body,
	}, nil
}

// lowerFunCallExpr converts an aotir FunCallExpr (calling a
// fun-typed value) into a TS CallExpr. When the callee is itself
// an arrow literal the expression is wrapped in a ParenExpr so the
// emitted text is `((x) => ...)(args)` rather than the ambiguous
// `(x) => ...(args)` (which TS would parse as the arrow's body
// being the call).
func (l *lowerer) lowerFunCallExpr(e *aotir.FunCallExpr) (tstree.Expr, error) {
	if e == nil {
		return nil, fmt.Errorf("ts lower: nil FunCallExpr")
	}
	callee, err := l.lowerExpr(e.Callee)
	if err != nil {
		return nil, fmt.Errorf("ts lower: FunCallExpr callee: %w", err)
	}
	if _, ok := callee.(*tstree.ArrowExpr); ok {
		callee = &tstree.ParenExpr{Inner: callee}
	}
	args := make([]tstree.Expr, 0, len(e.Args))
	for i, a := range e.Args {
		la, err := l.lowerExpr(a)
		if err != nil {
			return nil, fmt.Errorf("ts lower: FunCallExpr arg %d: %w", i, err)
		}
		args = append(args, la)
	}
	return &tstree.CallExpr{Callee: callee, Args: args}, nil
}

// lowerClosureEnvStmt drops the env-allocation statement entirely.
// The C lowerer needs it to malloc the env struct before a
// capturing FunLit; JS does not have an env struct, so the
// statement has no TS surface. Returning an empty slice keeps the
// surrounding block in source order.
func (l *lowerer) lowerClosureEnvStmt(_ *aotir.ClosureEnvStmt) ([]tstree.Stmt, error) {
	return nil, nil
}

// returnType renders a function's declared return type, threading
// the side-channel information through tsTypeForLetSlot. This is a
// small wrapper used by both lowerFunction (Phase 2) and
// lowerFunLit (Phase 6) so the rules stay in one place.
func returnType(fn *aotir.Function) (string, error) {
	if fn.ReturnType == aotir.TypeFun {
		return tsTypeForFunSig(fn.ReturnFunSig)
	}
	return tsTypeForLetSlot(fn.ReturnType, fn.ReturnElemType, fn.ReturnKeyType, fn.ReturnValueType, fn.ReturnRecordName, fn.ReturnElemRecordName, fn.ReturnUnionName)
}
