// TestPhase1HelloNode is the Phase 1 primary gate: every fixture
// under tests/transpiler3/typescript/fixtures/phase01-hello must
// lower via the TS transpiler and produce byte-equal stdout when
// executed under Node 22 (which supports `.ts` natively via
// --experimental-strip-types since 22.6, default-on since 22.18).
func TestPhase1HelloNode(t *testing.T) {
	runPhase1FixturesOn(t, "node")
}

// TestPhase1HelloDeno is the Phase 1 Deno gate. Deno 2.x runs
// `.ts` natively. Skipped when `deno` is missing on PATH.
func TestPhase1HelloDeno(t *testing.T) {
	runPhase1FixturesOn(t, "deno")
}

// TestPhase1HelloBun is the Phase 1 Bun gate. Bun 1.x runs `.ts`
// natively. Skipped when `bun` is missing on PATH.
func TestPhase1HelloBun(t *testing.T) {
	runPhase1FixturesOn(t, "bun")
}

func runPhase1FixturesOn(t *testing.T, runtime string) {
	t.Helper()
	fixtureDir := filepath.Join(repoRoot(t), "tests", "transpiler3", "typescript", "fixtures", "phase01-hello")
	entries, err := os.ReadDir(fixtureDir)
	if err != nil {
		t.Fatalf("ReadDir %s: %v", fixtureDir, err)
	}
	if len(entries) == 0 {
		t.Fatalf("Phase 1 fixture dir %s is empty", fixtureDir)
	}
	mochiCount := 0
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".mochi") {
			continue
		}
		mochiCount++
		name := strings.TrimSuffix(e.Name(), ".mochi")
		t.Run(name, func(t *testing.T) {
			runTsFixture(t, runtime,
				filepath.Join(fixtureDir, e.Name()),
				filepath.Join(fixtureDir, name+".out"))
		})
	}
	if mochiCount == 0 {
		t.Fatalf("Phase 1 fixture dir %s has no .mochi files", fixtureDir)
	}
}

// TestPhase1EmitWithoutRuntime confirms that the lowerer +
// emit pass produce a syntactically plausible mochi_print_str
// TS body for the canonical hello fixture even when no JS
// runtime is installed. This isolates the Go-side pipeline
// from the runtime gate above.
func TestPhase1EmitWithoutRuntime(t *testing.T) {
	fixtureDir := filepath.Join(repoRoot(t), "tests", "transpiler3", "typescript", "fixtures", "phase01-hello")
	mochiPath := filepath.Join(fixtureDir, "hello.mochi")
	if _, err := os.Stat(mochiPath); err != nil {
		t.Skipf("hello.mochi missing: %v", err)
	}
	outDir := t.TempDir()
	d := &Driver{CacheDir: t.TempDir(), NoCache: true}
	p, err := d.Build(mochiPath, outDir, TargetTypeScriptSource)
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	src := readTrim(t, p)
	for _, want := range []string{
		"// Generated by mochi transpiler3/typescript",
		"function mochi_print_str(value: string): void",
		"console.log(value);",
		"function mochi_main(): void",
		`mochi_print_str("hello, world");`,
		"mochi_main();",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("emitted source missing %q\n---\n%s", want, src)
		}
	}
}

// TestPhase1EmitFragments locks the emitted TS shape for each of
// the four print families (str, i64, f64, bool) plus the embedded-
// newline hello fixture. Phase 2 separately exercises these helpers
// as part of its scalar surface; this test pins them against the
// Phase 1 hello deliverable specifically, so a regression that
// breaks the i64 / f64 / bool entry points fails at Phase 1 (where
// the promise lives) instead of bleeding into Phase 2 coverage.
func TestPhase1EmitFragments(t *testing.T) {
	cases := []struct {
		fixture string
		wants   []string
	}{
		{
			fixture: "hello.mochi",
			wants: []string{
				"function mochi_print_str(value: string): void",
				`mochi_print_str("hello, world");`,
			},
		},
		{
			fixture: "hello_int.mochi",
			wants: []string{
				"function mochi_print_i64(value: number): void",
				"console.log(value.toString());",
				"mochi_print_i64(42);",
			},
		},
		{
			fixture: "hello_float.mochi",
			wants: []string{
				"function mochi_print_f64(value: number): void",
				`if (Number.isNaN(value)) { console.log("NaN"); return; }`,
				`if (!Number.isFinite(value)) { console.log(value < 0 ? "-Inf" : "+Inf"); return; }`,
				"mochi_print_f64(3.14);",
			},
		},
		{
			fixture: "hello_bool.mochi",
			wants: []string{
				"function mochi_print_bool(value: boolean): void",
				`console.log(value ? "true" : "false");`,
				"mochi_print_bool(true);",
			},
		},
		{
			fixture: "hello_newline.mochi",
			wants: []string{
				`mochi_print_str("line1\nline2");`,
			},
		},
	}
	fixtureDir := filepath.Join(repoRoot(t), "tests", "transpiler3", "typescript", "fixtures", "phase01-hello")
	for _, tc := range cases {
		t.Run(strings.TrimSuffix(tc.fixture, ".mochi"), func(t *testing.T) {
			outDir := t.TempDir()
			d := &Driver{CacheDir: t.TempDir(), NoCache: true}
			p, err := d.Build(filepath.Join(fixtureDir, tc.fixture), outDir, TargetTypeScriptSource)
			if err != nil {
				t.Fatalf("Build %s: %v", tc.fixture, err)
			}
			src := readTrim(t, p)
			for _, want := range tc.wants {
				if !strings.Contains(src, want) {
					t.Errorf("%s emit missing %q\n---\n%s", tc.fixture, want, src)
				}
			}
		})
	}
}

// TestPhase1DeterministicEmit asserts that two consecutive Build
// invocations of the same fixture produce byte-identical .ts
// source. This is the Phase 16 reproducibility precondition: if
// emit is non-deterministic at Phase 1 (e.g. map iteration order
// leaking into the file), Phase 16 has nothing to stabilise.
func TestPhase1DeterministicEmit(t *testing.T) {
	fixtureDir := filepath.Join(repoRoot(t), "tests", "transpiler3", "typescript", "fixtures", "phase01-hello")
	mochiPath := filepath.Join(fixtureDir, "hello.mochi")
	if _, err := os.Stat(mochiPath); err != nil {
		t.Skipf("hello.mochi missing: %v", err)
	}
	d := &Driver{CacheDir: t.TempDir(), NoCache: true}
	const N = 5
	var prev []byte
	for i := 0; i < N; i++ {
		outDir := t.TempDir()
		p, err := d.Build(mochiPath, outDir, TargetTypeScriptSource)
		if err != nil {
			t.Fatalf("Build iter %d: %v", i, err)
		}
		got, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("read iter %d: %v", i, err)
		}
		if i > 0 && string(prev) != string(got) {
			t.Fatalf("iter %d output drift\nprev: %q\nnow:  %q", i, prev, got)
		}
		prev = got
	}
}

