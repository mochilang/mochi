// Phase 18.0: emit `.github/workflows/release.yml` that publishes
// the Phase 15 npm package via Trusted Publishing.
//
// Trusted Publishing (npm: GA April 2024; JSR: GA mid-2024) lets
// a CI workflow publish to the registry without storing a long-
// lived API token. The workflow's GitHub OIDC token is exchanged
// at publish time for a short-lived registry credential; the
// registry verifies the token's `iss`, `aud`, `repository`, and
// `workflow_ref` claims against the publisher's pre-registered
// Trusted Publisher configuration.
//
// Sigstore signs the npm tarball at publish time; the signature
// + a SLSA-style provenance statement land in the registry. Any
// consumer can verify via `npm audit signatures` (npm) or `deno
// publish --check-signatures` (Deno; on roadmap).
//
// emitReleaseWorkflow writes a single workflow YAML file. Why
// YAML by template (not by yaml.Marshal): GitHub Actions parses
// the file as YAML 1.2 with specific anchor handling, and the
// human-readable diff is the audit surface security reviewers
// look at. A hand-templated string is auditable line-by-line.
package build

import (
	"fmt"
	"os"
	"path/filepath"
)

// emitReleaseWorkflow writes <outDir>/.github/workflows/release.yml
// describing the Trusted Publishing pipeline. Returns the
// absolute path of the workflow file.
//
// Invariants the file must hold (each enforced by phase18_test.go):
//
//  1. `permissions.id-token: write` is set at the workflow level
//     or job level. Required for OIDC token issuance.
//  2. No `NPM_TOKEN`, `JSR_TOKEN`, or any `secrets.*TOKEN`
//     reference. Trusted Publishing replaces long-lived tokens.
//  3. The npm publish step uses `--provenance` and
//     `--access=public`.
//  4. The deno publish step uses `--token-source=github-actions`
//     (Deno's flag that fetches the OIDC token from the Actions
//     environment).
//  5. The workflow is tag-triggered (`v*.*.*`); PRs run the same
//     code path with `--dry-run`.
func emitReleaseWorkflow(outDir, pkgName string) (string, error) {
	if pkgName == "" {
		return "", fmt.Errorf("ts emit workflow: empty package name")
	}
	dir := filepath.Join(outDir, ".github", "workflows")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("ts emit workflow: mkdir %s: %w", dir, err)
	}
	body := renderReleaseWorkflow(pkgName)
	abs := filepath.Join(dir, "release.yml")
	if err := os.WriteFile(abs, []byte(body), 0o644); err != nil {
		return "", fmt.Errorf("ts emit workflow: write %s: %w", abs, err)
	}
	return abs, nil
}

// renderReleaseWorkflow returns the YAML body for release.yml.
// Pinning notes:
//
//   - Node 22.11.0: current LTS at time of Phase 18 emit.
//   - Deno 2.0.0: minimum version with `--token-source=github-
//     actions`.
//   - `actions/setup-node@v4`: required for registry-url +
//     `always-auth` flag wiring.
//   - `actions/checkout@v4`: required for `fetch-depth: 0` (used
//     by provenance for the commit SHA1 reference).
//   - `actions/upload-artifact@v4`: v4 is the current major;
//     v3 was sunset 2024-12-05.
//   - `actions/attest-build-provenance@v2`: GitHub Attestations
//     v2 API (October 2024 GA).
func renderReleaseWorkflow(pkgName string) string {
	return fmt.Sprintf(`# AUTO-GENERATED by mochi build --target=release-workflow.
# Trusted Publishing pipeline for %s.
#
# Edit this file in your downstream repository; mochi does NOT
# regenerate it after the first emit. Subsequent mochi build runs
# leave the file untouched so your customisations survive.
name: release
on:
  push:
    tags:
      - "v*.*.*"
  pull_request:
    branches: [main]

permissions:
  contents: read
  id-token: write
  attestations: write

jobs:
  release:
    runs-on: ubuntu-22.04
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: "22.11.0"
          registry-url: "https://registry.npmjs.org"
      - uses: denoland/setup-deno@v2
        with:
          deno-version: "2.0.0"
      - name: Build npm package
        run: mochi build --target=npm-package -o dist/npm
      - name: Publish to npm (Trusted Publishing)
        if: startsWith(github.ref, 'refs/tags/')
        working-directory: dist/npm
        run: npm publish --provenance --access=public
      - name: Publish to npm (dry-run on PR)
        if: github.event_name == 'pull_request'
        working-directory: dist/npm
        run: npm publish --dry-run --provenance --access=public
      - name: Build JSR package
        run: mochi build --target=deno-jsr -o dist/jsr
      - name: Publish to JSR (Trusted Publishing)
        if: startsWith(github.ref, 'refs/tags/')
        working-directory: dist/jsr
        run: deno publish --token-source=github-actions
      - name: Publish to JSR (dry-run on PR)
        if: github.event_name == 'pull_request'
        working-directory: dist/jsr
        run: deno publish --dry-run --token-source=github-actions --allow-dirty
      - name: Build browser bundle
        run: mochi build --target=browser-bundle -o dist/browser
      - name: Attest browser bundle
        if: startsWith(github.ref, 'refs/tags/')
        uses: actions/attest-build-provenance@v2
        with:
          subject-path: dist/browser/dist/bundle/index.js
      - name: Upload browser bundle artefact
        uses: actions/upload-artifact@v4
        with:
          name: browser-bundle
          path: dist/browser/dist/bundle/
`, pkgName)
}
