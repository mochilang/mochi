package emit

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"mochi/transpiler3/c/aotir"
)

// Emit renders prog as a single ISO C23 translation unit.
//
// Phase 1 surface: a fixed prologue that includes mochi/print.h,
// then one C function per aotir.Function (entry-point function
// becomes int main(void)), then a trailing newline. Phase 2.0
// extends the expression grammar to scalar literals plus typed
// binary/unary operators. Phase 2.1 adds let/var declarations,
// assignment, if/else, while, break, continue, and bare return
// from main.
//
// Phase 17 reproducibility: functions are emitted in
// sorted-by-Name order; the C source is byte-identical for
// byte-identical inputs.
//
// The output is intended to compile clean under
// `cc -std=c2x -Wall -Wextra -pedantic`. No GNU extensions are
// emitted; the only header dependency is the libmochi runtime.
func Emit(prog *aotir.Program) (string, error) {
	if prog == nil {
		return "", fmt.Errorf("transpiler3/c/emit: nil Program")
	}
	if err := aotir.Verify(prog); err != nil {
		return "", fmt.Errorf("transpiler3/c/emit: verify: %w", err)
	}

	var b strings.Builder
	b.WriteString("/* generated by mochi transpiler3/c (MEP-45 Phase 2.1). */\n")
	b.WriteString("#include <stdint.h>\n")
	b.WriteString("#include \"mochi/print.h\"\n")
	b.WriteString("\n")

	indices := make([]int, len(prog.Functions))
	for i := range prog.Functions {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return prog.Functions[indices[i]].Name < prog.Functions[indices[j]].Name
	})

	for _, idx := range indices {
		fn := prog.Functions[idx]
		isEntry := idx == prog.Main
		if err := emitFunction(&b, fn, isEntry); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

func emitFunction(b *strings.Builder, fn *aotir.Function, entry bool) error {
	if entry {
		b.WriteString("int main(void) {\n")
	} else {
		if fn.ReturnType != aotir.TypeUnit {
			return fmt.Errorf("transpiler3/c/emit: non-unit return type %s on %s (Phase 2.1 limit)", fn.ReturnType, fn.Name)
		}
		fmt.Fprintf(b, "static void %s(void) {\n", fn.Name)
	}
	for _, st := range fn.Body.Statements {
		if err := emitStmt(b, st, "    "); err != nil {
			return err
		}
	}
	if entry && !endsWithReturn(fn.Body) {
		b.WriteString("    return 0;\n")
	}
	b.WriteString("}\n")
	return nil
}

// endsWithReturn reports whether the last statement in a block is a
// ReturnStmt, so the entry emitter can skip the trailing `return 0;`
// it would otherwise add. Avoids unreachable-code diagnostics on
// programs whose Mochi source ends in an explicit `return`.
func endsWithReturn(b *aotir.Block) bool {
	if b == nil || len(b.Statements) == 0 {
		return false
	}
	_, ok := b.Statements[len(b.Statements)-1].(*aotir.ReturnStmt)
	return ok
}

// emitStmt writes one statement preceded by `indent` and a trailing
// newline. Nested blocks (if/while bodies) inherit indent+"    ".
func emitStmt(b *strings.Builder, st aotir.Stmt, indent string) error {
	switch s := st.(type) {
	case *aotir.CallStmt:
		b.WriteString(indent)
		b.WriteString(s.Func)
		b.WriteString("(")
		for i, arg := range s.Args {
			if i > 0 {
				b.WriteString(", ")
			}
			es, err := emitExpr(arg)
			if err != nil {
				return err
			}
			b.WriteString(es)
		}
		b.WriteString(");\n")
		return nil
	case *aotir.LetStmt:
		ts, err := cType(s.VarType)
		if err != nil {
			return fmt.Errorf("let %q: %w", s.Name, err)
		}
		init, err := emitExpr(s.Init)
		if err != nil {
			return err
		}
		b.WriteString(indent)
		if !s.Mutable {
			b.WriteString("const ")
		}
		fmt.Fprintf(b, "%s %s = %s;\n", ts, s.Name, init)
		return nil
	case *aotir.AssignStmt:
		val, err := emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s = %s;\n", indent, s.Name, val)
		return nil
	case *aotir.IfStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Then, indent+"    "); err != nil {
			return err
		}
		if s.Else != nil {
			fmt.Fprintf(b, "%s} else {\n", indent)
			if err := emitBlock(b, s.Else, indent+"    "); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.WhileStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%swhile (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Body, indent+"    "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.BreakStmt:
		fmt.Fprintf(b, "%sbreak;\n", indent)
		return nil
	case *aotir.ContinueStmt:
		fmt.Fprintf(b, "%scontinue;\n", indent)
		return nil
	case *aotir.ReturnStmt:
		if s.Value != nil {
			return fmt.Errorf("transpiler3/c/emit: value-returning return reserved for Phase 2.2")
		}
		fmt.Fprintf(b, "%sreturn 0;\n", indent)
		return nil
	}
	return fmt.Errorf("transpiler3/c/emit: unhandled Stmt %T", st)
}

func emitBlock(b *strings.Builder, blk *aotir.Block, indent string) error {
	if blk == nil {
		return nil
	}
	for _, st := range blk.Statements {
		if err := emitStmt(b, st, indent); err != nil {
			return err
		}
	}
	return nil
}

// cType maps an aotir.Type to its C declaration spelling. The bool
// ABI uses C `int` (0/1) so the runtime print signature lines up
// without an explicit cast.
func cType(t aotir.Type) (string, error) {
	switch t {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("no C declaration for %s", t)
}

func emitExpr(e aotir.Expr) (string, error) {
	switch v := e.(type) {
	case *aotir.StringLit:
		return cStringLiteral(v.Value), nil
	case *aotir.IntLit:
		return emitInt64Lit(v.Value), nil
	case *aotir.FloatLit:
		return emitFloatLit(v.Value), nil
	case *aotir.BoolLit:
		if v.Value {
			return "1", nil
		}
		return "0", nil
	case *aotir.VarRef:
		return v.Name, nil
	case *aotir.BinaryExpr:
		return emitBinary(v)
	case *aotir.UnaryExpr:
		return emitUnary(v)
	default:
		return "", fmt.Errorf("transpiler3/c/emit: unhandled Expr %T", e)
	}
}

// emitInt64Lit renders v with explicit width using INT64_C so the
// generated source carries the value's type into mixed contexts
// (e.g. comparison operands). INT64_MIN is special-cased because
// `INT64_C(-9223372036854775808)` would lex as `-(9223372036854775808)`
// and trip the warning "integer literal is too large".
func emitInt64Lit(v int64) string {
	if v == -1<<63 {
		return "(-INT64_C(9223372036854775807) - INT64_C(1))"
	}
	if v < 0 {
		return "-INT64_C(" + strconv.FormatInt(-v, 10) + ")"
	}
	return "INT64_C(" + strconv.FormatInt(v, 10) + ")"
}

// emitFloatLit renders v through Go's strconv.FormatFloat 'g' -1 64
// then appends a typed suffix-free form ("(double)(<literal>)") so
// the C compiler does not narrow it to float. The literal itself is
// always a finite, exactly-representable double (NaN/Inf are barred
// by the lowerer until Phase 2.4 hardens the print path).
func emitFloatLit(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	// Go produces "1" for 1.0; C reads that as int. Force the
	// literal to read as double via an explicit decimal point or
	// exponent when needed.
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return "(double)(" + s + ")"
}

// emitBinary picks the C operator string and assembles a fully
// parenthesised infix expression. Boolean operators map to C's
// `&&` / `||`, which preserve short-circuit semantics.
func emitBinary(v *aotir.BinaryExpr) (string, error) {
	left, err := emitExpr(v.Left)
	if err != nil {
		return "", err
	}
	right, err := emitExpr(v.Right)
	if err != nil {
		return "", err
	}
	op, err := cBinOp(v.Op)
	if err != nil {
		return "", err
	}
	return "(" + left + " " + op + " " + right + ")", nil
}

func cBinOp(op aotir.BinOp) (string, error) {
	switch op {
	case aotir.BinAddI64, aotir.BinAddF64:
		return "+", nil
	case aotir.BinSubI64, aotir.BinSubF64:
		return "-", nil
	case aotir.BinMulI64, aotir.BinMulF64:
		return "*", nil
	case aotir.BinDivI64, aotir.BinDivF64:
		return "/", nil
	case aotir.BinModI64:
		return "%", nil
	case aotir.BinEqI64, aotir.BinEqF64, aotir.BinEqBool:
		return "==", nil
	case aotir.BinNeI64, aotir.BinNeF64, aotir.BinNeBool:
		return "!=", nil
	case aotir.BinLtI64, aotir.BinLtF64:
		return "<", nil
	case aotir.BinLeI64, aotir.BinLeF64:
		return "<=", nil
	case aotir.BinGtI64, aotir.BinGtF64:
		return ">", nil
	case aotir.BinGeI64, aotir.BinGeF64:
		return ">=", nil
	case aotir.BinAndBool:
		return "&&", nil
	case aotir.BinOrBool:
		return "||", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled BinOp %d", op)
}

func emitUnary(v *aotir.UnaryExpr) (string, error) {
	operand, err := emitExpr(v.Operand)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.UnNegI64, aotir.UnNegF64:
		return "(-" + operand + ")", nil
	case aotir.UnNotBool:
		return "(!" + operand + ")", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled UnOp %d", v.Op)
}

// cStringLiteral renders s as a C string literal. Non-ASCII
// bytes are emitted as \xNN to keep the source plain-ASCII
// (Phase 17 reproducibility: emit output never depends on
// the host's locale / source encoding).
func cStringLiteral(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		case 0:
			b.WriteString("\\0")
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, "\\x%02x", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
