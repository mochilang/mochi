// emitRecordLit renders a RecordLit as a C99 compound literal with
// designated initialisers, e.g. `(struct mochi_Pt){.x=1, .y=2}`. The
// lowerer has already reordered fields into record-decl order so the
// generated source is byte-identical for byte-identical inputs.
func emitRecordLit(v *aotir.RecordLit) (string, error) {
	var b strings.Builder
	b.WriteString("(")
	b.WriteString(cRecordTypeName(v.TypeName))
	b.WriteString("){")
	for i, f := range v.Fields {
		if i > 0 {
			b.WriteString(", ")
		}
		val, err := emitExpr(f.Value)
		if err != nil {
			return "", fmt.Errorf("record %q field %q: %w", v.TypeName, f.Name, err)
		}
		fmt.Fprintf(&b, ".%s = %s", f.Name, val)
	}
	b.WriteString("}")
	return b.String(), nil
}

// emitFieldAccess renders a FieldAccess as `(receiver).field`. The
// receiver is wrapped in parens so a literal receiver (e.g.
// `Pt{...}.x`) parses correctly in C, where compound-literal then
// `.member` is an unusual but valid idiom.
func emitFieldAccess(v *aotir.FieldAccess) (string, error) {
	recv, err := emitExpr(v.Receiver)
	if err != nil {
		return "", fmt.Errorf("field %q: %w", v.FieldName, err)
	}
	return "(" + recv + ")." + v.FieldName, nil
}

// emitRecordDecls renders the file-scope `struct mochi_<Name> {...}`
// declarations plus a per-record equality helper that callers can
// invoke via BinEqRec / BinNeRec. Phase 3.0 keeps the helper
// branchless and inline-friendly: it returns `int` (0/1) and
// compares each field with the appropriate primitive operator (==
// for scalars, strcmp for strings). Nested records are gated out by
// the lowerer, so no recursive eq call is generated yet.
func emitRecordDecls(b *strings.Builder, recs []*aotir.RecordDecl) error {
	if len(recs) == 0 {
		return nil
	}
	indices := make([]int, len(recs))
	for i := range recs {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return recs[indices[i]].Name < recs[indices[j]].Name
	})
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "%s {\n", cRecordTypeName(r.Name))
		for _, f := range r.Fields {
			cT, err := cTypeWithRec(f.Type, f.RecordName)
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			fmt.Fprintf(b, "    %s %s;\n", cT, f.Name)
		}
		b.WriteString("};\n\n")
	}
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "static int mochi_eq_%s(%s a, %s b) {\n",
			r.Name, cRecordTypeName(r.Name), cRecordTypeName(r.Name))
		if len(r.Fields) == 0 {
			b.WriteString("    (void)a; (void)b;\n    return 1;\n}\n\n")
			continue
		}
		b.WriteString("    return ")
		for i, f := range r.Fields {
			if i > 0 {
				b.WriteString(" && ")
			}
			eq, err := fieldEqExpr(f, "a", "b")
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			b.WriteString(eq)
		}
		b.WriteString(";\n}\n\n")
	}
	return nil
}

// fieldEqExpr renders the equality predicate for one record field
// between two operands `a` and `b`. Strings compare byte-wise via
// strcmp; bool/int/float compare with ==; nested records (gated out
// in 3.0) would recurse into mochi_eq_<Name>.
func fieldEqExpr(f aotir.RecordField, a, b string) (string, error) {
	la := "(" + a + ")." + f.Name
	lb := "(" + b + ")." + f.Name
	switch f.Type {
	case aotir.TypeInt, aotir.TypeFloat, aotir.TypeBool:
		return "(" + la + " == " + lb + ")", nil
	case aotir.TypeString:
		return "(strcmp(" + la + ", " + lb + ") == 0)", nil
	case aotir.TypeRecord:
		return "mochi_eq_" + f.RecordName + "(" + la + ", " + lb + ")", nil
	}
	return "", fmt.Errorf("no eq for field type %s", f.Type)
}

// emitCallExpr renders a value-producing call to a user-defined
// function as `name(a0, a1, ...)`. The verifier has already checked
// that the callee exists and the argument types line up, so emit
// only has to walk the argument list.
func emitCallExpr(c *aotir.CallExpr) (string, error) {
	var b strings.Builder
	b.WriteString(c.Func)
	b.WriteByte('(')
	for i, a := range c.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(a)
		if err != nil {
			return "", err
		}
		b.WriteString(es)
	}
	b.WriteByte(')')
	return b.String(), nil
}

// emitInt64Lit renders v with explicit width using INT64_C so the
// generated source carries the value's type into mixed contexts
// (e.g. comparison operands). INT64_MIN is special-cased because
// `INT64_C(-9223372036854775808)` would lex as `-(9223372036854775808)`
// and trip the warning "integer literal is too large".
func emitInt64Lit(v int64) string {
	if v == -1<<63 {
		return "(-INT64_C(9223372036854775807) - INT64_C(1))"
	}
	if v < 0 {
		return "-INT64_C(" + strconv.FormatInt(-v, 10) + ")"
	}
	return "INT64_C(" + strconv.FormatInt(v, 10) + ")"
}

// emitFloatLit renders v through Go's strconv.FormatFloat 'g' -1 64
// then appends a typed suffix-free form ("(double)(<literal>)") so
// the C compiler does not narrow it to float. The literal itself is
// always a finite, exactly-representable double (NaN/Inf are barred
// by the lowerer until Phase 2.4 hardens the print path).
func emitFloatLit(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	// Go produces "1" for 1.0; C reads that as int. Force the
	// literal to read as double via an explicit decimal point or
	// exponent when needed.
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return "(double)(" + s + ")"
}

// emitBinary picks the C operator string and assembles a fully
// parenthesised infix expression. Boolean operators map to C's
// `&&` / `||`, which preserve short-circuit semantics.
//
// Integer division and modulo are special: Phase 2.3 routes
// `BinDivI64` and `BinModI64` through the libmochi runtime
// helpers (`mochi_div_i64`, `mochi_mod_i64`) so that a `rhs == 0`
// trip exits with `MOCHI_ERR_DIVZERO` instead of triggering C
// undefined behaviour (SIGFPE on most ISAs). Float division and
// every other op keep their infix form.
func emitBinary(v *aotir.BinaryExpr) (string, error) {
	left, err := emitExpr(v.Left)
	if err != nil {
		return "", err
	}
	right, err := emitExpr(v.Right)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.BinDivI64:
		return "mochi_div_i64(" + left + ", " + right + ")", nil
	case aotir.BinModI64:
		return "mochi_mod_i64(" + left + ", " + right + ")", nil
	case aotir.BinEqStr:
		return "(strcmp(" + left + ", " + right + ") == 0)", nil
	case aotir.BinNeStr:
		return "(strcmp(" + left + ", " + right + ") != 0)", nil
	case aotir.BinEqRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "mochi_eq_" + recName + "(" + left + ", " + right + ")", nil
	case aotir.BinNeRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "(!mochi_eq_" + recName + "(" + left + ", " + right + "))", nil
	}
	op, err := cBinOp(v.Op)
	if err != nil {
		return "", err
	}
	return "(" + left + " " + op + " " + right + ")", nil
}

// binaryRecordName recovers the record's name from either side of a
// record-typed eq/ne. The lowerer guarantees both operands carry the
// same record name (the verifier rejects mismatches), so reading
// from the left side is sufficient; the right side is consulted as a
// fallback for defensive emit-time diagnostics.
func binaryRecordName(v *aotir.BinaryExpr) (string, error) {
	if n := exprRecordName(v.Left); n != "" {
		return n, nil
	}
	if n := exprRecordName(v.Right); n != "" {
		return n, nil
	}
	return "", fmt.Errorf("record eq without RecordName on either operand")
}

// exprRecordName extracts the record name from a record-typed Expr.
// Mirrors lower.exprRecordName so emit can reach the same answer
// without depending on the lowerer package.
func exprRecordName(e aotir.Expr) string {
	switch x := e.(type) {
	case *aotir.VarRef:
		return x.RecordName
	case *aotir.RecordLit:
		return x.TypeName
	case *aotir.FieldAccess:
		return x.ResultRecordName
	case *aotir.CallExpr:
		return x.ResultRecordName
	}
	return ""
}

func cBinOp(op aotir.BinOp) (string, error) {
	switch op {
	case aotir.BinAddI64, aotir.BinAddF64:
		return "+", nil
	case aotir.BinSubI64, aotir.BinSubF64:
		return "-", nil
	case aotir.BinMulI64, aotir.BinMulF64:
		return "*", nil
	case aotir.BinDivI64, aotir.BinDivF64:
		return "/", nil
	case aotir.BinModI64:
		return "%", nil
	case aotir.BinEqI64, aotir.BinEqF64, aotir.BinEqBool:
		return "==", nil
	case aotir.BinNeI64, aotir.BinNeF64, aotir.BinNeBool:
		return "!=", nil
	case aotir.BinLtI64, aotir.BinLtF64:
		return "<", nil
	case aotir.BinLeI64, aotir.BinLeF64:
		return "<=", nil
	case aotir.BinGtI64, aotir.BinGtF64:
		return ">", nil
	case aotir.BinGeI64, aotir.BinGeF64:
		return ">=", nil
	case aotir.BinAndBool:
		return "&&", nil
	case aotir.BinOrBool:
		return "||", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled BinOp %d", op)
}

func emitUnary(v *aotir.UnaryExpr) (string, error) {
	operand, err := emitExpr(v.Operand)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.UnNegI64, aotir.UnNegF64:
		return "(-" + operand + ")", nil
	case aotir.UnNotBool:
		return "(!" + operand + ")", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled UnOp %d", v.Op)
}

// cStringLiteral renders s as a C string literal. Non-ASCII
// bytes are emitted as \xNN to keep the source plain-ASCII
// (Phase 17 reproducibility: emit output never depends on
// the host's locale / source encoding).
func cStringLiteral(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		case 0:
			b.WriteString("\\0")
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, "\\x%02x", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
