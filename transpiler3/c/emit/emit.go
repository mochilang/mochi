package emit

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"mochi/transpiler3/c/aotir"
)

// Emit renders prog as a single ISO C23 translation unit.
//
// Phase 1 surface: a fixed prologue that includes mochi/print.h,
// then one C function per aotir.Function (entry-point function
// becomes int main(void)), then a trailing newline. Phase 2.0
// extends the expression grammar to scalar literals plus typed
// binary/unary operators. Phase 2.1 adds let/var declarations,
// assignment, if/else, while, break, continue, and bare return
// from main.
//
// Phase 17 reproducibility: functions are emitted in
// sorted-by-Name order; the C source is byte-identical for
// byte-identical inputs.
//
// The output is intended to compile clean under
// `cc -std=c2x -Wall -Wextra -pedantic`. No GNU extensions are
// emitted; the only header dependency is the libmochi runtime.
func Emit(prog *aotir.Program) (string, error) {
	if prog == nil {
		return "", fmt.Errorf("transpiler3/c/emit: nil Program")
	}
	if err := aotir.Verify(prog); err != nil {
		return "", fmt.Errorf("transpiler3/c/emit: verify: %w", err)
	}

	var b strings.Builder
	b.WriteString("/* generated by mochi transpiler3/c (MEP-45 Phase 3.0). */\n")
	b.WriteString("#include <stdint.h>\n")
	b.WriteString("#include <string.h>\n")
	b.WriteString("#include \"mochi/print.h\"\n")
	b.WriteString("#include \"mochi/errors.h\"\n")
	b.WriteString("\n")

	if err := emitRecordDecls(&b, prog.Records); err != nil {
		return "", err
	}

	indices := make([]int, len(prog.Functions))
	for i := range prog.Functions {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return prog.Functions[indices[i]].Name < prog.Functions[indices[j]].Name
	})

	// Forward-declare every non-entry function so order of mutual
	// recursion doesn't matter to the C compiler. The entry function
	// uses the C `int main(void)` signature and is never called from
	// other functions, so it gets no prototype.
	hasUserFn := false
	for _, idx := range indices {
		if idx == prog.Main {
			continue
		}
		fn := prog.Functions[idx]
		proto, err := emitFunctionPrototype(fn)
		if err != nil {
			return "", err
		}
		b.WriteString(proto)
		b.WriteString(";\n")
		hasUserFn = true
	}
	if hasUserFn {
		b.WriteString("\n")
	}

	for _, idx := range indices {
		fn := prog.Functions[idx]
		isEntry := idx == prog.Main
		if err := emitFunction(&b, fn, isEntry); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

// emitFunctionPrototype renders the C declarator portion of a
// non-entry function (return type, name, parameter list). Used both
// for the file-scope forward declarations and for the function body
// definitions. Keeping the two in lockstep avoids drift between
// prototype and definition.
func emitFunctionPrototype(fn *aotir.Function) (string, error) {
	ret, err := cReturnType(fn.ReturnType, fn.ReturnRecordName)
	if err != nil {
		return "", fmt.Errorf("function %q return: %w", fn.Name, err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "static %s %s(", ret, fn.Name)
	if len(fn.Params) == 0 {
		b.WriteString("void")
	} else {
		for i, p := range fn.Params {
			if i > 0 {
				b.WriteString(", ")
			}
			pt, err := cTypeWithRec(p.Type, p.RecordName)
			if err != nil {
				return "", fmt.Errorf("function %q param %q: %w", fn.Name, p.Name, err)
			}
			fmt.Fprintf(&b, "%s %s", pt, p.Name)
		}
	}
	b.WriteString(")")
	return b.String(), nil
}

// cReturnType maps an aotir.Type to its C return-type spelling. Unit
// is `void`; the scalar types share the cType spellings; record types
// render as `struct mochi_<Name>` value (returned by value).
func cReturnType(t aotir.Type, recName string) (string, error) {
	if t == aotir.TypeUnit {
		return "void", nil
	}
	return cTypeWithRec(t, recName)
}

func emitFunction(b *strings.Builder, fn *aotir.Function, entry bool) error {
	if entry {
		b.WriteString("int main(void) {\n")
	} else {
		proto, err := emitFunctionPrototype(fn)
		if err != nil {
			return err
		}
		b.WriteString(proto)
		b.WriteString(" {\n")
	}
	for _, st := range fn.Body.Statements {
		if err := emitStmt(b, st, "    "); err != nil {
			return err
		}
	}
	if entry && !endsWithReturn(fn.Body) {
		b.WriteString("    return 0;\n")
	}
	b.WriteString("}\n")
	return nil
}

// endsWithReturn reports whether the last statement in a block is a
// ReturnStmt, so the entry emitter can skip the trailing `return 0;`
// it would otherwise add. Avoids unreachable-code diagnostics on
// programs whose Mochi source ends in an explicit `return`.
func endsWithReturn(b *aotir.Block) bool {
	if b == nil || len(b.Statements) == 0 {
		return false
	}
	_, ok := b.Statements[len(b.Statements)-1].(*aotir.ReturnStmt)
	return ok
}

// emitStmt writes one statement preceded by `indent` and a trailing
// newline. Nested blocks (if/while bodies) inherit indent+"    ".
func emitStmt(b *strings.Builder, st aotir.Stmt, indent string) error {
	switch s := st.(type) {
	case *aotir.CallStmt:
		b.WriteString(indent)
		b.WriteString(s.Func)
		b.WriteString("(")
		for i, arg := range s.Args {
			if i > 0 {
				b.WriteString(", ")
			}
			es, err := emitExpr(arg)
			if err != nil {
				return err
			}
			b.WriteString(es)
		}
		b.WriteString(");\n")
		return nil
	case *aotir.LetStmt:
		ts, err := cTypeWithRec(s.VarType, s.RecordName)
		if err != nil {
			return fmt.Errorf("let %q: %w", s.Name, err)
		}
		init, err := emitExpr(s.Init)
		if err != nil {
			return err
		}
		b.WriteString(indent)
		if !s.Mutable {
			b.WriteString("const ")
		}
		fmt.Fprintf(b, "%s %s = %s;\n", ts, s.Name, init)
		return nil
	case *aotir.AssignStmt:
		val, err := emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s = %s;\n", indent, s.Name, val)
		return nil
	case *aotir.IfStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Then, indent+"    "); err != nil {
			return err
		}
		if s.Else != nil {
			fmt.Fprintf(b, "%s} else {\n", indent)
			if err := emitBlock(b, s.Else, indent+"    "); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.WhileStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%swhile (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Body, indent+"    "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.ForRangeStmt:
		start, err := emitExpr(s.Start)
		if err != nil {
			return err
		}
		end, err := emitExpr(s.End)
		if err != nil {
			return err
		}
		// Half-open [start, end): the induction variable is declared
		// inside the for header so the C scope mirrors Mochi's. The
		// end expression is hoisted into a const sentinel so any
		// side effect or function call evaluates exactly once at
		// loop entry, matching vm3 semantics.
		sentinel := "__mochi_end_" + s.Var
		fmt.Fprintf(b, "%s{\n", indent)
		fmt.Fprintf(b, "%s    const int64_t %s = %s;\n", indent, sentinel, end)
		fmt.Fprintf(b, "%s    for (int64_t %s = %s; %s < %s; %s++) {\n",
			indent, s.Var, start, s.Var, sentinel, s.Var)
		if err := emitBlock(b, s.Body, indent+"        "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s    }\n", indent)
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.BreakStmt:
		fmt.Fprintf(b, "%sbreak;\n", indent)
		return nil
	case *aotir.ContinueStmt:
		fmt.Fprintf(b, "%scontinue;\n", indent)
		return nil
	case *aotir.ReturnStmt:
		if s.Value == nil {
			// A bare `return` is only legal in a unit-return function
			// (main or a user fn returning unit). The verifier already
			// enforces this; emit lowers it to `return 0;` from main
			// and `return;` from any other unit-return function.
			//
			// Phase 2.2 doesn't yet expose unit-return user functions
			// from the surface (every user fn must have an explicit
			// non-unit return type), so the only context that hits
			// this branch is main.
			fmt.Fprintf(b, "%sreturn 0;\n", indent)
			return nil
		}
		val, err := emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sreturn %s;\n", indent, val)
		return nil
	}
	return fmt.Errorf("transpiler3/c/emit: unhandled Stmt %T", st)
}

func emitBlock(b *strings.Builder, blk *aotir.Block, indent string) error {
	if blk == nil {
		return nil
	}
	for _, st := range blk.Statements {
		if err := emitStmt(b, st, indent); err != nil {
			return err
		}
	}
	return nil
}

// cType maps a scalar aotir.Type to its C declaration spelling. The
// bool ABI uses C `int` (0/1) so the runtime print signature lines
// up without an explicit cast. cType does not accept TypeRecord;
// callers that may see records must use cTypeWithRec so the record's
// identity is plumbed through.
func cType(t aotir.Type) (string, error) {
	switch t {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("no C declaration for %s", t)
}

// cTypeWithRec extends cType with TypeRecord support. The record's
// identity rides on a parallel string at every IR site that can hold
// a record value (LetStmt.RecordName, Param.RecordName, etc.); the
// caller passes it through so emit can render the correct
// `struct mochi_<Name>` spelling.
func cTypeWithRec(t aotir.Type, recName string) (string, error) {
	if t == aotir.TypeRecord {
		if recName == "" {
			return "", fmt.Errorf("TypeRecord without RecordName")
		}
		return cRecordTypeName(recName), nil
	}
	return cType(t)
}

// cRecordTypeName returns the C type spelling for a record type
// named `name`. The `mochi_` prefix avoids clashes with arbitrary
// user names and `struct` keeps the spelling self-contained (no
// typedef needed; that would force a sort-by-dependency that 3.0
// doesn't need yet).
func cRecordTypeName(name string) string {
	return "struct mochi_" + name
}

func emitExpr(e aotir.Expr) (string, error) {
	switch v := e.(type) {
	case *aotir.StringLit:
		return cStringLiteral(v.Value), nil
	case *aotir.IntLit:
		return emitInt64Lit(v.Value), nil
	case *aotir.FloatLit:
		return emitFloatLit(v.Value), nil
	case *aotir.BoolLit:
		if v.Value {
			return "1", nil
		}
		return "0", nil
	case *aotir.VarRef:
		return v.Name, nil
	case *aotir.BinaryExpr:
		return emitBinary(v)
	case *aotir.UnaryExpr:
		return emitUnary(v)
	case *aotir.CallExpr:
		return emitCallExpr(v)
	case *aotir.RecordLit:
		return emitRecordLit(v)
	case *aotir.FieldAccess:
		return emitFieldAccess(v)
	default:
		return "", fmt.Errorf("transpiler3/c/emit: unhandled Expr %T", e)
	}
}

// emitRecordLit renders a RecordLit as a C99 compound literal with
// designated initialisers, e.g. `(struct mochi_Pt){.x=1, .y=2}`. The
// lowerer has already reordered fields into record-decl order so the
// generated source is byte-identical for byte-identical inputs.
func emitRecordLit(v *aotir.RecordLit) (string, error) {
	var b strings.Builder
	b.WriteString("(")
	b.WriteString(cRecordTypeName(v.TypeName))
	b.WriteString("){")
	for i, f := range v.Fields {
		if i > 0 {
			b.WriteString(", ")
		}
		val, err := emitExpr(f.Value)
		if err != nil {
			return "", fmt.Errorf("record %q field %q: %w", v.TypeName, f.Name, err)
		}
		fmt.Fprintf(&b, ".%s = %s", f.Name, val)
	}
	b.WriteString("}")
	return b.String(), nil
}

// emitFieldAccess renders a FieldAccess as `(receiver).field`. The
// receiver is wrapped in parens so a literal receiver (e.g.
// `Pt{...}.x`) parses correctly in C, where compound-literal then
// `.member` is an unusual but valid idiom.
func emitFieldAccess(v *aotir.FieldAccess) (string, error) {
	recv, err := emitExpr(v.Receiver)
	if err != nil {
		return "", fmt.Errorf("field %q: %w", v.FieldName, err)
	}
	return "(" + recv + ")." + v.FieldName, nil
}

// emitRecordDecls renders the file-scope `struct mochi_<Name> {...}`
// declarations plus a per-record equality helper that callers can
// invoke via BinEqRec / BinNeRec. Phase 3.0 keeps the helper
// branchless and inline-friendly: it returns `int` (0/1) and
// compares each field with the appropriate primitive operator (==
// for scalars, strcmp for strings). Nested records are gated out by
// the lowerer, so no recursive eq call is generated yet.
func emitRecordDecls(b *strings.Builder, recs []*aotir.RecordDecl) error {
	if len(recs) == 0 {
		return nil
	}
	indices := make([]int, len(recs))
	for i := range recs {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return recs[indices[i]].Name < recs[indices[j]].Name
	})
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "%s {\n", cRecordTypeName(r.Name))
		for _, f := range r.Fields {
			cT, err := cTypeWithRec(f.Type, f.RecordName)
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			fmt.Fprintf(b, "    %s %s;\n", cT, f.Name)
		}
		b.WriteString("};\n\n")
	}
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "static int mochi_eq_%s(%s a, %s b) {\n",
			r.Name, cRecordTypeName(r.Name), cRecordTypeName(r.Name))
		if len(r.Fields) == 0 {
			b.WriteString("    (void)a; (void)b;\n    return 1;\n}\n\n")
			continue
		}
		b.WriteString("    return ")
		for i, f := range r.Fields {
			if i > 0 {
				b.WriteString(" && ")
			}
			eq, err := fieldEqExpr(f, "a", "b")
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			b.WriteString(eq)
		}
		b.WriteString(";\n}\n\n")
	}
	return nil
}

// fieldEqExpr renders the equality predicate for one record field
// between two operands `a` and `b`. Strings compare byte-wise via
// strcmp; bool/int/float compare with ==; nested records (gated out
// in 3.0) would recurse into mochi_eq_<Name>.
func fieldEqExpr(f aotir.RecordField, a, b string) (string, error) {
	la := "(" + a + ")." + f.Name
	lb := "(" + b + ")." + f.Name
	switch f.Type {
	case aotir.TypeInt, aotir.TypeFloat, aotir.TypeBool:
		return "(" + la + " == " + lb + ")", nil
	case aotir.TypeString:
		return "(strcmp(" + la + ", " + lb + ") == 0)", nil
	case aotir.TypeRecord:
		return "mochi_eq_" + f.RecordName + "(" + la + ", " + lb + ")", nil
	}
	return "", fmt.Errorf("no eq for field type %s", f.Type)
}

// emitCallExpr renders a value-producing call to a user-defined
// function as `name(a0, a1, ...)`. The verifier has already checked
// that the callee exists and the argument types line up, so emit
// only has to walk the argument list.
func emitCallExpr(c *aotir.CallExpr) (string, error) {
	var b strings.Builder
	b.WriteString(c.Func)
	b.WriteByte('(')
	for i, a := range c.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(a)
		if err != nil {
			return "", err
		}
		b.WriteString(es)
	}
	b.WriteByte(')')
	return b.String(), nil
}

// emitInt64Lit renders v with explicit width using INT64_C so the
// generated source carries the value's type into mixed contexts
// (e.g. comparison operands). INT64_MIN is special-cased because
// `INT64_C(-9223372036854775808)` would lex as `-(9223372036854775808)`
// and trip the warning "integer literal is too large".
func emitInt64Lit(v int64) string {
	if v == -1<<63 {
		return "(-INT64_C(9223372036854775807) - INT64_C(1))"
	}
	if v < 0 {
		return "-INT64_C(" + strconv.FormatInt(-v, 10) + ")"
	}
	return "INT64_C(" + strconv.FormatInt(v, 10) + ")"
}

// emitFloatLit renders v through Go's strconv.FormatFloat 'g' -1 64
// then appends a typed suffix-free form ("(double)(<literal>)") so
// the C compiler does not narrow it to float. The literal itself is
// always a finite, exactly-representable double (NaN/Inf are barred
// by the lowerer until Phase 2.4 hardens the print path).
func emitFloatLit(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	// Go produces "1" for 1.0; C reads that as int. Force the
	// literal to read as double via an explicit decimal point or
	// exponent when needed.
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return "(double)(" + s + ")"
}

// emitBinary picks the C operator string and assembles a fully
// parenthesised infix expression. Boolean operators map to C's
// `&&` / `||`, which preserve short-circuit semantics.
//
// Integer division and modulo are special: Phase 2.3 routes
// `BinDivI64` and `BinModI64` through the libmochi runtime
// helpers (`mochi_div_i64`, `mochi_mod_i64`) so that a `rhs == 0`
// trip exits with `MOCHI_ERR_DIVZERO` instead of triggering C
// undefined behaviour (SIGFPE on most ISAs). Float division and
// every other op keep their infix form.
func emitBinary(v *aotir.BinaryExpr) (string, error) {
	left, err := emitExpr(v.Left)
	if err != nil {
		return "", err
	}
	right, err := emitExpr(v.Right)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.BinDivI64:
		return "mochi_div_i64(" + left + ", " + right + ")", nil
	case aotir.BinModI64:
		return "mochi_mod_i64(" + left + ", " + right + ")", nil
	case aotir.BinEqStr:
		return "(strcmp(" + left + ", " + right + ") == 0)", nil
	case aotir.BinNeStr:
		return "(strcmp(" + left + ", " + right + ") != 0)", nil
	case aotir.BinEqRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "mochi_eq_" + recName + "(" + left + ", " + right + ")", nil
	case aotir.BinNeRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "(!mochi_eq_" + recName + "(" + left + ", " + right + "))", nil
	}
	op, err := cBinOp(v.Op)
	if err != nil {
		return "", err
	}
	return "(" + left + " " + op + " " + right + ")", nil
}

// binaryRecordName recovers the record's name from either side of a
// record-typed eq/ne. The lowerer guarantees both operands carry the
// same record name (the verifier rejects mismatches), so reading
// from the left side is sufficient; the right side is consulted as a
// fallback for defensive emit-time diagnostics.
func binaryRecordName(v *aotir.BinaryExpr) (string, error) {
	if n := exprRecordName(v.Left); n != "" {
		return n, nil
	}
	if n := exprRecordName(v.Right); n != "" {
		return n, nil
	}
	return "", fmt.Errorf("record eq without RecordName on either operand")
}

// exprRecordName extracts the record name from a record-typed Expr.
// Mirrors lower.exprRecordName so emit can reach the same answer
// without depending on the lowerer package.
func exprRecordName(e aotir.Expr) string {
	switch x := e.(type) {
	case *aotir.VarRef:
		return x.RecordName
	case *aotir.RecordLit:
		return x.TypeName
	case *aotir.FieldAccess:
		return x.ResultRecordName
	case *aotir.CallExpr:
		return x.ResultRecordName
	}
	return ""
}

func cBinOp(op aotir.BinOp) (string, error) {
	switch op {
	case aotir.BinAddI64, aotir.BinAddF64:
		return "+", nil
	case aotir.BinSubI64, aotir.BinSubF64:
		return "-", nil
	case aotir.BinMulI64, aotir.BinMulF64:
		return "*", nil
	case aotir.BinDivI64, aotir.BinDivF64:
		return "/", nil
	case aotir.BinModI64:
		return "%", nil
	case aotir.BinEqI64, aotir.BinEqF64, aotir.BinEqBool:
		return "==", nil
	case aotir.BinNeI64, aotir.BinNeF64, aotir.BinNeBool:
		return "!=", nil
	case aotir.BinLtI64, aotir.BinLtF64:
		return "<", nil
	case aotir.BinLeI64, aotir.BinLeF64:
		return "<=", nil
	case aotir.BinGtI64, aotir.BinGtF64:
		return ">", nil
	case aotir.BinGeI64, aotir.BinGeF64:
		return ">=", nil
	case aotir.BinAndBool:
		return "&&", nil
	case aotir.BinOrBool:
		return "||", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled BinOp %d", op)
}

func emitUnary(v *aotir.UnaryExpr) (string, error) {
	operand, err := emitExpr(v.Operand)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.UnNegI64, aotir.UnNegF64:
		return "(-" + operand + ")", nil
	case aotir.UnNotBool:
		return "(!" + operand + ")", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled UnOp %d", v.Op)
}

// cStringLiteral renders s as a C string literal. Non-ASCII
// bytes are emitted as \xNN to keep the source plain-ASCII
// (Phase 17 reproducibility: emit output never depends on
// the host's locale / source encoding).
func cStringLiteral(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		case 0:
			b.WriteString("\\0")
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, "\\x%02x", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
