// emitFunCallExpr renders a FunCallExpr as `callee(arg0, arg1, ...)`.
func emitFunCallExpr(v *aotir.FunCallExpr) (string, error) {
	callee, err := emitExpr(v.Callee)
	if err != nil {
		return "", fmt.Errorf("FunCallExpr callee: %w", err)
	}
	var b strings.Builder
	b.WriteString(callee)
	b.WriteString("(")
	for i, arg := range v.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		as, err := emitExpr(arg)
		if err != nil {
			return "", fmt.Errorf("FunCallExpr arg %d: %w", i, err)
		}
		b.WriteString(as)
	}
	b.WriteString(")")
	return b.String(), nil
}

// collectFunSigs walks the Program and collects all unique FunSig instances
// used in LetStmt bindings, function parameters, and FunLit nodes. The
// returned slice is deduplicated by FunTypeName so each typedef is emitted
// exactly once.
func collectFunSigs(prog *aotir.Program) []*aotir.FunSig {
	seen := map[string]*aotir.FunSig{}
	var add func(sig *aotir.FunSig)
	add = func(sig *aotir.FunSig) {
		if sig == nil {
			return
		}
		name := sig.FunTypeName()
		if _, ok := seen[name]; !ok {
			seen[name] = sig
		}
	}
	for _, fn := range prog.Functions {
		// Function parameters.
		for _, p := range fn.Params {
			if p.Type == aotir.TypeFun {
				add(p.FunSig)
			}
		}
		// Function return type.
		if fn.ReturnType == aotir.TypeFun {
			add(fn.ReturnFunSig)
		}
		// Walk statements for LetStmt and FunLit nodes.
		if fn.Body != nil {
			collectFunSigsBlock(fn.Body, seen)
		}
	}
	// Return sorted by typedef name for reproducibility.
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	sort.Strings(names)
	result := make([]*aotir.FunSig, 0, len(names))
	for _, n := range names {
		result = append(result, seen[n])
	}
	return result
}

// collectFunSigsBlock recursively walks a Block looking for FunSig
// instances in LetStmt nodes and FunLit expressions.
func collectFunSigsBlock(blk *aotir.Block, seen map[string]*aotir.FunSig) {
	if blk == nil {
		return
	}
	for _, st := range blk.Statements {
		collectFunSigsStmt(st, seen)
	}
}

func collectFunSigsStmt(st aotir.Stmt, seen map[string]*aotir.FunSig) {
	switch s := st.(type) {
	case *aotir.LetStmt:
		if s.VarType == aotir.TypeFun && s.FunSig != nil {
			name := s.FunSig.FunTypeName()
			if _, ok := seen[name]; !ok {
				seen[name] = s.FunSig
			}
		}
		if s.Init != nil {
			collectFunSigsExpr(s.Init, seen)
		}
	case *aotir.AssignStmt:
		if s.Value != nil {
			collectFunSigsExpr(s.Value, seen)
		}
	case *aotir.ReturnStmt:
		if s.Value != nil {
			collectFunSigsExpr(s.Value, seen)
		}
	case *aotir.IfStmt:
		collectFunSigsBlock(s.Then, seen)
		collectFunSigsBlock(s.Else, seen)
	case *aotir.WhileStmt:
		collectFunSigsBlock(s.Body, seen)
	case *aotir.ForRangeStmt:
		collectFunSigsBlock(s.Body, seen)
	case *aotir.ForEachStmt:
		collectFunSigsBlock(s.Body, seen)
	case *aotir.CallStmt:
		for _, arg := range s.Args {
			collectFunSigsExpr(arg, seen)
		}
	case *aotir.MatchStmt:
		for i := range s.Arms {
			collectFunSigsBlock(s.Arms[i].Body, seen)
		}
		if s.Default != nil {
			collectFunSigsBlock(s.Default.Body, seen)
		}
	}
}

func collectFunSigsExpr(e aotir.Expr, seen map[string]*aotir.FunSig) {
	if e == nil {
		return
	}
	switch v := e.(type) {
	case *aotir.FunLit:
		if v.Sig != nil {
			name := v.Sig.FunTypeName()
			if _, ok := seen[name]; !ok {
				seen[name] = v.Sig
			}
		}
	case *aotir.FunCallExpr:
		collectFunSigsExpr(v.Callee, seen)
		for _, arg := range v.Args {
			collectFunSigsExpr(arg, seen)
		}
	case *aotir.VarRef:
		if v.VarType == aotir.TypeFun && v.FunSig != nil {
			name := v.FunSig.FunTypeName()
			if _, ok := seen[name]; !ok {
				seen[name] = v.FunSig
			}
		}
	}
}

// emitFunTypedefs emits a C function-pointer typedef for each unique FunSig.
// Format: typedef <ret> (*<name>)(<params>);
func emitFunTypedefs(b *strings.Builder, sigs []*aotir.FunSig) error {
	if len(sigs) == 0 {
		return nil
	}
	for _, sig := range sigs {
		cRet, err := funSigCReturnType(sig.ReturnType)
		if err != nil {
			return fmt.Errorf("emitFunTypedefs: %w", err)
		}
		var params string
		if len(sig.ParamTypes) == 0 {
			params = "void"
		} else {
			parts := make([]string, len(sig.ParamTypes))
			for i, pt := range sig.ParamTypes {
				cp, err := funSigCParamType(pt)
				if err != nil {
					return fmt.Errorf("emitFunTypedefs param %d: %w", i, err)
				}
				parts[i] = cp
			}
			params = strings.Join(parts, ", ")
		}
		fmt.Fprintf(b, "typedef %s (*%s)(%s);\n", cRet, sig.FunTypeName(), params)
	}
	b.WriteString("\n")
	return nil
}

// funSigCReturnType returns the C return type spelling for a fun signature's
// return type. Only scalar primitives and unit are valid in Phase 5.0.
func funSigCReturnType(t aotir.Type) (string, error) {
	switch t {
	case aotir.TypeUnit:
		return "void", nil
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("fun return type %s not supported in Phase 5.0 (scalar primitives or void only)", t)
}

// funSigCParamType returns the C parameter type spelling for a fun signature's
// parameter type. Only scalar primitives are valid in Phase 5.0.
func funSigCParamType(t aotir.Type) (string, error) {
	switch t {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("fun param type %s not supported in Phase 5.0 (scalar primitives only)", t)
}

// cStringLiteral renders s as a C string literal. Non-ASCII
// bytes are emitted as \xNN to keep the source plain-ASCII
// (Phase 17 reproducibility: emit output never depends on
// the host's locale / source encoding).
func cStringLiteral(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		case 0:
			b.WriteString("\\0")
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, "\\x%02x", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
