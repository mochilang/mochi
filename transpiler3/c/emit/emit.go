// emitUnionDecls renders a typedef struct for each union in source
// order, followed by per-variant inline constructor functions.
//
// C layout (MEP-45 §4):
//
//	typedef struct pkg_Shape {
//	    uint8_t tag;
//	    union { struct { int64_t r; } Circle; ... } u;
//	} pkg_Shape;
//	static inline pkg_Shape pkg_Shape_Circle(int64_t r) { ... }
func emitUnionDecls(b *strings.Builder, unions []*aotir.UnionDecl) error {
	if len(unions) == 0 {
		return nil
	}
	for _, u := range unions {
		cName := cUnionTypeName(u.Name)
		fmt.Fprintf(b, "typedef struct %s {\n    uint8_t tag;\n    union {\n", cName)
		for _, v := range u.Variants {
			if len(v.Fields) == 0 {
				fmt.Fprintf(b, "        struct { char __pad; } %s;\n", v.Name)
			} else {
				fmt.Fprintf(b, "        struct {\n")
				for _, f := range v.Fields {
					ct, err := variantFieldCType(f)
					if err != nil {
						return fmt.Errorf("union %q variant %q field %q: %w", u.Name, v.Name, f.Name, err)
					}
					fmt.Fprintf(b, "            %s %s;\n", ct, f.Name)
				}
				fmt.Fprintf(b, "        } %s;\n", v.Name)
			}
		}
		fmt.Fprintf(b, "    } u;\n} %s;\n\n", cName)

		// Per-variant inline constructors.
		for _, v := range u.Variants {
			ctorName := cUnionCtorName(u.Name, v.Name)
			if len(v.Fields) == 0 {
				fmt.Fprintf(b, "static inline %s %s(void) { %s __v; __v.tag = %d; return __v; }\n",
					cName, ctorName, cName, v.Tag)
			} else {
				// Build param list.
				var params strings.Builder
				for i, f := range v.Fields {
					if i > 0 {
						params.WriteString(", ")
					}
					ct, err := variantFieldCType(f)
					if err != nil {
						return fmt.Errorf("union %q ctor %q param %q: %w", u.Name, v.Name, f.Name, err)
					}
					fmt.Fprintf(&params, "%s %s", ct, f.Name)
				}
				fmt.Fprintf(b, "static inline %s %s(%s) {\n    %s __v;\n    __v.tag = %d;\n",
					cName, ctorName, params.String(), cName, v.Tag)
				for _, f := range v.Fields {
					fmt.Fprintf(b, "    __v.u.%s.%s = %s;\n", v.Name, f.Name, f.Name)
				}
				fmt.Fprintf(b, "    return __v;\n}\n")
			}
		}
		b.WriteString("\n")
	}
	return nil
}

// variantFieldCType returns the C type for one variant field.
// Phase 4.0 restricts to scalar primitives.
func variantFieldCType(f aotir.VariantField) (string, error) {
	switch f.FieldType {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	case aotir.TypeRecord:
		if f.RecordName == "" {
			return "", fmt.Errorf("record-typed field missing RecordName")
		}
		return cRecordTypeName(f.RecordName), nil
	}
	return "", fmt.Errorf("unsupported variant field type %s in Phase 4.0", f.FieldType)
}

// emitVariantLit renders `pkg_U_Ctor(arg0, arg1, ...)` for a VariantLit
// with fields, or `pkg_U_Ctor()` for a unit variant.
func emitVariantLit(v *aotir.VariantLit) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "%s(", cUnionCtorName(v.UnionName, v.VariantName))
	for i, f := range v.Fields {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(f.Value)
		if err != nil {
			return "", fmt.Errorf("variant %q field %q: %w", v.VariantName, f.Name, err)
		}
		b.WriteString(es)
	}
	b.WriteString(")")
	return b.String(), nil
}

// emitVariantFieldAccess renders `val.u.VariantName.FieldName`.
func emitVariantFieldAccess(v *aotir.VariantFieldAccess) (string, error) {
	recv, err := emitExpr(v.Receiver)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("(%s).u.%s.%s", recv, v.VariantName, v.FieldName), nil
}

// emitMatchStmt renders a Mochi `match` as a C `switch` on the tag.
// When s.ResultVar is non-empty the caller has already pre-declared
// a mutable variable; each arm assigns into it.
// Each match is wrapped in its own {} block so that multiple matches
// on the same union type in the same scope don't collide on the
// __mochi_match_<Union> local name.
func emitMatchStmt(b *strings.Builder, s *aotir.MatchStmt, indent string) error {
	targetC, err := emitExpr(s.Target)
	if err != nil {
		return fmt.Errorf("match target: %w", err)
	}
	innerIndent := indent + "    "
	armBodyIndent := indent + "        "

	// Wrap in a block so the target local doesn't leak or collide.
	fmt.Fprintf(b, "%s{\n", indent)

	// Bind the target to a const local so it's evaluated once.
	cName := cUnionTypeName(s.UnionName)
	targetVar := "__mochi_match_" + s.UnionName
	fmt.Fprintf(b, "%s    const %s %s = %s;\n", indent, cName, targetVar, targetC)
	fmt.Fprintf(b, "%s    switch (%s.tag) {\n", indent, targetVar)

	emitArm := func(arm *aotir.MatchArm, isDefault bool) error {
		if isDefault {
			fmt.Fprintf(b, "%sdefault: {\n", innerIndent)
		} else {
			fmt.Fprintf(b, "%scase %d: {\n", innerIndent, arm.Tag)
		}
		// Emit field bindings.
		for _, bind := range arm.Bindings {
			ct, err := variantFieldCType(aotir.VariantField{Name: bind.FieldName, FieldType: bind.FieldType, RecordName: bind.RecordName})
			if err != nil {
				return fmt.Errorf("arm %q binding %q: %w", arm.VariantName, bind.VarName, err)
			}
			// Avoid emitting "const const char *": only prefix const when the
			// type string does not already start with "const " (e.g. TypeString).
			if strings.HasPrefix(ct, "const ") {
				fmt.Fprintf(b, "%s%s %s = %s.u.%s.%s;\n",
					armBodyIndent, ct, bind.VarName, targetVar, arm.VariantName, bind.FieldName)
			} else {
				fmt.Fprintf(b, "%sconst %s %s = %s.u.%s.%s;\n",
					armBodyIndent, ct, bind.VarName, targetVar, arm.VariantName, bind.FieldName)
			}
		}
		// Emit arm body.
		if err := emitBlock(b, arm.Body, armBodyIndent); err != nil {
			return err
		}
		fmt.Fprintf(b, "%sbreak;\n", armBodyIndent)
		fmt.Fprintf(b, "%s}\n", innerIndent)
		return nil
	}

	for i := range s.Arms {
		if err := emitArm(&s.Arms[i], false); err != nil {
			return fmt.Errorf("match arm %d: %w", i, err)
		}
	}
	if s.Default != nil {
		if err := emitArm(s.Default, true); err != nil {
			return fmt.Errorf("match default arm: %w", err)
		}
	}
	fmt.Fprintf(b, "%s    }\n", indent) // close switch
	fmt.Fprintf(b, "%s}\n", indent)     // close outer block
	return nil
}

// emitCallExpr renders a value-producing call to a user-defined
// function as `name(a0, a1, ...)`. The verifier has already checked
// that the callee exists and the argument types line up, so emit
// only has to walk the argument list.
func emitCallExpr(c *aotir.CallExpr) (string, error) {
	var b strings.Builder
	b.WriteString(c.Func)
	b.WriteByte('(')
	for i, a := range c.Args {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(a)
		if err != nil {
			return "", err
		}
		b.WriteString(es)
	}
	b.WriteByte(')')
	return b.String(), nil
}

// emitInt64Lit renders v with explicit width using INT64_C so the
// generated source carries the value's type into mixed contexts
// (e.g. comparison operands). INT64_MIN is special-cased because
// `INT64_C(-9223372036854775808)` would lex as `-(9223372036854775808)`
// and trip the warning "integer literal is too large".
func emitInt64Lit(v int64) string {
	if v == -1<<63 {
		return "(-INT64_C(9223372036854775807) - INT64_C(1))"
	}
	if v < 0 {
		return "-INT64_C(" + strconv.FormatInt(-v, 10) + ")"
	}
	return "INT64_C(" + strconv.FormatInt(v, 10) + ")"
}

// emitFloatLit renders v through Go's strconv.FormatFloat 'g' -1 64
// then appends a typed suffix-free form ("(double)(<literal>)") so
// the C compiler does not narrow it to float. The literal itself is
// always a finite, exactly-representable double (NaN/Inf are barred
// by the lowerer until Phase 2.4 hardens the print path).
func emitFloatLit(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	// Go produces "1" for 1.0; C reads that as int. Force the
	// literal to read as double via an explicit decimal point or
	// exponent when needed.
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return "(double)(" + s + ")"
}

// emitBinary picks the C operator string and assembles a fully
// parenthesised infix expression. Boolean operators map to C's
// `&&` / `||`, which preserve short-circuit semantics.
//
// Integer division and modulo are special: Phase 2.3 routes
// `BinDivI64` and `BinModI64` through the libmochi runtime
// helpers (`mochi_div_i64`, `mochi_mod_i64`) so that a `rhs == 0`
// trip exits with `MOCHI_ERR_DIVZERO` instead of triggering C
// undefined behaviour (SIGFPE on most ISAs). Float division and
// every other op keep their infix form.
func emitBinary(v *aotir.BinaryExpr) (string, error) {
	left, err := emitExpr(v.Left)
	if err != nil {
		return "", err
	}
	right, err := emitExpr(v.Right)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.BinDivI64:
		return "mochi_div_i64(" + left + ", " + right + ")", nil
	case aotir.BinModI64:
		return "mochi_mod_i64(" + left + ", " + right + ")", nil
	case aotir.BinEqStr:
		return "(strcmp(" + left + ", " + right + ") == 0)", nil
	case aotir.BinNeStr:
		return "(strcmp(" + left + ", " + right + ") != 0)", nil
	case aotir.BinStrCat:
		return "mochi_str_cat(" + left + ", " + right + ")", nil
	case aotir.BinEqRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "mochi_eq_" + recName + "(" + left + ", " + right + ")", nil
	case aotir.BinNeRec:
		recName, err := binaryRecordName(v)
		if err != nil {
			return "", err
		}
		return "(!mochi_eq_" + recName + "(" + left + ", " + right + "))", nil
	case aotir.BinEqList:
		elem := exprListElemType(v.Left)
		if elem == aotir.TypeInvalid {
			elem = exprListElemType(v.Right)
		}
		suf, err := scalarListInnerSuffix(elem)
		if err != nil {
			return "", fmt.Errorf("list eq elem: %w", err)
		}
		return "mochi_eq_mochi_list_" + suf + "(" + left + ", " + right + ")", nil
	case aotir.BinNeList:
		elem := exprListElemType(v.Left)
		if elem == aotir.TypeInvalid {
			elem = exprListElemType(v.Right)
		}
		suf, err := scalarListInnerSuffix(elem)
		if err != nil {
			return "", fmt.Errorf("list ne elem: %w", err)
		}
		return "(!mochi_eq_mochi_list_" + suf + "(" + left + ", " + right + "))", nil
	case aotir.BinEqMap:
		key := exprMapKeyType(v.Left)
		val := exprMapValueType(v.Left)
		lve := exprMapListValueElemType(v.Left)
		if key == aotir.TypeInvalid {
			key = exprMapKeyType(v.Right)
		}
		if val == aotir.TypeInvalid {
			val = exprMapValueType(v.Right)
		}
		if lve == aotir.TypeInvalid {
			lve = exprMapListValueElemType(v.Right)
		}
		suf, err := mapSuffix(key, val, lve)
		if err != nil {
			return "", fmt.Errorf("map eq: %w", err)
		}
		return "mochi_eq_mochi_map_" + suf + "(" + left + ", " + right + ")", nil
	case aotir.BinNeMap:
		key := exprMapKeyType(v.Left)
		val := exprMapValueType(v.Left)
		lve := exprMapListValueElemType(v.Left)
		if key == aotir.TypeInvalid {
			key = exprMapKeyType(v.Right)
		}
		if val == aotir.TypeInvalid {
			val = exprMapValueType(v.Right)
		}
		if lve == aotir.TypeInvalid {
			lve = exprMapListValueElemType(v.Right)
		}
		suf, err := mapSuffix(key, val, lve)
		if err != nil {
			return "", fmt.Errorf("map ne: %w", err)
		}
		return "(!mochi_eq_mochi_map_" + suf + "(" + left + ", " + right + "))", nil
	}
	op, err := cBinOp(v.Op)
	if err != nil {
		return "", err
	}
	return "(" + left + " " + op + " " + right + ")", nil
}

// binaryRecordName recovers the record's name from either side of a
// record-typed eq/ne. The lowerer guarantees both operands carry the
// same record name (the verifier rejects mismatches), so reading
// from the left side is sufficient; the right side is consulted as a
// fallback for defensive emit-time diagnostics.
func binaryRecordName(v *aotir.BinaryExpr) (string, error) {
	if n := exprRecordName(v.Left); n != "" {
		return n, nil
	}
	if n := exprRecordName(v.Right); n != "" {
		return n, nil
	}
	return "", fmt.Errorf("record eq without RecordName on either operand")
}

// exprRecordName extracts the record name from a record-typed Expr.
// Mirrors lower.exprRecordName so emit can reach the same answer
// without depending on the lowerer package.
func exprRecordName(e aotir.Expr) string {
	switch x := e.(type) {
	case *aotir.VarRef:
		return x.RecordName
	case *aotir.RecordLit:
		return x.TypeName
	case *aotir.FieldAccess:
		return x.ResultRecordName
	case *aotir.CallExpr:
		return x.ResultRecordName
	}
	return ""
}

// exprListElemType extracts the element type from a list-typed Expr.
func exprListElemType(e aotir.Expr) aotir.Type {
	switch v := e.(type) {
	case *aotir.VarRef:
		return v.ElemType
	case *aotir.ListLit:
		return v.ElemType
	case *aotir.CallExpr:
		return v.ResultElemType
	}
	return aotir.TypeInvalid
}

// exprMapKeyType extracts the key type from a map-typed Expr.
func exprMapKeyType(e aotir.Expr) aotir.Type {
	switch v := e.(type) {
	case *aotir.VarRef:
		return v.KeyType
	case *aotir.MapLit:
		return v.KeyType
	case *aotir.CallExpr:
		return v.ResultKeyType
	}
	return aotir.TypeInvalid
}

// exprMapValueType extracts the value type from a map-typed Expr.
func exprMapValueType(e aotir.Expr) aotir.Type {
	switch v := e.(type) {
	case *aotir.VarRef:
		return v.ValueType
	case *aotir.MapLit:
		return v.ValueType
	case *aotir.CallExpr:
		return v.ResultValueType
	}
	return aotir.TypeInvalid
}

// exprMapListValueElemType extracts the list-value inner element type from
// a map-typed Expr whose value type is TypeList (used for map<K,list<V>>).
func exprMapListValueElemType(e aotir.Expr) aotir.Type {
	switch v := e.(type) {
	case *aotir.VarRef:
		return v.ListValueElemType
	case *aotir.MapLit:
		return v.ListValueElemType
	case *aotir.CallExpr:
		return v.ResultListValueElemType
	}
	return aotir.TypeInvalid
}

func cBinOp(op aotir.BinOp) (string, error) {
	switch op {
	case aotir.BinAddI64, aotir.BinAddF64:
		return "+", nil
	case aotir.BinSubI64, aotir.BinSubF64:
		return "-", nil
	case aotir.BinMulI64, aotir.BinMulF64:
		return "*", nil
	case aotir.BinDivI64, aotir.BinDivF64:
		return "/", nil
	case aotir.BinModI64:
		return "%", nil
	case aotir.BinEqI64, aotir.BinEqF64, aotir.BinEqBool:
		return "==", nil
	case aotir.BinNeI64, aotir.BinNeF64, aotir.BinNeBool:
		return "!=", nil
	case aotir.BinLtI64, aotir.BinLtF64:
		return "<", nil
	case aotir.BinLeI64, aotir.BinLeF64:
		return "<=", nil
	case aotir.BinGtI64, aotir.BinGtF64:
		return ">", nil
	case aotir.BinGeI64, aotir.BinGeF64:
		return ">=", nil
	case aotir.BinAndBool:
		return "&&", nil
	case aotir.BinOrBool:
		return "||", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled BinOp %d", op)
}

func emitUnary(v *aotir.UnaryExpr) (string, error) {
	operand, err := emitExpr(v.Operand)
	if err != nil {
		return "", err
	}
	switch v.Op {
	case aotir.UnNegI64, aotir.UnNegF64:
		return "(-" + operand + ")", nil
	case aotir.UnNotBool:
		return "(!" + operand + ")", nil
	}
	return "", fmt.Errorf("transpiler3/c/emit: unhandled UnOp %d", v.Op)
}

