// emitRecordLit renders a RecordLit as a C99 compound literal with
// designated initialisers, e.g. `(struct mochi_Pt){.x=1, .y=2}`. The
// lowerer has already reordered fields into record-decl order so the
// generated source is byte-identical for byte-identical inputs.
func emitRecordLit(v *aotir.RecordLit) (string, error) {
	var b strings.Builder
	b.WriteString("(")
	b.WriteString(cRecordTypeName(v.TypeName))
	b.WriteString("){")
	for i, f := range v.Fields {
		if i > 0 {
			b.WriteString(", ")
		}
		val, err := emitExpr(f.Value)
		if err != nil {
			return "", fmt.Errorf("record %q field %q: %w", v.TypeName, f.Name, err)
		}
		fmt.Fprintf(&b, ".%s = %s", f.Name, val)
	}
	b.WriteString("}")
	return b.String(), nil
}

// emitFieldAccess renders a FieldAccess as `(receiver).field`. The
// receiver is wrapped in parens so a literal receiver (e.g.
// `Pt{...}.x`) parses correctly in C, where compound-literal then
// `.member` is an unusual but valid idiom.
func emitFieldAccess(v *aotir.FieldAccess) (string, error) {
	recv, err := emitExpr(v.Receiver)
	if err != nil {
		return "", fmt.Errorf("field %q: %w", v.FieldName, err)
	}
	return "(" + recv + ")." + v.FieldName, nil
}

// emitRecordDecls renders the file-scope `struct mochi_<Name> {...}`
// declarations plus a per-record equality helper that callers can
// invoke via BinEqRec / BinNeRec. Phase 3.0 keeps the helper
// branchless and inline-friendly: it returns `int` (0/1) and
// compares each field with the appropriate primitive operator (==
// for scalars, strcmp for strings). Nested records are gated out by
// the lowerer, so no recursive eq call is generated yet.
func emitRecordDecls(b *strings.Builder, recs []*aotir.RecordDecl) error {
	if len(recs) == 0 {
		return nil
	}
	indices := make([]int, len(recs))
	for i := range recs {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return recs[indices[i]].Name < recs[indices[j]].Name
	})
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "%s {\n", cRecordTypeName(r.Name))
		for _, f := range r.Fields {
			cT, err := cTypeWithRec(f.Type, f.RecordName)
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			fmt.Fprintf(b, "    %s %s;\n", cT, f.Name)
		}
		b.WriteString("};\n\n")
	}
	for _, idx := range indices {
		r := recs[idx]
		fmt.Fprintf(b, "static int mochi_eq_%s(%s a, %s b) {\n",
			r.Name, cRecordTypeName(r.Name), cRecordTypeName(r.Name))
		if len(r.Fields) == 0 {
			b.WriteString("    (void)a; (void)b;\n    return 1;\n}\n\n")
			continue
		}
		b.WriteString("    return ")
		for i, f := range r.Fields {
			if i > 0 {
				b.WriteString(" && ")
			}
			eq, err := fieldEqExpr(f, "a", "b")
			if err != nil {
				return fmt.Errorf("record %q field %q: %w", r.Name, f.Name, err)
			}
			b.WriteString(eq)
		}
		b.WriteString(";\n}\n\n")
	}
	return nil
}

// fieldEqExpr renders the equality predicate for one record field
// between two operands `a` and `b`. Strings compare byte-wise via
// strcmp; bool/int/float compare with ==; nested records (gated out
// in 3.0) would recurse into mochi_eq_<Name>.
func fieldEqExpr(f aotir.RecordField, a, b string) (string, error) {
	la := "(" + a + ")." + f.Name
	lb := "(" + b + ")." + f.Name
	switch f.Type {
	case aotir.TypeInt, aotir.TypeFloat, aotir.TypeBool:
		return "(" + la + " == " + lb + ")", nil
	case aotir.TypeString:
		return "(strcmp(" + la + ", " + lb + ") == 0)", nil
	case aotir.TypeRecord:
		return "mochi_eq_" + f.RecordName + "(" + la + ", " + lb + ")", nil
	}
	return "", fmt.Errorf("no eq for field type %s", f.Type)
}

