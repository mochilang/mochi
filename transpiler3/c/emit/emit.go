// Emit renders prog as a single ISO C23 translation unit.
//
// Phase 1 surface: a fixed prologue that includes mochi/print.h,
// then one C function per aotir.Function (entry-point function
// becomes int main(void)), then a trailing newline. Phase 2.0
// extends the expression grammar to scalar literals plus typed
// binary/unary operators. Phase 2.1 adds let/var declarations,
// assignment, if/else, while, break, continue, and bare return
// from main.
//
// Phase 17 reproducibility: functions are emitted in
// sorted-by-Name order; the C source is byte-identical for
// byte-identical inputs.
//
// The output is intended to compile clean under
// `cc -std=c2x -Wall -Wextra -pedantic`. No GNU extensions are
// emitted; the only header dependency is the libmochi runtime.
func Emit(prog *aotir.Program) (string, error) {
	if prog == nil {
		return "", fmt.Errorf("transpiler3/c/emit: nil Program")
	}
	if err := aotir.Verify(prog); err != nil {
		return "", fmt.Errorf("transpiler3/c/emit: verify: %w", err)
	}

	var b strings.Builder
	b.WriteString("/* generated by mochi transpiler3/c (MEP-45 Phase 5.0). */\n")
	b.WriteString("#include <stdint.h>\n")
	b.WriteString("#include <string.h>\n")
	b.WriteString("#include \"mochi/print.h\"\n")
	b.WriteString("#include \"mochi/errors.h\"\n")
	b.WriteString("#include \"mochi/list.h\"\n")
	b.WriteString("#include \"mochi/map.h\"\n")
	b.WriteString("#include \"mochi/strings.h\"\n")
	listRecNames := collectListRecordElems(prog)
	listListInners := collectListListInners(prog)
	listMapPairs := collectListOfMapPairs(prog)
	mapOfListPairs := collectMapOfListInners(prog)
	// The _values() helper for every map<K,list<V>> returns list<list<V>>,
	// so the mochi_list_list_<inner> struct must be present. Ensure the
	// inner suffix from each map-of-list pair is included in the
	// list-of-list emission pass (which runs first).
	{
		innerSet := map[string]struct{}{}
		for _, s := range listListInners {
			innerSet[s] = struct{}{}
		}
		for _, p := range mapOfListPairs {
			suf, err := scalarListInnerSuffix(p.inner)
			if err != nil {
				continue
			}
			if _, ok := innerSet[suf]; !ok {
				innerSet[suf] = struct{}{}
				listListInners = append(listListInners, suf)
			}
		}
	}
	if len(listRecNames) > 0 || len(listListInners) > 0 || len(listMapPairs) > 0 || len(mapOfListPairs) > 0 {
		// malloc lives in <stdlib.h>; only pull it in when we actually
		// emit list<R>, list<list<T>>, list<map<K,V>>, or map<K,list<V>>
		// helpers so user-defined functions whose names would collide with
		// stdlib (e.g. `abs`) keep working.
		b.WriteString("#include <stdlib.h>\n")
	}
	b.WriteString("\n")

	if err := emitRecordDecls(&b, prog.Records); err != nil {
		return "", err
	}

	if err := emitUnionDecls(&b, prog.Unions); err != nil {
		return "", err
	}

	// Phase 5.0: function pointer typedefs for fun types.
	funSigs := collectFunSigs(prog)
	if err := emitFunTypedefs(&b, funSigs); err != nil {
		return "", err
	}

	if err := emitListRecordHelpers(&b, listRecNames); err != nil {
		return "", err
	}

	if err := emitListOfListHelpers(&b, listListInners); err != nil {
		return "", err
	}

	// list<map<K,V>> TU-local helpers (Phase 3.4f): must come after any
	// mochi_map_<K>_<V> struct is available (libmochi exports it), and
	// before any function that uses a list<map<K,V>> value.
	if err := emitListOfMapHelpers(&b, listMapPairs); err != nil {
		return "", err
	}

	// map<K,list<V>> TU-local helpers must come after list-of-list
	// helpers because the values() function returns list<list<V>>.
	if err := emitMapOfListHelpers(&b, mapOfListPairs); err != nil {
		return "", err
	}

	// List equality helpers (mochi_eq_mochi_list_<elem>) must come before
	// any function that uses list == / !=.
	listEqElems := collectListEqElems(prog)
	if err := emitListEqHelpers(&b, listEqElems); err != nil {
		return "", err
	}

	// Map equality helpers (mochi_eq_mochi_map_<K>_<V>) must come before
	// any function that uses map == / !=. When the value type is TypeList
	// the helper references a mochi_eq_mochi_list_<inner> helper, so list
	// equality helpers are emitted first (above).
	mapEqPairs := collectMapEqPairs(prog)
	if err := emitMapEqHelpers(&b, mapEqPairs); err != nil {
		return "", err
	}

	indices := make([]int, len(prog.Functions))
	for i := range prog.Functions {
		indices[i] = i
	}
	sort.SliceStable(indices, func(i, j int) bool {
		return prog.Functions[indices[i]].Name < prog.Functions[indices[j]].Name
	})

	// Forward-declare every non-entry function so order of mutual
	// recursion doesn't matter to the C compiler. The entry function
	// uses the C `int main(void)` signature and is never called from
	// other functions, so it gets no prototype.
	hasUserFn := false
	for _, idx := range indices {
		if idx == prog.Main {
			continue
		}
		fn := prog.Functions[idx]
		proto, err := emitFunctionPrototype(fn)
		if err != nil {
			return "", err
		}
		b.WriteString(proto)
		b.WriteString(";\n")
		hasUserFn = true
	}
	if hasUserFn {
		b.WriteString("\n")
	}

	for _, idx := range indices {
		fn := prog.Functions[idx]
		isEntry := idx == prog.Main
		if err := emitFunction(&b, fn, isEntry); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

// emitFunctionPrototype renders the C declarator portion of a
// non-entry function (return type, name, parameter list). Used both
// for the file-scope forward declarations and for the function body
// definitions. Keeping the two in lockstep avoids drift between
// prototype and definition.
func emitFunctionPrototype(fn *aotir.Function) (string, error) {
	var ret string
	if fn.ReturnType == aotir.TypeFun {
		if fn.ReturnFunSig == nil {
			return "", fmt.Errorf("function %q return: TypeFun with nil ReturnFunSig", fn.Name)
		}
		ret = fn.ReturnFunSig.FunTypeName()
	} else {
		retRecOrUnion := fn.ReturnRecordName
		if fn.ReturnType == aotir.TypeUnion {
			retRecOrUnion = fn.ReturnUnionName
		}
		var err error
		ret, err = cReturnType(fn.ReturnType, retRecOrUnion, fn.ReturnElemType, fn.ReturnElemRecordName, fn.ReturnInnerElemType, fn.ReturnMapElemKeyType, fn.ReturnMapElemValueType, fn.ReturnKeyType, fn.ReturnValueType, fn.ReturnListValueElemType)
		if err != nil {
			return "", fmt.Errorf("function %q return: %w", fn.Name, err)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "static %s %s(", ret, fn.Name)
	if len(fn.Params) == 0 {
		b.WriteString("void")
	} else {
		for i, p := range fn.Params {
			if i > 0 {
				b.WriteString(", ")
			}
			var pt string
			if p.Type == aotir.TypeFun {
				if p.FunSig == nil {
					return "", fmt.Errorf("function %q param %q: TypeFun with nil FunSig", fn.Name, p.Name)
				}
				pt = p.FunSig.FunTypeName()
			} else {
				recOrUnion := p.RecordName
				if p.Type == aotir.TypeUnion {
					recOrUnion = p.UnionName
				}
				var err error
				pt, err = cTypeFull(p.Type, recOrUnion, p.ElemType, p.ElemRecordName, p.InnerElemType, p.MapElemKeyType, p.MapElemValueType, p.KeyType, p.ValueType, p.ListValueElemType)
				if err != nil {
					return "", fmt.Errorf("function %q param %q: %w", fn.Name, p.Name, err)
				}
			}
			fmt.Fprintf(&b, "%s %s", pt, p.Name)
		}
	}
	b.WriteString(")")
	return b.String(), nil
}

// cReturnType maps an aotir.Type to its C return-type spelling. Unit
// is `void`; the scalar types share the cType spellings; record types
// render as `struct mochi_<Name>` value (returned by value); list and
// map types render as `mochi_list_<T>` / `mochi_map_<K>_<V>` values.
// For list<R>, elemRecName carries the element record identity so
// the per-record helper instantiation suffix can be resolved. For
// list<list<T>> (Phase 3.4b), innerElem carries the inner T so the
// suffix resolves to `list_<innerSuf>`. For map<K,list<V>> (Phase
// 3.4e), listValueElemType carries the inner scalar of the list value.
// For list<map<K,V>> (Phase 3.4f), mapElemKey/mapElemValue carry K/V.
func cReturnType(t aotir.Type, recName string, elemType aotir.Type, elemRecName string, innerElem aotir.Type, mapElemKey aotir.Type, mapElemValue aotir.Type, keyType aotir.Type, valueType aotir.Type, listValueElemType aotir.Type) (string, error) {
	if t == aotir.TypeUnit {
		return "void", nil
	}
	return cTypeFull(t, recName, elemType, elemRecName, innerElem, mapElemKey, mapElemValue, keyType, valueType, listValueElemType)
}

func emitFunction(b *strings.Builder, fn *aotir.Function, entry bool) error {
	if entry {
		b.WriteString("int main(void) {\n")
	} else {
		proto, err := emitFunctionPrototype(fn)
		if err != nil {
			return err
		}
		b.WriteString(proto)
		b.WriteString(" {\n")
	}
	for _, st := range fn.Body.Statements {
		if err := emitStmt(b, st, "    "); err != nil {
			return err
		}
	}
	if entry && !endsWithReturn(fn.Body) {
		b.WriteString("    return 0;\n")
	}
	b.WriteString("}\n")
	return nil
}

// endsWithReturn reports whether the last statement in a block is a
// ReturnStmt, so the entry emitter can skip the trailing `return 0;`
// it would otherwise add. Avoids unreachable-code diagnostics on
// programs whose Mochi source ends in an explicit `return`.
func endsWithReturn(b *aotir.Block) bool {
	if b == nil || len(b.Statements) == 0 {
		return false
	}
	_, ok := b.Statements[len(b.Statements)-1].(*aotir.ReturnStmt)
	return ok
}

// emitStmt writes one statement preceded by `indent` and a trailing
// newline. Nested blocks (if/while bodies) inherit indent+"    ".
func emitStmt(b *strings.Builder, st aotir.Stmt, indent string) error {
	switch s := st.(type) {
	case *aotir.CallStmt:
		b.WriteString(indent)
		b.WriteString(s.Func)
		b.WriteString("(")
		for i, arg := range s.Args {
			if i > 0 {
				b.WriteString(", ")
			}
			es, err := emitExpr(arg)
			if err != nil {
				return err
			}
			b.WriteString(es)
		}
		b.WriteString(");\n")
		return nil
	case *aotir.LetStmt:
		// Phase 5.0: TypeFun uses FunSig.FunTypeName() directly.
		var ts string
		if s.VarType == aotir.TypeFun {
			if s.FunSig == nil {
				return fmt.Errorf("let %q: TypeFun with nil FunSig", s.Name)
			}
			ts = s.FunSig.FunTypeName()
		} else {
			// For TypeUnion, recName carries the union name (not a record name).
			recOrUnion := s.RecordName
			if s.VarType == aotir.TypeUnion {
				recOrUnion = s.UnionName
			}
			var err error
			ts, err = cTypeFull(s.VarType, recOrUnion, s.ElemType, s.ElemRecordName, s.InnerElemType, s.MapElemKeyType, s.MapElemValueType, s.KeyType, s.ValueType, s.ListValueElemType)
			if err != nil {
				return fmt.Errorf("let %q: %w", s.Name, err)
			}
		}
		if s.Init == nil {
			// Result-var pre-declaration from match expression lowering.
			b.WriteString(indent)
			if !s.Mutable {
				b.WriteString("const ")
			}
			fmt.Fprintf(b, "%s %s;\n", ts, s.Name)
			return nil
		}
		init, err := emitExpr(s.Init)
		if err != nil {
			return err
		}
		b.WriteString(indent)
		if !s.Mutable {
			b.WriteString("const ")
		}
		fmt.Fprintf(b, "%s %s = %s;\n", ts, s.Name, init)
		return nil
	case *aotir.MatchStmt:
		return emitMatchStmt(b, s, indent)
	case *aotir.AssignStmt:
		val, err := emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s = %s;\n", indent, s.Name, val)
		return nil
	case *aotir.IfStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Then, indent+"    "); err != nil {
			return err
		}
		if s.Else != nil {
			fmt.Fprintf(b, "%s} else {\n", indent)
			if err := emitBlock(b, s.Else, indent+"    "); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.WhileStmt:
		cond, err := emitExpr(s.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%swhile (%s) {\n", indent, cond)
		if err := emitBlock(b, s.Body, indent+"    "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.ForRangeStmt:
		start, err := emitExpr(s.Start)
		if err != nil {
			return err
		}
		end, err := emitExpr(s.End)
		if err != nil {
			return err
		}
		// Half-open [start, end): the induction variable is declared
		// inside the for header so the C scope mirrors Mochi's. The
		// end expression is hoisted into a const sentinel so any
		// side effect or function call evaluates exactly once at
		// loop entry, matching vm3 semantics.
		sentinel := "__mochi_end_" + s.Var
		fmt.Fprintf(b, "%s{\n", indent)
		fmt.Fprintf(b, "%s    const int64_t %s = %s;\n", indent, sentinel, end)
		fmt.Fprintf(b, "%s    for (int64_t %s = %s; %s < %s; %s++) {\n",
			indent, s.Var, start, s.Var, sentinel, s.Var)
		if err := emitBlock(b, s.Body, indent+"        "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s    }\n", indent)
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.ForEachStmt:
		listExpr, err := emitExpr(s.List)
		if err != nil {
			return err
		}
		// For list<list<T>>, the induction variable's C type is the
		// inner list struct `mochi_list_<inner>`. For list<map<K,V>>,
		// it is `mochi_map_<K>_<V>`. The outer list's runtime suffix
		// is `list_<inner>` or `map_<K>_<V>` accordingly.
		var elemC string
		switch s.ElemType {
		case aotir.TypeList:
			innerSuf, err := scalarListInnerSuffix(s.InnerElemType)
			if err != nil {
				return fmt.Errorf("foreach %q: %w", s.Var, err)
			}
			elemC = "mochi_list_" + innerSuf
		case aotir.TypeMap:
			mapSuf, err := mapSuffix(s.MapElemKeyType, s.MapElemValueType, aotir.TypeInvalid)
			if err != nil {
				return fmt.Errorf("foreach %q: %w", s.Var, err)
			}
			elemC = "mochi_map_" + mapSuf
		default:
			ec, err := cTypeFull(s.ElemType, s.ElemRecordName, aotir.TypeInvalid, "", aotir.TypeInvalid, aotir.TypeInvalid, aotir.TypeInvalid, aotir.TypeInvalid, aotir.TypeInvalid, aotir.TypeInvalid)
			if err != nil {
				return fmt.Errorf("foreach %q: %w", s.Var, err)
			}
			elemC = ec
		}
		listSuf, err := listSuffix(s.ElemType, s.ElemRecordName, s.InnerElemType, s.MapElemKeyType, s.MapElemValueType)
		if err != nil {
			return fmt.Errorf("foreach %q: %w", s.Var, err)
		}
		// The list expression is evaluated once and bound to a
		// const sentinel so a callee-returning-a-list source does
		// not re-execute per iteration. The element binding is a
		// fresh `elemC` per loop step, matching Mochi value
		// semantics for the induction variable.
		sentinel := "__mochi_list_" + s.Var
		fmt.Fprintf(b, "%s{\n", indent)
		fmt.Fprintf(b, "%s    const mochi_list_%s %s = %s;\n", indent, listSuf, sentinel, listExpr)
		fmt.Fprintf(b, "%s    const int64_t __mochi_len_%s = mochi_list_%s_len(%s);\n", indent, s.Var, listSuf, sentinel)
		fmt.Fprintf(b, "%s    for (int64_t __mochi_i_%s = 0; __mochi_i_%s < __mochi_len_%s; __mochi_i_%s++) {\n",
			indent, s.Var, s.Var, s.Var, s.Var)
		fmt.Fprintf(b, "%s        const %s %s = mochi_list_%s_index(%s, __mochi_i_%s);\n",
			indent, elemC, s.Var, listSuf, sentinel, s.Var)
		if err := emitBlock(b, s.Body, indent+"        "); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s    }\n", indent)
		fmt.Fprintf(b, "%s}\n", indent)
		return nil
	case *aotir.BreakStmt:
		fmt.Fprintf(b, "%sbreak;\n", indent)
		return nil
	case *aotir.ContinueStmt:
		fmt.Fprintf(b, "%scontinue;\n", indent)
		return nil
	case *aotir.ReturnStmt:
		if s.Value == nil {
			// A bare `return` is only legal in a unit-return function
			// (main or a user fn returning unit). The verifier already
			// enforces this; emit lowers it to `return 0;` from main
			// and `return;` from any other unit-return function.
			//
			// Phase 2.2 doesn't yet expose unit-return user functions
			// from the surface (every user fn must have an explicit
			// non-unit return type), so the only context that hits
			// this branch is main.
			fmt.Fprintf(b, "%sreturn 0;\n", indent)
			return nil
		}
		val, err := emitExpr(s.Value)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sreturn %s;\n", indent, val)
		return nil
	}
	return fmt.Errorf("transpiler3/c/emit: unhandled Stmt %T", st)
}

func emitBlock(b *strings.Builder, blk *aotir.Block, indent string) error {
	if blk == nil {
		return nil
	}
	for _, st := range blk.Statements {
		if err := emitStmt(b, st, indent); err != nil {
			return err
		}
	}
	return nil
}

// cType maps a scalar aotir.Type to its C declaration spelling. The
// bool ABI uses C `int` (0/1) so the runtime print signature lines
// up without an explicit cast. cType does not accept TypeRecord;
// callers that may see records must use cTypeWithRec so the record's
// identity is plumbed through.
func cType(t aotir.Type) (string, error) {
	switch t {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("no C declaration for %s", t)
}

// cTypeWithRec extends cType with TypeRecord support. The record's
// identity rides on a parallel string at every IR site that can hold
// a record value (LetStmt.RecordName, Param.RecordName, etc.); the
// caller passes it through so emit can render the correct
// `struct mochi_<Name>` spelling.
func cTypeWithRec(t aotir.Type, recName string) (string, error) {
	if t == aotir.TypeRecord {
		if recName == "" {
			return "", fmt.Errorf("TypeRecord without RecordName")
		}
		return cRecordTypeName(recName), nil
	}
	if t == aotir.TypeUnion {
		if recName == "" {
			return "", fmt.Errorf("TypeUnion without UnionName")
		}
		return cUnionTypeName(recName), nil
	}
	return cType(t)
}

// cUnionTypeName returns the C struct typedef name for a Mochi union.
// Convention: `pkg_<Name>` (matches MEP-45 §4 emit spec).
func cUnionTypeName(name string) string { return "pkg_" + name }

// cUnionCtorName returns the inline constructor name for one variant.
func cUnionCtorName(unionName, variantName string) string {
	return "pkg_" + unionName + "_" + variantName
}

// cTypeFull extends cTypeWithRec with TypeList and TypeMap support.
// The element type rides on a parallel field for lists; key + value
// types ride on parallel fields for maps. The caller passes them
// through so emit can render the correct `mochi_list_<T>` /
// `mochi_map_<K>_<V>` spelling. For list<R> (Phase 3.4a), the
// elemRecName parameter carries the element record's identity. For
// list<list<T>> (Phase 3.4b), innerElem carries the inner T. For
// map<K,list<V>> (Phase 3.4e), listValueElemType carries the inner
// scalar of the list value type. For list<map<K,V>> (Phase 3.4f),
// mapElemKey and mapElemValue carry the map's K and V.
func cTypeFull(t aotir.Type, recName string, elemType aotir.Type, elemRecName string, innerElem aotir.Type, mapElemKey aotir.Type, mapElemValue aotir.Type, keyType aotir.Type, valueType aotir.Type, listValueElemType aotir.Type) (string, error) {
	if t == aotir.TypeList {
		suf, err := listSuffix(elemType, elemRecName, innerElem, mapElemKey, mapElemValue)
		if err != nil {
			return "", err
		}
		return "mochi_list_" + suf, nil
	}
	if t == aotir.TypeMap {
		suf, err := mapSuffix(keyType, valueType, listValueElemType)
		if err != nil {
			return "", err
		}
		return "mochi_map_" + suf, nil
	}
	return cTypeWithRec(t, recName)
}

// listSuffix returns the per-T runtime suffix for a list element
// type: i64 / f64 / bool / str for the four scalar primitives, the
// record's own name for list<R> (Phase 3.4a), "list_<innerSuf>"
// for list<list<T>> (Phase 3.4b), or "map_<K>_<V>" for
// list<map<K,V>> (Phase 3.4f). The suffix selects the matching
// `mochi_list_<T>_*` helper family. Scalar suffixes resolve to
// libmochi exports; record and list-of-list/list-of-map suffixes
// resolve to per-(outer,inner) helpers emitted into the same
// translation unit's prologue.
func listSuffix(elem aotir.Type, elemRecName string, innerElem aotir.Type, mapElemKey aotir.Type, mapElemValue aotir.Type) (string, error) {
	switch elem {
	case aotir.TypeInt:
		return "i64", nil
	case aotir.TypeFloat:
		return "f64", nil
	case aotir.TypeBool:
		return "bool", nil
	case aotir.TypeString:
		return "str", nil
	case aotir.TypeRecord:
		if elemRecName == "" {
			return "", fmt.Errorf("list of record requires non-empty record name")
		}
		return elemRecName, nil
	case aotir.TypeList:
		inner, err := scalarListInnerSuffix(innerElem)
		if err != nil {
			return "", err
		}
		return "list_" + inner, nil
	case aotir.TypeMap:
		// Phase 3.4f: list<map<K,V>>
		suf, err := mapSuffix(mapElemKey, mapElemValue, aotir.TypeInvalid)
		if err != nil {
			return "", fmt.Errorf("list<map<K,V>> suffix: %w", err)
		}
		return "map_" + suf, nil
	}
	return "", fmt.Errorf("no list runtime for element type %s", elem)
}

// scalarListInnerSuffix returns the libmochi suffix for the inner T
// of a list<list<T>>. Phase 3.4b restricts T to the four scalar
// primitives, so anything else is a phase-bounded error.
func scalarListInnerSuffix(inner aotir.Type) (string, error) {
	switch inner {
	case aotir.TypeInt:
		return "i64", nil
	case aotir.TypeFloat:
		return "f64", nil
	case aotir.TypeBool:
		return "bool", nil
	case aotir.TypeString:
		return "str", nil
	}
	return "", fmt.Errorf("list<list<T>> inner type %s is not supported in Phase 3.4b", inner)
}

// mapSuffix returns the per-(K,V) runtime suffix used to select the
// `mochi_map_<K>_<V>_*` helper family. Phase 3.2 ships eight libmochi
// combinations (K ∈ {i64, str}, V ∈ {i64, f64, bool, str}). Phase 3.4e
// extends V to list<scalar>, producing TU-local helpers with suffix
// "<K>_list_<inner>" (e.g. "i64_list_i64").
func mapSuffix(key aotir.Type, value aotir.Type, listValueElemType aotir.Type) (string, error) {
	var ks, vs string
	switch key {
	case aotir.TypeInt:
		ks = "i64"
	case aotir.TypeString:
		ks = "str"
	default:
		return "", fmt.Errorf("no map runtime for key type %s", key)
	}
	switch value {
	case aotir.TypeInt:
		vs = "i64"
	case aotir.TypeFloat:
		vs = "f64"
	case aotir.TypeBool:
		vs = "bool"
	case aotir.TypeString:
		vs = "str"
	case aotir.TypeList:
		inner, err := scalarListInnerSuffix(listValueElemType)
		if err != nil {
			return "", fmt.Errorf("map<K,list<V>> inner: %w", err)
		}
		vs = "list_" + inner
	default:
		return "", fmt.Errorf("no map runtime for value type %s", value)
	}
	return ks + "_" + vs, nil
}

// cRecordTypeName returns the C type spelling for a record type
// named `name`. The `mochi_` prefix avoids clashes with arbitrary
// user names and `struct` keeps the spelling self-contained (no
// typedef needed; that would force a sort-by-dependency that 3.0
// doesn't need yet).
func cRecordTypeName(name string) string {
	return "struct mochi_" + name
}

// emitListOfListHelpers walks the Program for every list<list<T>>
// usage and emits a TU-local `mochi_list_list_<innerSuf>` struct plus
// the four canonical helpers (_lit, _append, _index, _len) per unique
// inner suffix. The outer list's data buffer is a heap array of
// `mochi_list_<inner>` structs (each carrying its own data pointer +
// len/cap); the helper memcpys the struct headers, so the inner
// lists' data buffers are aliased rather than deep-copied. Phase
// 3.4b's read-only fixtures never reach into a shared inner via two
// outer-list paths concurrently, so the aliasing is safe for the
// surface that lands here.
func emitListOfListHelpers(b *strings.Builder, inners []string) error {
	if len(inners) == 0 {
		return nil
	}
	sort.Strings(inners)
	for _, inner := range inners {
		innerC := "mochi_list_" + inner
		outer := "mochi_list_list_" + inner
		fmt.Fprintf(b, "typedef struct %s {\n", outer)
		fmt.Fprintf(b, "    %s *data;\n", innerC)
		b.WriteString("    int64_t  len;\n")
		b.WriteString("    int64_t  cap;\n")
		fmt.Fprintf(b, "} %s;\n\n", outer)

		fmt.Fprintf(b, "static %s %s_lit(const %s *xs, int64_t n) {\n", outer, outer, innerC)
		fmt.Fprintf(b, "    %s out = {NULL, n, n};\n", outer)
		b.WriteString("    if (n > 0) {\n")
		fmt.Fprintf(b, "        out.data = (%s *)malloc((size_t)n * sizeof(%s));\n", innerC, innerC)
		b.WriteString("        if (out.data == NULL) { mochi_panic_index(); }\n")
		fmt.Fprintf(b, "        memcpy(out.data, xs, (size_t)n * sizeof(%s));\n", innerC)
		b.WriteString("    }\n")
		b.WriteString("    return out;\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static %s %s_append(%s xs, %s v) {\n", outer, outer, outer, innerC)
		fmt.Fprintf(b, "    %s out = {NULL, xs.len + 1, xs.len + 1};\n", outer)
		fmt.Fprintf(b, "    out.data = (%s *)malloc((size_t)out.cap * sizeof(%s));\n", innerC, innerC)
		b.WriteString("    if (out.data == NULL) { mochi_panic_index(); }\n")
		b.WriteString("    if (xs.len > 0) {\n")
		fmt.Fprintf(b, "        memcpy(out.data, xs.data, (size_t)xs.len * sizeof(%s));\n", innerC)
		b.WriteString("    }\n")
		b.WriteString("    out.data[xs.len] = v;\n")
		b.WriteString("    return out;\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static %s %s_index(%s xs, int64_t i) {\n", innerC, outer, outer)
		b.WriteString("    if (i < 0 || i >= xs.len) { mochi_panic_index(); }\n")
		b.WriteString("    return xs.data[i];\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static int64_t %s_len(%s xs) { return xs.len; }\n\n", outer, outer)
	}
	return nil
}

// collectListListInners walks the program collecting every distinct
// inner scalar suffix (i64/f64/bool/str) used as the inner T of a
// list<list<T>>. Covers function signatures and every statement /
// expression carrier that can hold a list<list<T>> value.
func collectListListInners(prog *aotir.Program) []string {
	set := map[string]struct{}{}
	visit := func(elem aotir.Type, inner aotir.Type) {
		if elem != aotir.TypeList {
			return
		}
		suf, err := scalarListInnerSuffix(inner)
		if err != nil {
			return
		}
		set[suf] = struct{}{}
	}
	for _, fn := range prog.Functions {
		if fn == nil {
			continue
		}
		visit(fn.ReturnElemType, fn.ReturnInnerElemType)
		for _, p := range fn.Params {
			visit(p.ElemType, p.InnerElemType)
		}
		walkBlockInner(fn.Body, visit)
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	return out
}

// listOfMapPair identifies a unique (map key type, map value type) pair
