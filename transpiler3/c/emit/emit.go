// emitMapLit renders a MapLit as a `mochi_map_<K>_<V>_lit` call.
// Keys and values are held in two parallel C99 compound-literal
// arrays; the runtime helper makes a heap-allocated copy. An empty
// literal still needs a non-empty placeholder array (size-0 arrays
// are an ISO C extension), so we emit a single zero-initialised
// dummy element with a length of zero -- the helper's loop never
// touches it.
func emitMapLit(v *aotir.MapLit) (string, error) {
	suf, err := mapSuffix(v.KeyType, v.ValueType, v.ListValueElemType)
	if err != nil {
		return "", fmt.Errorf("map literal: %w", err)
	}
	keyC, err := cMapKeyBufferC(v.KeyType)
	if err != nil {
		return "", fmt.Errorf("map literal: %w", err)
	}
	valC, err := cMapValueBufferC(v.ValueType, v.ListValueElemType)
	if err != nil {
		return "", fmt.Errorf("map literal: %w", err)
	}
	if len(v.Keys) == 0 {
		return fmt.Sprintf("mochi_map_%s_lit((%s[]){0}, (%s[]){0}, INT64_C(0))", suf, keyC, valC), nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "mochi_map_%s_lit((%s[]){", suf, keyC)
	for i, k := range v.Keys {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(k)
		if err != nil {
			return "", fmt.Errorf("map literal key %d: %w", i, err)
		}
		b.WriteString(es)
	}
	fmt.Fprintf(&b, "}, (%s[]){", valC)
	for i, val := range v.Values {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(val)
		if err != nil {
			return "", fmt.Errorf("map literal value %d: %w", i, err)
		}
		b.WriteString(es)
	}
	fmt.Fprintf(&b, "}, INT64_C(%d))", len(v.Keys))
	return b.String(), nil
}

// cMapKeyBufferC returns the C element spelling for the keys array
// passed to `mochi_map_<K>_<V>_lit`. The map runtime declares the
// key-array parameter as `const <KT> *` (with KT = int64_t or
// `const char *`); the compound-literal element type drops the outer
// const so the array is assignable, and the helper signature accepts
// it via the usual array-to-pointer decay.
func cMapKeyBufferC(key aotir.Type) (string, error) {
	switch key {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeString:
		return "const char *", nil
	}
	return "", fmt.Errorf("no map-literal key buffer for key type %s", key)
}

// cMapValueBufferC returns the C element spelling for the values
