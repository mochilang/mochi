// listEqElem identifies a unique scalar element type for list equality helpers.
type listEqElem struct{ elem aotir.Type }

// mapEqPair identifies a unique (key, value, listValueElem) triple for map equality helpers.
type mapEqPair struct {
	key, value  aotir.Type
	listValElem aotir.Type // valid when value==TypeList
}

// collectListEqElems walks the program collecting every distinct list element
// type used in a BinEqList / BinNeList expression. These drive TU-local
// mochi_eq_mochi_list_<elem> helper emission.
func collectListEqElems(prog *aotir.Program) []listEqElem {
	seen := map[aotir.Type]bool{}
	var result []listEqElem
	visit := func(e aotir.Expr) {
		b, ok := e.(*aotir.BinaryExpr)
		if !ok {
			return
		}
		if b.Op != aotir.BinEqList && b.Op != aotir.BinNeList {
			return
		}
		elem := exprListElemType(b.Left)
		if elem == aotir.TypeInvalid {
			elem = exprListElemType(b.Right)
		}
		if elem != aotir.TypeInvalid && !seen[elem] {
			seen[elem] = true
			result = append(result, listEqElem{elem})
		}
	}
	for _, fn := range prog.Functions {
		if fn == nil {
			continue
		}
		walkExprVisit(fn.Body, visit)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].elem < result[j].elem })
	return result
}

// collectMapEqPairs walks the program collecting every distinct (key, value,
// listValElem) triple used in a BinEqMap / BinNeMap expression. These drive
// TU-local mochi_eq_mochi_map_<K>_<V> helper emission.
func collectMapEqPairs(prog *aotir.Program) []mapEqPair {
	type kv struct {
		k, v aotir.Type
		lve  aotir.Type
	}
	seen := map[kv]bool{}
	var result []mapEqPair
	visit := func(e aotir.Expr) {
		b, ok := e.(*aotir.BinaryExpr)
		if !ok {
			return
		}
		if b.Op != aotir.BinEqMap && b.Op != aotir.BinNeMap {
			return
		}
		key := exprMapKeyType(b.Left)
		val := exprMapValueType(b.Left)
		lve := exprMapListValueElemType(b.Left)
		if key == aotir.TypeInvalid {
			key = exprMapKeyType(b.Right)
		}
		if val == aotir.TypeInvalid {
			val = exprMapValueType(b.Right)
		}
		if lve == aotir.TypeInvalid {
			lve = exprMapListValueElemType(b.Right)
		}
		if key != aotir.TypeInvalid && val != aotir.TypeInvalid {
			p := kv{key, val, lve}
			if !seen[p] {
				seen[p] = true
				result = append(result, mapEqPair{key, val, lve})
			}
		}
	}
	for _, fn := range prog.Functions {
		if fn == nil {
			continue
		}
		walkExprVisit(fn.Body, visit)
	}
	sort.Slice(result, func(i, j int) bool {
		if result[i].key != result[j].key {
			return result[i].key < result[j].key
		}
		if result[i].value != result[j].value {
			return result[i].value < result[j].value
		}
		return result[i].listValElem < result[j].listValElem
	})
	return result
}

// walkExprVisit walks all expressions reachable from blk and calls visit on
// each. Used by collectListEqElems and collectMapEqPairs.
func walkExprVisit(blk *aotir.Block, visit func(aotir.Expr)) {
	if blk == nil {
		return
	}
	for _, st := range blk.Statements {
		walkStmtExprVisit(st, visit)
	}
}

func walkStmtExprVisit(st aotir.Stmt, visit func(aotir.Expr)) {
	switch s := st.(type) {
	case *aotir.LetStmt:
		walkExprNodeVisit(s.Init, visit)
	case *aotir.AssignStmt:
		walkExprNodeVisit(s.Value, visit)
	case *aotir.CallStmt:
		for _, a := range s.Args {
			walkExprNodeVisit(a, visit)
		}
	case *aotir.IfStmt:
		walkExprNodeVisit(s.Cond, visit)
		walkExprVisit(s.Then, visit)
		walkExprVisit(s.Else, visit)
	case *aotir.WhileStmt:
		walkExprNodeVisit(s.Cond, visit)
		walkExprVisit(s.Body, visit)
	case *aotir.ForRangeStmt:
		walkExprNodeVisit(s.Start, visit)
		walkExprNodeVisit(s.End, visit)
		walkExprVisit(s.Body, visit)
	case *aotir.ForEachStmt:
		walkExprNodeVisit(s.List, visit)
		walkExprVisit(s.Body, visit)
	case *aotir.ReturnStmt:
		if s.Value != nil {
			walkExprNodeVisit(s.Value, visit)
		}
	}
}

func walkExprNodeVisit(e aotir.Expr, visit func(aotir.Expr)) {
	if e == nil {
		return
	}
	visit(e)
	switch v := e.(type) {
	case *aotir.CallExpr:
		for _, a := range v.Args {
			walkExprNodeVisit(a, visit)
		}
	case *aotir.BinaryExpr:
		walkExprNodeVisit(v.Left, visit)
		walkExprNodeVisit(v.Right, visit)
	case *aotir.UnaryExpr:
		walkExprNodeVisit(v.Operand, visit)
	case *aotir.ListLit:
		for _, el := range v.Elems {
			walkExprNodeVisit(el, visit)
		}
	case *aotir.IndexExpr:
		walkExprNodeVisit(v.Receiver, visit)
		walkExprNodeVisit(v.Index, visit)
	case *aotir.LenExpr:
		walkExprNodeVisit(v.Receiver, visit)
	case *aotir.AppendExpr:
		walkExprNodeVisit(v.Receiver, visit)
		walkExprNodeVisit(v.Value, visit)
	case *aotir.FieldAccess:
		walkExprNodeVisit(v.Receiver, visit)
	case *aotir.RecordLit:
		for _, f := range v.Fields {
			walkExprNodeVisit(f.Value, visit)
		}
	case *aotir.MapLit:
		for _, k := range v.Keys {
			walkExprNodeVisit(k, visit)
		}
		for _, val := range v.Values {
			walkExprNodeVisit(val, visit)
		}
	case *aotir.MapGetExpr:
		walkExprNodeVisit(v.Receiver, visit)
		walkExprNodeVisit(v.Key, visit)
	case *aotir.MapHasExpr:
		walkExprNodeVisit(v.Receiver, visit)
		walkExprNodeVisit(v.Key, visit)
	case *aotir.MapLenExpr:
		walkExprNodeVisit(v.Receiver, visit)
	case *aotir.MapKeysExpr:
		walkExprNodeVisit(v.Receiver, visit)
	case *aotir.MapValuesExpr:
		walkExprNodeVisit(v.Receiver, visit)
	}
}

// emitListEqHelpers emits a TU-local static equality helper for each scalar
// list element type used in list == / != comparisons.
func emitListEqHelpers(b *strings.Builder, elems []listEqElem) error {
	for _, le := range elems {
		suf, err := scalarListInnerSuffix(le.elem)
		if err != nil {
			return fmt.Errorf("list eq: %w", err)
		}
		name := "mochi_list_" + suf
		var cmpExpr string
		if le.elem == aotir.TypeString {
			cmpExpr = "strcmp(a.data[_i], b.data[_i]) != 0"
		} else {
			cmpExpr = "a.data[_i] != b.data[_i]"
		}
		fmt.Fprintf(b, "static int mochi_eq_%s(%s a, %s b) {\n", name, name, name)
		b.WriteString("    if (a.len != b.len) return 0;\n")
		b.WriteString("    for (int64_t _i = 0; _i < a.len; _i++) {\n")
		fmt.Fprintf(b, "        if (%s) return 0;\n", cmpExpr)
		b.WriteString("    }\n    return 1;\n}\n\n")
	}
	return nil
}

// emitMapEqHelpers emits a TU-local static equality helper for each (K,V)
// pair used in map == / != comparisons. For scalar value types the helper
// iterates one map's live entries, checks the other has the same key, and
// compares values. For map<K,list<V>> value types, value comparison uses
// the corresponding mochi_eq_mochi_list_<inner> helper.
func emitMapEqHelpers(b *strings.Builder, pairs []mapEqPair) error {
	for _, p := range pairs {
		suf, err := mapSuffix(p.key, p.value, p.listValElem)
		if err != nil {
			return fmt.Errorf("map eq: %w", err)
		}
		name := "mochi_map_" + suf

		var keyDecl string
		switch p.key {
		case aotir.TypeInt:
			keyDecl = "int64_t _k = a.table[_i].key;"
		case aotir.TypeString:
			keyDecl = "const char *_k = a.table[_i].key;"
		default:
			return fmt.Errorf("map eq: unsupported key type %s", p.key)
		}

		var valCmpExpr string
		switch p.value {
		case aotir.TypeString:
			valCmpExpr = fmt.Sprintf("strcmp(%s_get(b, _k), a.table[_i].value) != 0", name)
		case aotir.TypeList:
			innerSuf, err2 := scalarListInnerSuffix(p.listValElem)
			if err2 != nil {
				return fmt.Errorf("map eq list value: %w", err2)
			}
			listName := "mochi_list_" + innerSuf
			valCmpExpr = fmt.Sprintf("!mochi_eq_%s(%s_get(b, _k), a.table[_i].value)", listName, name)
		default:
			valCmpExpr = fmt.Sprintf("%s_get(b, _k) != a.table[_i].value", name)
		}

		fmt.Fprintf(b, "static int mochi_eq_%s(%s a, %s b) {\n", name, name, name)
		b.WriteString("    if (a.nLive != b.nLive) return 0;\n")
		b.WriteString("    for (int64_t _i = 0; _i < a.cap; _i++) {\n")
		b.WriteString("        if (a.table[_i].hash == 0) continue;\n")
		fmt.Fprintf(b, "        %s\n", keyDecl)
		fmt.Fprintf(b, "        if (!%s_has(b, _k)) return 0;\n", name)
		fmt.Fprintf(b, "        if (%s) return 0;\n", valCmpExpr)
		b.WriteString("    }\n    return 1;\n}\n\n")
	}
	return nil
}

func walkBlockMapOfList(blk *aotir.Block, add func(aotir.Type, aotir.Type, aotir.Type)) {
	if blk == nil {
		return
	}
	for _, st := range blk.Statements {
		walkStmtMapOfList(st, add)
	}
}

func walkStmtMapOfList(st aotir.Stmt, add func(aotir.Type, aotir.Type, aotir.Type)) {
	switch s := st.(type) {
	case *aotir.LetStmt:
		add(s.KeyType, s.ValueType, s.ListValueElemType)
		walkExprMapOfList(s.Init, add)
	case *aotir.AssignStmt:
		walkExprMapOfList(s.Value, add)
	case *aotir.CallStmt:
		for _, a := range s.Args {
			walkExprMapOfList(a, add)
		}
	case *aotir.IfStmt:
		walkExprMapOfList(s.Cond, add)
		walkBlockMapOfList(s.Then, add)
		walkBlockMapOfList(s.Else, add)
	case *aotir.WhileStmt:
		walkExprMapOfList(s.Cond, add)
		walkBlockMapOfList(s.Body, add)
	case *aotir.ForRangeStmt:
		walkExprMapOfList(s.Start, add)
		walkExprMapOfList(s.End, add)
		walkBlockMapOfList(s.Body, add)
	case *aotir.ForEachStmt:
		walkExprMapOfList(s.List, add)
		walkBlockMapOfList(s.Body, add)
	case *aotir.ReturnStmt:
		if s.Value != nil {
			walkExprMapOfList(s.Value, add)
		}
	}
}

func walkExprMapOfList(e aotir.Expr, add func(aotir.Type, aotir.Type, aotir.Type)) {
	if e == nil {
		return
	}
	switch v := e.(type) {
	case *aotir.VarRef:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
	case *aotir.CallExpr:
		add(v.ResultKeyType, v.ResultValueType, v.ResultListValueElemType)
		for _, a := range v.Args {
			walkExprMapOfList(a, add)
		}
	case *aotir.MapLit:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		for _, val := range v.Values {
			walkExprMapOfList(val, add)
		}
	case *aotir.MapGetExpr:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		walkExprMapOfList(v.Receiver, add)
	case *aotir.MapHasExpr:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		walkExprMapOfList(v.Receiver, add)
	case *aotir.MapLenExpr:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		walkExprMapOfList(v.Receiver, add)
	case *aotir.MapKeysExpr:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		walkExprMapOfList(v.Receiver, add)
	case *aotir.MapValuesExpr:
		add(v.KeyType, v.ValueType, v.ListValueElemType)
		walkExprMapOfList(v.Receiver, add)
	case *aotir.BinaryExpr:
		walkExprMapOfList(v.Left, add)
		walkExprMapOfList(v.Right, add)
	case *aotir.UnaryExpr:
		walkExprMapOfList(v.Operand, add)
	case *aotir.ListLit:
		for _, el := range v.Elems {
			walkExprMapOfList(el, add)
		}
	case *aotir.IndexExpr:
		walkExprMapOfList(v.Receiver, add)
	case *aotir.AppendExpr:
		walkExprMapOfList(v.Receiver, add)
		walkExprMapOfList(v.Value, add)
	case *aotir.FieldAccess:
		walkExprMapOfList(v.Receiver, add)
	case *aotir.RecordLit:
		for _, f := range v.Fields {
			walkExprMapOfList(f.Value, add)
		}
	}
}

// emitMapOfListHelpers emits a TU-local static helper set for each
// distinct map<K,list<V>> instantiation: struct typedef, _lit, _get,
// _has, _len, _keys, _values. Because the hash functions in map.c are
// static inline (not exported by libmochi), this emitter re-emits
// them as static inline helpers inside the same `static` block so
// the linker never sees a duplicate symbol.
//
// The _values() helper returns mochi_list_list_<inner>, which must
// already have been emitted by emitListOfListHelpers (called first in
// Emit()).
func emitMapOfListHelpers(b *strings.Builder, pairs []mapOfListPair) error {
	if len(pairs) == 0 {
		return nil
	}

	// Emit the hash helpers once (guarded by a macro so a TU that uses
	// multiple instantiations doesn't double-define them).
	b.WriteString("#ifndef MOCHI_MAP_LIST_HASH_HELPERS\n")
	b.WriteString("#define MOCHI_MAP_LIST_HASH_HELPERS\n")
	b.WriteString("static inline uint64_t mochi_map_list_hash_i64_(int64_t k) {\n")
	b.WriteString("    uint64_t x = (uint64_t)k;\n")
	b.WriteString("    x ^= x >> 30; x *= 0xbf58476d1ce4e5b9ULL;\n")
	b.WriteString("    x ^= x >> 27; x *= 0x94d049bb133111ebULL;\n")
	b.WriteString("    x ^= x >> 31; return x | 1ULL;\n")
	b.WriteString("}\n")
	b.WriteString("static inline uint64_t mochi_map_list_hash_str_(const char *s) {\n")
	b.WriteString("    uint64_t h = 0xcbf29ce484222325ULL;\n")
	b.WriteString("    while (*s) { h ^= (uint64_t)(unsigned char)*s++; h *= 0x100000001b3ULL; }\n")
	b.WriteString("    return h | 1ULL;\n")
	b.WriteString("}\n")
	b.WriteString("#endif /* MOCHI_MAP_LIST_HASH_HELPERS */\n\n")

	for _, p := range pairs {
		innerSuf, err := scalarListInnerSuffix(p.inner)
		if err != nil {
			return fmt.Errorf("map of list helper: %w", err)
		}

		var keySuf, keyC, hashFn string
		// eqFn(x, y) returns the equality expression for two key values x and y.
		var eqFn func(x, y string) string
		switch p.key {
		case aotir.TypeInt:
			keySuf = "i64"
			keyC = "int64_t"
			hashFn = "mochi_map_list_hash_i64_"
			eqFn = func(x, y string) string { return fmt.Sprintf("(%s) == (%s)", x, y) }
		case aotir.TypeString:
			keySuf = "str"
			keyC = "const char *"
			hashFn = "mochi_map_list_hash_str_"
			eqFn = func(x, y string) string { return fmt.Sprintf("strcmp((%s), (%s)) == 0", x, y) }
		default:
			return fmt.Errorf("map of list: unsupported key type %s", p.key)
		}

		valC := "mochi_list_" + innerSuf
		name := "mochi_map_" + keySuf + "_list_" + innerSuf
		entryName := name + "_entry"
		listKName := "mochi_list_" + keySuf
		listVName := "mochi_list_list_" + innerSuf

		// struct typedef
		fmt.Fprintf(b, "typedef struct %s {\n", entryName)
		fmt.Fprintf(b, "    uint64_t hash;\n")
		fmt.Fprintf(b, "    %s key;\n", keyC)
		fmt.Fprintf(b, "    %s value;\n", valC)
		fmt.Fprintf(b, "} %s;\n\n", entryName)

		fmt.Fprintf(b, "typedef struct %s {\n", name)
		fmt.Fprintf(b, "    %s *table;\n", entryName)
		fmt.Fprintf(b, "    int64_t cap;\n")
		fmt.Fprintf(b, "    int64_t nLive;\n")
		fmt.Fprintf(b, "} %s;\n\n", name)

		// _lit
		var keyArrC string
		if p.key == aotir.TypeString {
			keyArrC = "const char **"
		} else {
			keyArrC = "const int64_t *"
		}
		valArrC := "const " + valC + " *"

		fmt.Fprintf(b, "static %s %s_lit(%s keys, %s values, int64_t n) {\n", name, name, keyArrC, valArrC)
		fmt.Fprintf(b, "    %s out;\n", name)
		b.WriteString("    int64_t cap = 8;\n")
		b.WriteString("    while (cap < 2 * (n + 1)) cap <<= 1;\n")
		fmt.Fprintf(b, "    out.table = (%s *)calloc((size_t)cap, sizeof(%s));\n", entryName, entryName)
		b.WriteString("    out.cap = cap; out.nLive = 0;\n")
		b.WriteString("    if (out.table == NULL) mochi_panic_index();\n")
		b.WriteString("    for (int64_t i = 0; i < n; i++) {\n")
		fmt.Fprintf(b, "        uint64_t h = %s(keys[i]);\n", hashFn)
		b.WriteString("        uint64_t mask = (uint64_t)(cap - 1);\n")
		b.WriteString("        uint64_t pos = h & mask;\n")
		b.WriteString("        while (1) {\n")
		fmt.Fprintf(b, "            %s *e = &out.table[pos];\n", entryName)
		b.WriteString("            if (e->hash == 0) {\n")
		b.WriteString("                e->hash = h; e->key = keys[i]; e->value = values[i]; out.nLive++; break;\n")
		b.WriteString("            }\n")
		fmt.Fprintf(b, "            if (e->hash == h && %s) { e->value = values[i]; break; }\n", eqFn("e->key", "keys[i]"))
		b.WriteString("            pos = (pos + 1) & mask;\n")
		b.WriteString("        }\n")
		b.WriteString("    }\n")
		b.WriteString("    return out;\n")
		b.WriteString("}\n\n")

		// _get
		fmt.Fprintf(b, "static %s %s_get(%s m, %s k) {\n", valC, name, name, keyC)
		b.WriteString("    if (m.cap == 0) mochi_panic_index();\n")
		fmt.Fprintf(b, "    uint64_t h = %s(k);\n", hashFn)
		b.WriteString("    uint64_t mask = (uint64_t)(m.cap - 1);\n")
		b.WriteString("    uint64_t pos = h & mask;\n")
		b.WriteString("    while (1) {\n")
		fmt.Fprintf(b, "        %s *e = &m.table[pos];\n", entryName)
		b.WriteString("        if (e->hash == 0) mochi_panic_index();\n")
		fmt.Fprintf(b, "        if (e->hash == h && %s) return e->value;\n", eqFn("e->key", "k"))
		b.WriteString("        pos = (pos + 1) & mask;\n")
		b.WriteString("    }\n")
		b.WriteString("}\n\n")

		// _has
		fmt.Fprintf(b, "static int %s_has(%s m, %s k) {\n", name, name, keyC)
		b.WriteString("    if (m.cap == 0) return 0;\n")
		fmt.Fprintf(b, "    uint64_t h = %s(k);\n", hashFn)
		b.WriteString("    uint64_t mask = (uint64_t)(m.cap - 1);\n")
		b.WriteString("    uint64_t pos = h & mask;\n")
		b.WriteString("    while (1) {\n")
		fmt.Fprintf(b, "        %s *e = &m.table[pos];\n", entryName)
		b.WriteString("        if (e->hash == 0) return 0;\n")
		fmt.Fprintf(b, "        if (e->hash == h && %s) return 1;\n", eqFn("e->key", "k"))
		b.WriteString("        pos = (pos + 1) & mask;\n")
		b.WriteString("    }\n")
		b.WriteString("}\n\n")

		// _len
		fmt.Fprintf(b, "static int64_t %s_len(%s m) { return m.nLive; }\n\n", name, name)

		// _snapshot (internal, for keys/values)
		fmt.Fprintf(b, "static void %s_snapshot_(%s m, %s *out_keys, %s *out_vals) {\n", name, name, keyC, valC)
		b.WriteString("    int64_t ki = 0;\n")
		b.WriteString("    for (int64_t i = 0; i < m.cap; i++) {\n")
		fmt.Fprintf(b, "        %s *e = &m.table[i];\n", entryName)
		b.WriteString("        if (e->hash == 0) continue;\n")
		b.WriteString("        out_keys[ki] = e->key; out_vals[ki] = e->value; ki++;\n")
		b.WriteString("    }\n")
		// insertion sort by key
		b.WriteString("    for (int64_t i = 1; i < m.nLive; i++) {\n")
		fmt.Fprintf(b, "        %s key = out_keys[i]; %s val = out_vals[i]; int64_t j = i - 1;\n", keyC, valC)
		if p.key == aotir.TypeString {
			b.WriteString("        while (j >= 0 && strcmp(key, out_keys[j]) < 0) {\n")
		} else {
			b.WriteString("        while (j >= 0 && key < out_keys[j]) {\n")
		}
		b.WriteString("            out_keys[j+1] = out_keys[j]; out_vals[j+1] = out_vals[j]; j--;\n")
		b.WriteString("        }\n")
		b.WriteString("        out_keys[j+1] = key; out_vals[j+1] = val;\n")
		b.WriteString("    }\n")
		b.WriteString("}\n\n")

		// _keys -- returns list<K>
		fmt.Fprintf(b, "static %s %s_keys(%s m) {\n", listKName, name, name)
		fmt.Fprintf(b, "    size_t kbytes = (size_t)(m.nLive > 0 ? m.nLive : 1) * sizeof(%s);\n", keyC)
		fmt.Fprintf(b, "    size_t vbytes = (size_t)(m.nLive > 0 ? m.nLive : 1) * sizeof(%s);\n", valC)
		fmt.Fprintf(b, "    %s *ks = (%s *)malloc(kbytes);\n", keyC, keyC)
		fmt.Fprintf(b, "    %s *vs = (%s *)malloc(vbytes);\n", valC, valC)
		b.WriteString("    if (ks == NULL || vs == NULL) mochi_panic_index();\n")
		fmt.Fprintf(b, "    %s_snapshot_(m, ks, vs);\n", name)
		fmt.Fprintf(b, "    %s out = %s_lit(ks, m.nLive); free(ks); free(vs); return out;\n", listKName, listKName)
		b.WriteString("}\n\n")

		// _values -- returns list<list<V>>
		fmt.Fprintf(b, "static %s %s_values(%s m) {\n", listVName, name, name)
		fmt.Fprintf(b, "    size_t kbytes = (size_t)(m.nLive > 0 ? m.nLive : 1) * sizeof(%s);\n", keyC)
		fmt.Fprintf(b, "    size_t vbytes = (size_t)(m.nLive > 0 ? m.nLive : 1) * sizeof(%s);\n", valC)
		fmt.Fprintf(b, "    %s *ks = (%s *)malloc(kbytes);\n", keyC, keyC)
		fmt.Fprintf(b, "    %s *vs = (%s *)malloc(vbytes);\n", valC, valC)
		b.WriteString("    if (ks == NULL || vs == NULL) mochi_panic_index();\n")
		fmt.Fprintf(b, "    %s_snapshot_(m, ks, vs);\n", name)
		fmt.Fprintf(b, "    %s out = %s_lit(vs, m.nLive); free(ks); free(vs); return out;\n", listVName, listVName)
		b.WriteString("}\n\n")
	}
	return nil
}

func walkBlockInner(blk *aotir.Block, visit func(aotir.Type, aotir.Type)) {
	if blk == nil {
		return
	}
	for _, st := range blk.Statements {
		walkStmtInner(st, visit)
	}
}

func walkStmtInner(st aotir.Stmt, visit func(aotir.Type, aotir.Type)) {
	switch s := st.(type) {
	case *aotir.LetStmt:
		visit(s.ElemType, s.InnerElemType)
		walkExprInner(s.Init, visit)
	case *aotir.AssignStmt:
		walkExprInner(s.Value, visit)
	case *aotir.CallStmt:
		for _, a := range s.Args {
			walkExprInner(a, visit)
		}
	case *aotir.IfStmt:
		walkExprInner(s.Cond, visit)
		walkBlockInner(s.Then, visit)
		walkBlockInner(s.Else, visit)
	case *aotir.WhileStmt:
		walkExprInner(s.Cond, visit)
		walkBlockInner(s.Body, visit)
	case *aotir.ForRangeStmt:
		walkExprInner(s.Start, visit)
		walkExprInner(s.End, visit)
		walkBlockInner(s.Body, visit)
	case *aotir.ForEachStmt:
		visit(s.ElemType, s.InnerElemType)
		walkExprInner(s.List, visit)
		walkBlockInner(s.Body, visit)
	case *aotir.ReturnStmt:
		if s.Value != nil {
			walkExprInner(s.Value, visit)
		}
	}
}

func walkExprInner(e aotir.Expr, visit func(aotir.Type, aotir.Type)) {
	if e == nil {
		return
	}
	switch v := e.(type) {
	case *aotir.ListLit:
		visit(v.ElemType, v.InnerElemType)
		for _, el := range v.Elems {
			walkExprInner(el, visit)
		}
	case *aotir.IndexExpr:
		visit(v.ElemType, v.InnerElemType)
		walkExprInner(v.Receiver, visit)
		walkExprInner(v.Index, visit)
	case *aotir.LenExpr:
		visit(v.ElemType, v.InnerElemType)
		walkExprInner(v.Receiver, visit)
	case *aotir.AppendExpr:
		visit(v.ElemType, v.InnerElemType)
		walkExprInner(v.Receiver, visit)
		walkExprInner(v.Value, visit)
	case *aotir.VarRef:
		visit(v.ElemType, v.InnerElemType)
	case *aotir.CallExpr:
		visit(v.ResultElemType, v.ResultInnerElemType)
		for _, a := range v.Args {
			walkExprInner(a, visit)
		}
	case *aotir.BinaryExpr:
		walkExprInner(v.Left, visit)
		walkExprInner(v.Right, visit)
	case *aotir.UnaryExpr:
		walkExprInner(v.Operand, visit)
	case *aotir.FieldAccess:
		walkExprInner(v.Receiver, visit)
	case *aotir.RecordLit:
		for _, f := range v.Fields {
			walkExprInner(f.Value, visit)
		}
	case *aotir.MapLit:
		for _, k := range v.Keys {
			walkExprInner(k, visit)
		}
		for _, val := range v.Values {
			walkExprInner(val, visit)
		}
	case *aotir.MapGetExpr:
		walkExprInner(v.Receiver, visit)
		walkExprInner(v.Key, visit)
	case *aotir.MapHasExpr:
		walkExprInner(v.Receiver, visit)
		walkExprInner(v.Key, visit)
	case *aotir.MapLenExpr:
		walkExprInner(v.Receiver, visit)
	case *aotir.MapKeysExpr:
		walkExprInner(v.Receiver, visit)
	case *aotir.MapValuesExpr:
		// values(m) on map<K,list<V>> produces list<list<V>>; visit
		// with (TypeList, ListValueElemType) so collectListListInners
		// emits the mochi_list_list_<inner> helper needed by _values.
		visit(v.ValueType, v.ListValueElemType)
		walkExprInner(v.Receiver, visit)
	}
}

// emitListRecordHelpers walks the Program for every list<R> usage and
// emits a TU-local `mochi_list_<R>` struct plus the four canonical
// helpers (_lit, _append, _index, _len) per unique record name. The
// shape mirrors libmochi's scalar list runtime so the rest of the
// emitter is record-agnostic at the call site. Helpers are emitted
// `static` so multiple TU compilations don't collide and `inline`
// keeps the cost the same as the inlined libmochi helpers.
func emitListRecordHelpers(b *strings.Builder, names []string) error {
	if len(names) == 0 {
		return nil
	}
	sort.Strings(names)
	for _, name := range names {
		rec := cRecordTypeName(name)
		fmt.Fprintf(b, "typedef struct mochi_list_%s {\n", name)
		fmt.Fprintf(b, "    %s *data;\n", rec)
		b.WriteString("    int64_t  len;\n")
		b.WriteString("    int64_t  cap;\n")
		fmt.Fprintf(b, "} mochi_list_%s;\n\n", name)

		fmt.Fprintf(b, "static mochi_list_%s mochi_list_%s_lit(const %s *xs, int64_t n) {\n", name, name, rec)
		fmt.Fprintf(b, "    mochi_list_%s out = {NULL, n, n};\n", name)
		b.WriteString("    if (n > 0) {\n")
		fmt.Fprintf(b, "        out.data = (%s *)malloc((size_t)n * sizeof(%s));\n", rec, rec)
		b.WriteString("        if (out.data == NULL) { mochi_panic_index(); }\n")
		fmt.Fprintf(b, "        memcpy(out.data, xs, (size_t)n * sizeof(%s));\n", rec)
		b.WriteString("    }\n")
		b.WriteString("    return out;\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static mochi_list_%s mochi_list_%s_append(mochi_list_%s xs, %s v) {\n", name, name, name, rec)
		fmt.Fprintf(b, "    mochi_list_%s out = {NULL, xs.len + 1, xs.len + 1};\n", name)
		fmt.Fprintf(b, "    out.data = (%s *)malloc((size_t)out.cap * sizeof(%s));\n", rec, rec)
		b.WriteString("    if (out.data == NULL) { mochi_panic_index(); }\n")
		b.WriteString("    if (xs.len > 0) {\n")
		fmt.Fprintf(b, "        memcpy(out.data, xs.data, (size_t)xs.len * sizeof(%s));\n", rec)
		b.WriteString("    }\n")
		b.WriteString("    out.data[xs.len] = v;\n")
		b.WriteString("    return out;\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static %s mochi_list_%s_index(mochi_list_%s xs, int64_t i) {\n", rec, name, name)
		b.WriteString("    if (i < 0 || i >= xs.len) { mochi_panic_index(); }\n")
		b.WriteString("    return xs.data[i];\n")
		b.WriteString("}\n\n")

		fmt.Fprintf(b, "static int64_t mochi_list_%s_len(mochi_list_%s xs) { return xs.len; }\n\n", name, name)
	}
	return nil
}

// collectListRecordElems walks the program collecting every distinct
// record name used as a list<R> element type. The walk covers
// function signatures (params + return) and every statement/expression
// node so that no list<R> usage escapes the helper-emission pass.
func collectListRecordElems(prog *aotir.Program) []string {
	set := map[string]struct{}{}
	visit := func(elem aotir.Type, rec string) {
		if elem == aotir.TypeRecord && rec != "" {
			set[rec] = struct{}{}
		}
	}
	for _, fn := range prog.Functions {
		if fn == nil {
			continue
		}
		visit(fn.ReturnElemType, fn.ReturnElemRecordName)
		for _, p := range fn.Params {
			visit(p.ElemType, p.ElemRecordName)
		}
		walkBlock(fn.Body, visit)
	}
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	return out
}

func walkBlock(blk *aotir.Block, visit func(aotir.Type, string)) {
	if blk == nil {
		return
	}
	for _, st := range blk.Statements {
		walkStmt(st, visit)
	}
}

func walkStmt(st aotir.Stmt, visit func(aotir.Type, string)) {
	switch s := st.(type) {
	case *aotir.LetStmt:
		visit(s.ElemType, s.ElemRecordName)
		walkExpr(s.Init, visit)
	case *aotir.AssignStmt:
		walkExpr(s.Value, visit)
	case *aotir.CallStmt:
		for _, a := range s.Args {
			walkExpr(a, visit)
		}
	case *aotir.IfStmt:
		walkExpr(s.Cond, visit)
		walkBlock(s.Then, visit)
		walkBlock(s.Else, visit)
	case *aotir.WhileStmt:
		walkExpr(s.Cond, visit)
		walkBlock(s.Body, visit)
	case *aotir.ForRangeStmt:
		walkExpr(s.Start, visit)
		walkExpr(s.End, visit)
		walkBlock(s.Body, visit)
	case *aotir.ForEachStmt:
		visit(s.ElemType, s.ElemRecordName)
		walkExpr(s.List, visit)
		walkBlock(s.Body, visit)
	case *aotir.ReturnStmt:
		if s.Value != nil {
			walkExpr(s.Value, visit)
		}
	}
}

func walkExpr(e aotir.Expr, visit func(aotir.Type, string)) {
	if e == nil {
		return
	}
	switch v := e.(type) {
	case *aotir.ListLit:
		visit(v.ElemType, v.ElemRecordName)
		for _, el := range v.Elems {
			walkExpr(el, visit)
		}
	case *aotir.IndexExpr:
		visit(v.ElemType, v.ElemRecordName)
		walkExpr(v.Receiver, visit)
		walkExpr(v.Index, visit)
	case *aotir.LenExpr:
		visit(v.ElemType, v.ElemRecordName)
		walkExpr(v.Receiver, visit)
	case *aotir.AppendExpr:
		visit(v.ElemType, v.ElemRecordName)
		walkExpr(v.Receiver, visit)
		walkExpr(v.Value, visit)
	case *aotir.VarRef:
		visit(v.ElemType, v.ElemRecordName)
	case *aotir.CallExpr:
		visit(v.ResultElemType, v.ResultElemRecordName)
		for _, a := range v.Args {
			walkExpr(a, visit)
		}
	case *aotir.BinaryExpr:
		walkExpr(v.Left, visit)
		walkExpr(v.Right, visit)
	case *aotir.UnaryExpr:
		walkExpr(v.Operand, visit)
	case *aotir.FieldAccess:
		walkExpr(v.Receiver, visit)
	case *aotir.RecordLit:
		for _, f := range v.Fields {
			walkExpr(f.Value, visit)
		}
	case *aotir.MapLit:
		for _, k := range v.Keys {
			walkExpr(k, visit)
		}
		for _, val := range v.Values {
			walkExpr(val, visit)
		}
	case *aotir.MapGetExpr:
		walkExpr(v.Receiver, visit)
		walkExpr(v.Key, visit)
	case *aotir.MapHasExpr:
		walkExpr(v.Receiver, visit)
		walkExpr(v.Key, visit)
	case *aotir.MapLenExpr:
		walkExpr(v.Receiver, visit)
	case *aotir.MapKeysExpr:
		walkExpr(v.Receiver, visit)
	case *aotir.MapValuesExpr:
		walkExpr(v.Receiver, visit)
	}
}

func emitExpr(e aotir.Expr) (string, error) {
	switch v := e.(type) {
	case *aotir.StringLit:
		return cStringLiteral(v.Value), nil
	case *aotir.IntLit:
		return emitInt64Lit(v.Value), nil
	case *aotir.FloatLit:
		return emitFloatLit(v.Value), nil
	case *aotir.BoolLit:
		if v.Value {
			return "1", nil
		}
		return "0", nil
	case *aotir.VarRef:
		return v.Name, nil
	case *aotir.BinaryExpr:
		return emitBinary(v)
	case *aotir.UnaryExpr:
		return emitUnary(v)
	case *aotir.CallExpr:
		return emitCallExpr(v)
	case *aotir.RecordLit:
		return emitRecordLit(v)
	case *aotir.FieldAccess:
		return emitFieldAccess(v)
	case *aotir.ListLit:
		return emitListLit(v)
	case *aotir.IndexExpr:
		return emitIndexExpr(v)
	case *aotir.LenExpr:
		return emitLenExpr(v)
	case *aotir.StrLenExpr:
		recv, err := emitExpr(v.Receiver)
		if err != nil {
			return "", fmt.Errorf("StrLenExpr receiver: %w", err)
		}
		return "(int64_t)strlen(" + recv + ")", nil
	case *aotir.StrIndexExpr:
		recv, err := emitExpr(v.Receiver)
		if err != nil {
			return "", fmt.Errorf("StrIndexExpr receiver: %w", err)
		}
		idx, err := emitExpr(v.Index)
		if err != nil {
			return "", fmt.Errorf("StrIndexExpr index: %w", err)
		}
		return "mochi_str_index(" + recv + ", " + idx + ")", nil
	case *aotir.StrContainsExpr:
		recv, err := emitExpr(v.Receiver)
		if err != nil {
			return "", fmt.Errorf("StrContainsExpr receiver: %w", err)
		}
		sub, err := emitExpr(v.Sub)
		if err != nil {
			return "", fmt.Errorf("StrContainsExpr sub: %w", err)
		}
		return "mochi_str_contains(" + recv + ", " + sub + ")", nil
	case *aotir.StrSubstringExpr:
		recv, err := emitExpr(v.Receiver)
		if err != nil {
			return "", fmt.Errorf("StrSubstringExpr receiver: %w", err)
		}
		start, err := emitExpr(v.Start)
		if err != nil {
			return "", fmt.Errorf("StrSubstringExpr start: %w", err)
		}
		end, err := emitExpr(v.End)
		if err != nil {
			return "", fmt.Errorf("StrSubstringExpr end: %w", err)
		}
		return "mochi_str_substring(" + recv + ", " + start + ", " + end + ")", nil
	case *aotir.StrReverseExpr:
		recv, err := emitExpr(v.Receiver)
		if err != nil {
			return "", fmt.Errorf("StrReverseExpr receiver: %w", err)
		}
		return "mochi_str_reverse(" + recv + ")", nil
	case *aotir.AppendExpr:
		return emitAppendExpr(v)
	case *aotir.MapLit:
		return emitMapLit(v)
	case *aotir.MapGetExpr:
		return emitMapGetExpr(v)
	case *aotir.MapHasExpr:
		return emitMapHasExpr(v)
	case *aotir.MapLenExpr:
		return emitMapLenExpr(v)
	case *aotir.MapKeysExpr:
		return emitMapKeysExpr(v)
	case *aotir.MapValuesExpr:
		return emitMapValuesExpr(v)
	case *aotir.VariantLit:
		return emitVariantLit(v)
	case *aotir.UnionVarRef:
		return v.Name, nil
	case *aotir.VariantFieldAccess:
		return emitVariantFieldAccess(v)
	case *aotir.FunLit:
		// A non-capturing closure literal is already lifted to a top-level
		// function; the literal's value is the function's name (a function
		// pointer in C).
		return v.FuncName, nil
	case *aotir.FunCallExpr:
		return emitFunCallExpr(v)
	default:
		return "", fmt.Errorf("transpiler3/c/emit: unhandled Expr %T", e)
	}
}

// emitListLit renders a ListLit as a `mochi_list_<T>_lit` call with
// the elements held in a C99 compound-literal array temporary. The
// runtime helper makes a heap-allocated copy, so the temporary's
// lifetime (the enclosing full-expression) is enough.
func emitListLit(v *aotir.ListLit) (string, error) {
	suf, err := listSuffix(v.ElemType, v.ElemRecordName, v.InnerElemType, v.MapElemKeyType, v.MapElemValueType)
	if err != nil {
		return "", fmt.Errorf("list literal: %w", err)
	}
	elemC, err := cListBufferElemC(v.ElemType, v.ElemRecordName, v.InnerElemType, v.MapElemKeyType, v.MapElemValueType)
	if err != nil {
		return "", fmt.Errorf("list literal: %w", err)
	}
	if len(v.Elems) == 0 {
		return fmt.Sprintf("mochi_list_%s_lit((const %s[]){0}, INT64_C(0))", suf, elemC), nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "mochi_list_%s_lit((const %s[]){", suf, elemC)
	for i, e := range v.Elems {
		if i > 0 {
			b.WriteString(", ")
		}
		es, err := emitExpr(e)
		if err != nil {
			return "", fmt.Errorf("list literal element %d: %w", i, err)
		}
		b.WriteString(es)
	}
	fmt.Fprintf(&b, "}, INT64_C(%d))", len(v.Elems))
	return b.String(), nil
}

// cListBufferElemC returns the C element-type spelling used inside
// a list literal's compound-literal array temporary. This mirrors
// the `mochi_list_<T>_lit` first-parameter type from list.h. For
// list<list<T>> (Phase 3.4b), the buffer element is the nested list
// struct `mochi_list_<inner>` so the helper memcpys the nested-list
// headers (data pointer + len + cap) into the outer list. For
// list<map<K,V>> (Phase 3.4f), the buffer element is `mochi_map_<K>_<V>`.
func cListBufferElemC(elem aotir.Type, elemRecName string, innerElem aotir.Type, mapElemKey aotir.Type, mapElemValue aotir.Type) (string, error) {
	switch elem {
	case aotir.TypeInt:
		return "int64_t", nil
	case aotir.TypeFloat:
		return "double", nil
	case aotir.TypeBool:
		return "int", nil
	case aotir.TypeString:
		return "char *const", nil
	case aotir.TypeRecord:
		if elemRecName == "" {
			return "", fmt.Errorf("list of record requires non-empty record name")
		}
		return cRecordTypeName(elemRecName), nil
	case aotir.TypeList:
		inner, err := scalarListInnerSuffix(innerElem)
		if err != nil {
			return "", err
		}
		return "mochi_list_" + inner, nil
	case aotir.TypeMap:
		// Phase 3.4f: list<map<K,V>> buffer element is the map struct.
		suf, err := mapSuffix(mapElemKey, mapElemValue, aotir.TypeInvalid)
		if err != nil {
			return "", fmt.Errorf("list<map<K,V>> buffer elem: %w", err)
		}
		return "mochi_map_" + suf, nil
	}
	return "", fmt.Errorf("no list-literal buffer type for element %s", elem)
}

