package cgen

import (
	"bytes"
	"errors"
	"fmt"

	"mochi/compiler3/ir"
	"mochi/compiler3/verify"
)

// ErrUnsupportedOp is returned when the IR carries an op the C
// emitter does not yet lower. The driver maps this to a clean
// "AOT target unsupported, falling back to interpreter" failure
// rather than emitting a .c file that the system cc would reject or
// (worse) silently mis-link.
var ErrUnsupportedOp = errors.New("cgen: unsupported IR op")

// ErrUnsupportedType is returned when an SSA value carries a type
// outside the supported scalar set (i64, f64, bool, unit). Same
// rationale as ErrUnsupportedOp.
var ErrUnsupportedType = errors.New("cgen: unsupported IR type")

// ErrUnsupportedFFI is returned for OpCallGo bindings the C target
// cannot satisfy. The C target rejects general Go FFI by design
// (the MEP-42 identity is "no cgo on the Mochi build host"): only
// the `print(x)` sentinel binding (Pkg="fmt", Name="Println") is
// lowered, to runtime/c/print.h. Programs that need other Go
// imports must build with --target=go.
var ErrUnsupportedFFI = errors.New("cgen: C target does not support cross-language FFI; use --target=go")

// Program is the multi-function unit the emitter consumes. Main, if
// non-empty, names a no-parameter function to invoke from the
// generated `int main(void)`. The Main function's result type
// controls how main reports it to the host process: TypeI64 prints
// `%lld\n` to stdout (so the Phase 4.0 gate can byte-compare against
// `mochi run`), TypeBool prints `0` or `1`, TypeF64 prints `%.17g`,
// TypeUnit prints nothing. Other types fall under ErrUnsupportedType.
type Program struct {
	Funcs []*ir.Function
	Main  string
}

// Emit lowers p to a C99 source file. The output is self-contained
// except for the optional include of runtime/c/src/print.h: the
// driver writes that header next to gen.c when the program calls
// print(), so the include line resolves at cc-invocation time.
// Phase 4.0 (scalar-only) needs no Mochi runtime; Phase 4.1 adds the
// print include path for programs that route OpCallGo through the
// fmt.Println sentinel.
func Emit(p *Program) ([]byte, error) {
	for _, fn := range p.Funcs {
		if err := verify.Function(fn); err != nil {
			return nil, fmt.Errorf("verify %s: %w", fn.Name, err)
		}
	}

	// Walk the IR once to learn which runtime headers the source
	// needs. Doing this up front keeps the prologue self-contained
	// (no late "actually, also include X" patches as we emit bodies)
	// and lets the driver decide what runtime files to drop next to
	// gen.c.
	usesPrint := false
	usesListI64 := false
	usesF64Array := false
	usesStrArray := false
	usesNow := false
	usesMapI64I64 := false
	usesMapStrI64 := false
	usesListList := false
	usesTree := false
	usesStrH := false
	usesStrRuntime := false
	for _, fn := range p.Funcs {
		for _, v := range fn.Values {
			switch v.Op {
			case ir.OpCallGo:
				if int(v.Const) < 0 || int(v.Const) >= len(fn.GoBindings) {
					return nil, fmt.Errorf("emit %s: OpCallGo v%d: Const %d out of range (have %d bindings)",
						fn.Name, v.ID, v.Const, len(fn.GoBindings))
				}
				b := fn.GoBindings[v.Const]
				if isPrintBinding(b) {
					usesPrint = true
					continue
				}
				return nil, fmt.Errorf("emit %s: OpCallGo to %s.%s: %w", fn.Name, b.Pkg, b.Name, ErrUnsupportedFFI)
			case ir.OpNewList, ir.OpListLenI64, ir.OpListPushI64,
				ir.OpListGetI64, ir.OpListSetI64, ir.OpListConcatI64:
				usesListI64 = true
			case ir.OpNewF64Array, ir.OpF64ArrayLenI64, ir.OpF64ArrayPushF64,
				ir.OpF64ArrayGetF64, ir.OpF64ArraySetF64, ir.OpF64ArrayConcat,
				ir.OpF64ArrayToStr:
				usesF64Array = true
			case ir.OpNewStrArr, ir.OpStrArrLen, ir.OpStrArrPushStr,
				ir.OpStrArrGetStr, ir.OpStrArrSetStr, ir.OpStrArrToStr,
				ir.OpStrArrSlice:
				usesStrArray = true
			case ir.OpNewMap, ir.OpMapSetI64I64, ir.OpMapGetI64I64:
				usesMapI64I64 = true
			case ir.OpNewMapStrI64, ir.OpMapSetStrI64, ir.OpMapGetStrI64, ir.OpMapLenStrI64:
				usesMapStrI64 = true
			case ir.OpMapStrI64SortedKeys:
				usesMapStrI64 = true
				usesStrArray = true
			case ir.OpNewListList, ir.OpListListPush, ir.OpListListGet,
				ir.OpListListLen, ir.OpListListToStr:
				usesListList = true
				usesListI64 = true
			case ir.OpNewListAny, ir.OpListAnyLen, ir.OpListAnyPushAny, ir.OpListAnyGetAny:
				usesTree = true
			case ir.OpLenStr, ir.OpCmpEqStr, ir.OpCmpNeStr, ir.OpStrIn:
				usesStrH = true
			case ir.OpConcatStr, ir.OpI64ToStr, ir.OpF64ToStr, ir.OpBoolToStr, ir.OpStrCharAt, ir.OpStrRuneLen:
				usesStrRuntime = true
			case ir.OpNow:
				usesNow = true
			}
		}
	}

	var buf bytes.Buffer
	buf.WriteString("/* Code generated by compiler3/emit/c. DO NOT EDIT. */\n")
	buf.WriteString("#include <stdint.h>\n")
	buf.WriteString("#include <stdio.h>\n")
	buf.WriteString("#include <math.h>\n")
	if usesPrint {
		buf.WriteString("#include \"print.h\"\n")
	}
	if usesListI64 {
		buf.WriteString("#include \"mochi_list_i64.h\"\n")
	}
	if usesF64Array {
		buf.WriteString("#include \"mochi_f64_array.h\"\n")
	}
	if usesStrArray {
		buf.WriteString("#include \"mochi_str_array.h\"\n")
	}
	if usesMapI64I64 {
		buf.WriteString("#include \"mochi_map_i64_i64.h\"\n")
	}
	if usesMapStrI64 {
		buf.WriteString("#include \"mochi_map_str_i64.h\"\n")
	}
	if usesListList {
		buf.WriteString("#include \"mochi_list_list.h\"\n")
	}
	if usesTree {
		buf.WriteString("#include \"mochi_tree.h\"\n")
	}
	if usesNow {
		buf.WriteString("#include \"mochi_time.h\"\n")
	}
	if usesStrH {
		buf.WriteString("#include <string.h>\n")
	}
	if usesStrRuntime {
		buf.WriteString("#include \"mochi_str.h\"\n")
	}
	buf.WriteString("\n")

	for _, fn := range p.Funcs {
		emitPrototype(&buf, fn)
	}
	if len(p.Funcs) > 0 {
		buf.WriteString("\n")
	}
	for _, fn := range p.Funcs {
		if err := emitFunc(&buf, fn, p); err != nil {
			return nil, fmt.Errorf("emit %s: %w", fn.Name, err)
		}
	}
	if p.Main != "" {
		if err := emitMain(&buf, p); err != nil {
			return nil, err
		}
	} else {
		// Phase 4.2.26: a Mochi source with no executable top-level
		// statements (commented-out scripts, declaration-only files
		// like v0.6/extern.mochi) lowers to a Program with no main
		// function. Without a `_main` symbol the cc link step fails.
		// Emit a no-op `int main(void) { return 0; }` so the binary
		// links and runs with empty stdout, matching `mochi run` on
		// the same source.
		buf.WriteString("int main(void) { return 0; }\n")
	}
	return buf.Bytes(), nil
}

// cReservedWords are the C99 keywords plus the handful of C stdlib
// identifiers a Mochi-source function name would shadow if pasted
// verbatim. Any Mochi function name that hits the set is rewritten
// to "m_<name>" so the generated C compiles. The choice "prefix on
// collision, leave alone otherwise" preserves readable C output for
// the common case where the Mochi name is already C-safe.
var cReservedWords = map[string]bool{
	"auto": true, "break": true, "case": true, "char": true, "const": true,
	"continue": true, "default": true, "do": true, "double": true,
	"else": true, "enum": true, "extern": true, "float": true, "for": true,
	"goto": true, "if": true, "inline": true, "int": true, "long": true,
	"register": true, "restrict": true, "return": true, "short": true,
	"signed": true, "sizeof": true, "static": true, "struct": true,
	"switch": true, "typedef": true, "union": true, "unsigned": true,
	"void": true, "volatile": true, "while": true,
	"_Bool": true, "_Complex": true, "_Imaginary": true,
	// C99 stdlib types/macros likely to collide with a user Mochi name.
	"int64_t": true, "uint64_t": true, "size_t": true, "ssize_t": true,
	"NULL": true,
}

// cFuncName maps a Mochi-source function name to its C-source
// spelling. The rewrites are:
//   - "main" → "mochi_main", so the synthesized script-entry does
//     not collide with the wrapper `int main(void)` emitMain emits.
//   - any C99 keyword or reserved stdlib identifier → "m_<name>",
//     so a Mochi `fun double(...)` compiles instead of being
//     misparsed as a redeclared C type.
//   - any name starting with an underscore → "m_<name>", because
//     underscore-prefixed identifiers are reserved by C99 §7.1.3
//     for the implementation.
//
// Otherwise the name is passed through verbatim. Phase 4.1's tests
// pin the "main" and "double" rewrites; later phases can widen the
// set as new collisions appear.
func cFuncName(mochiName string) string {
	if mochiName == "main" {
		return "mochi_main"
	}
	if cReservedWords[mochiName] {
		return "m_" + mochiName
	}
	if len(mochiName) > 0 && mochiName[0] == '_' {
		return "m" + mochiName
	}
	return mochiName
}

// isPrintBinding identifies the one Go-FFI binding the C target
// special-cases: the compiler3 frontend lowers `print(arg)` to an
// OpCallGo with binding {Pkg:"fmt", Name:"Println"}. The C emitter
// translates that to a runtime/c/print.h call. Any other Go binding
// hits ErrUnsupportedFFI by design.
func isPrintBinding(b ir.GoBinding) bool {
	return b.Pkg == "fmt" && b.Name == "Println"
}

func emitPrototype(w *bytes.Buffer, fn *ir.Function) {
	fmt.Fprintf(w, "static %s %s(", cType(fn.Result), cFuncName(fn.Name))
	if len(fn.Params) == 0 {
		w.WriteString("void")
	} else {
		for i, pid := range fn.Params {
			if i > 0 {
				w.WriteString(", ")
			}
			fmt.Fprintf(w, "%s %s", cType(fn.Values[pid].Type), valueName(pid))
		}
	}
	w.WriteString(");\n")
}

func emitFunc(w *bytes.Buffer, fn *ir.Function, p *Program) error {
	fmt.Fprintf(w, "static %s %s(", cType(fn.Result), cFuncName(fn.Name))
	if len(fn.Params) == 0 {
		w.WriteString("void")
	} else {
		for i, pid := range fn.Params {
			if i > 0 {
				w.WriteString(", ")
			}
			fmt.Fprintf(w, "%s %s", cType(fn.Values[pid].Type), valueName(pid))
		}
	}
	w.WriteString(") {\n")

	// Declare every non-param, non-fnref value at the function head
	// with a zero initializer. C99 allows goto across declarations
	// only when no VLA is jumped over; Phase 4.0's scalar-only set
	// has no VLAs, so label-driven control flow is unconstrained.
	for _, v := range fn.Values {
		if v.Op == ir.OpParam || v.Op == ir.OpFnRef {
			continue
		}
		ct := cType(v.Type)
		if ct == "" || ct == "void" {
			continue
		}
		fmt.Fprintf(w, "    %s %s = 0;\n", ct, valueName(v.ID))
	}

	rpo := reversePostorder(fn)
	for i, bid := range rpo {
		blk := fn.Block(bid)
		if i > 0 {
			fmt.Fprintf(w, "L%d:;\n", bid)
		}
		for _, vid := range blk.Values {
			v := fn.Values[vid]
			if v.Op == ir.OpPhi {
				continue
			}
			if err := emitValue(w, fn, p, v); err != nil {
				return err
			}
		}
		if err := emitTerminator(w, fn, blk); err != nil {
			return err
		}
	}
	w.WriteString("}\n\n")
	return nil
}

func emitValue(w *bytes.Buffer, fn *ir.Function, p *Program, v ir.Value) error {
	name := valueName(v.ID)
	switch v.Op {
	case ir.OpParam:
		return nil
	case ir.OpConst:
		switch v.Type {
		case ir.TypeI64:
			// LLONG_MIN cannot be written as a positive literal in C
			// without a suffix; the safe form is (a - 1) where a is
			// (-LLONG_MAX). The cast to int64_t silences width warnings.
			if v.Const == -1<<63 {
				fmt.Fprintf(w, "    %s = (int64_t)(-9223372036854775807LL - 1);\n", name)
			} else {
				fmt.Fprintf(w, "    %s = (int64_t)%dLL;\n", name, v.Const)
			}
		case ir.TypeF64:
			// Bit-cast through a uint64 union: the IR carries f64
			// consts as raw bit patterns in v.Const.
			fmt.Fprintf(w, "    { union { uint64_t u; double d; } _c%d; _c%d.u = (uint64_t)%dULL; %s = _c%d.d; }\n",
				v.ID, v.ID, uint64(v.Const), name, v.ID)
		case ir.TypeBool:
			val := 0
			if v.Const != 0 {
				val = 1
			}
			fmt.Fprintf(w, "    %s = %d;\n", name, val)
		case ir.TypeStr:
			if int(v.Const) < 0 || int(v.Const) >= len(fn.Strings) {
				return fmt.Errorf("OpConst str v%d: Const %d out of range (have %d strings)",
					v.ID, v.Const, len(fn.Strings))
			}
			fmt.Fprintf(w, "    %s = %s;\n", name, cStringLiteral(fn.Strings[v.Const]))
		default:
			return fmt.Errorf("%w: OpConst type %s", ErrUnsupportedType, v.Type)
		}
	case ir.OpAddI64, ir.OpSubI64, ir.OpMulI64, ir.OpDivI64, ir.OpModI64:
		op := i64BinaryOp(v.Op)
		fmt.Fprintf(w, "    %s = %s %s %s;\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegI64:
		fmt.Fprintf(w, "    %s = -%s;\n", name, valueName(v.Args[0]))
	case ir.OpAddI64Imm, ir.OpSubI64Imm, ir.OpMulI64Imm, ir.OpDivI64Imm, ir.OpModI64Imm:
		op := i64ImmBinaryOp(v.Op)
		fmt.Fprintf(w, "    %s = %s %s (int64_t)%dLL;\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpAddF64, ir.OpSubF64, ir.OpMulF64, ir.OpDivF64:
		op := f64BinaryOp(v.Op)
		fmt.Fprintf(w, "    %s = %s %s %s;\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegF64:
		fmt.Fprintf(w, "    %s = -%s;\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqI64, ir.OpCmpNeI64, ir.OpCmpLtI64, ir.OpCmpLeI64, ir.OpCmpGtI64, ir.OpCmpGeI64:
		op := i64CmpOp(v.Op)
		fmt.Fprintf(w, "    %s = (%s %s %s) ? 1 : 0;\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpCmpEqI64Imm, ir.OpCmpNeI64Imm, ir.OpCmpLtI64Imm, ir.OpCmpLeI64Imm, ir.OpCmpGtI64Imm, ir.OpCmpGeI64Imm:
		op := i64ImmCmpOp(v.Op)
		fmt.Fprintf(w, "    %s = (%s %s (int64_t)%dLL) ? 1 : 0;\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpAndI64, ir.OpOrI64, ir.OpXorI64, ir.OpShlI64, ir.OpShrI64:
		op := i64BitwiseOp(v.Op)
		fmt.Fprintf(w, "    %s = %s %s %s;\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNotI64:
		fmt.Fprintf(w, "    %s = ~%s;\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqF64, ir.OpCmpNeF64, ir.OpCmpLtF64, ir.OpCmpLeF64, ir.OpCmpGtF64, ir.OpCmpGeF64:
		op := f64CmpOp(v.Op)
		fmt.Fprintf(w, "    %s = (%s %s %s) ? 1 : 0;\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNotBool:
		fmt.Fprintf(w, "    %s = %s ? 0 : 1;\n", name, valueName(v.Args[0]))
	case ir.OpI64ToF64:
		fmt.Fprintf(w, "    %s = (double)%s;\n", name, valueName(v.Args[0]))
	case ir.OpF64ToI64:
		fmt.Fprintf(w, "    %s = (int64_t)%s;\n", name, valueName(v.Args[0]))
	case ir.OpSqrtF64:
		fmt.Fprintf(w, "    %s = sqrt(%s);\n", name, valueName(v.Args[0]))
	case ir.OpNewList:
		// New empty list: allocates a header on the heap with NULL data.
		// The first push lazily reserves capacity; this matches the
		// Go target's `[]int64{}` shape (nil slice grown by append).
		fmt.Fprintf(w, "    %s = mochi_list_i64_new();\n", name)
	case ir.OpListLenI64:
		fmt.Fprintf(w, "    %s = mochi_list_i64_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpListPushI64:
		// Mutates the heap struct in place; the C pointer in Args[0]
		// stays valid. The op produces a TypeUnit value with no LHS.
		fmt.Fprintf(w, "    mochi_list_i64_push(%s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListGetI64:
		fmt.Fprintf(w, "    %s = mochi_list_i64_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListSetI64:
		fmt.Fprintf(w, "    mochi_list_i64_set(%s, %s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpNewF64Array:
		fmt.Fprintf(w, "    %s = mochi_f64_array_new();\n", name)
	case ir.OpF64ArrayLenI64:
		fmt.Fprintf(w, "    %s = mochi_f64_array_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpF64ArrayPushF64:
		fmt.Fprintf(w, "    mochi_f64_array_push(%s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArrayGetF64:
		fmt.Fprintf(w, "    %s = mochi_f64_array_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArraySetF64:
		fmt.Fprintf(w, "    mochi_f64_array_set(%s, %s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpListConcatI64:
		fmt.Fprintf(w, "    %s = mochi_list_i64_concat(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListI64ToStr:
		fmt.Fprintf(w, "    %s = mochi_list_i64_to_str(%s);\n", name, valueName(v.Args[0]))
	case ir.OpF64ArrayToStr:
		fmt.Fprintf(w, "    %s = mochi_f64_array_to_str(%s);\n", name, valueName(v.Args[0]))
	case ir.OpF64ArrayConcat:
		fmt.Fprintf(w, "    %s = mochi_f64_array_concat(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewStrArr:
		fmt.Fprintf(w, "    %s = mochi_str_array_new();\n", name)
	case ir.OpStrArrLen:
		fmt.Fprintf(w, "    %s = mochi_str_array_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpStrArrPushStr:
		fmt.Fprintf(w, "    mochi_str_array_push(%s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpStrArrGetStr:
		fmt.Fprintf(w, "    %s = mochi_str_array_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpStrArrSetStr:
		fmt.Fprintf(w, "    mochi_str_array_set(%s, %s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpStrArrToStr:
		fmt.Fprintf(w, "    %s = mochi_str_array_to_str(%s);\n", name, valueName(v.Args[0]))
	case ir.OpStrArrSlice:
		fmt.Fprintf(w, "    %s = mochi_str_array_slice(%s, %s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpNewMap:
		fmt.Fprintf(w, "    %s = mochi_map_i64_i64_new();\n", name)
	case ir.OpMapSetI64I64:
		fmt.Fprintf(w, "    mochi_map_i64_i64_set(%s, %s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpMapGetI64I64:
		fmt.Fprintf(w, "    %s = mochi_map_i64_i64_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewMapStrI64:
		fmt.Fprintf(w, "    %s = mochi_map_str_i64_new();\n", name)
	case ir.OpMapSetStrI64:
		fmt.Fprintf(w, "    mochi_map_str_i64_set(%s, %s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpMapGetStrI64:
		fmt.Fprintf(w, "    %s = mochi_map_str_i64_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpMapLenStrI64:
		fmt.Fprintf(w, "    %s = mochi_map_str_i64_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpMapStrI64SortedKeys:
		fmt.Fprintf(w, "    %s = mochi_map_str_i64_sorted_keys(%s);\n", name, valueName(v.Args[0]))
	case ir.OpNewListList:
		fmt.Fprintf(w, "    %s = mochi_list_list_new();\n", name)
	case ir.OpListListPush:
		fmt.Fprintf(w, "    mochi_list_list_push(%s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListListGet:
		fmt.Fprintf(w, "    %s = mochi_list_list_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListListLen:
		fmt.Fprintf(w, "    %s = mochi_list_list_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpListListToStr:
		fmt.Fprintf(w, "    %s = mochi_list_list_to_str(%s);\n", name, valueName(v.Args[0]))
	case ir.OpNewListAny:
		fmt.Fprintf(w, "    %s = mochi_tree_new();\n", name)
	case ir.OpListAnyLen:
		fmt.Fprintf(w, "    %s = mochi_tree_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpListAnyPushAny:
		fmt.Fprintf(w, "    mochi_tree_push(%s, %s);\n", valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListAnyGetAny:
		fmt.Fprintf(w, "    %s = mochi_tree_get(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpLenStr:
		// `const char*` carriers are NUL-terminated string literals
		// (Phase 4.2.0), so strlen reads byte length up to but not
		// including the terminator. Cast to int64_t because Mochi
		// `len(s)` returns int.
		fmt.Fprintf(w, "    %s = (int64_t)strlen(%s);\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqStr:
		// Byte equality on the NUL-terminated `const char*` carriers.
		// strcmp returns 0 iff the byte sequences match; the boolean
		// result is `(strcmp(a, b) == 0)`. Mochi `==` matches Go's
		// string `==` (byte equality) for Phase 4.2.x literals.
		fmt.Fprintf(w, "    %s = (strcmp(%s, %s) == 0);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpCmpNeStr:
		fmt.Fprintf(w, "    %s = (strcmp(%s, %s) != 0);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpCmpEqBool:
		// Bool carriers are int (cType returns "int" for TypeBool), so
		// equality is plain `==`. The `!!` normalises both operands to
		// 0 or 1 first; Phase 4.2.4 OpBoolToStr already routes through
		// the same normalisation, and the C emit of OpConst writes 0/1
		// for TypeBool, but defensively normalise so any future opaque
		// bool source (e.g. a Go FFI bridge) still compares correctly.
		fmt.Fprintf(w, "    %s = ((!!%s) == (!!%s));\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpCmpNeBool:
		fmt.Fprintf(w, "    %s = ((!!%s) != (!!%s));\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpAndBool:
		// Both args are already-evaluated bool carriers. C99 `&&` is
		// short-circuit at the AST level, but the IR pre-lowered the
		// right operand into a separate SSA value, so the emitted op
		// only performs the logical reduction (no actual short-
		// circuit, which would require control-flow lowering).
		fmt.Fprintf(w, "    %s = (%s && %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpOrBool:
		fmt.Fprintf(w, "    %s = (%s || %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpConcatStr:
		// mochi_str_concat allocates a NUL-terminated byte sequence
		// holding the bytes of v.Args[0] followed by v.Args[1] and
		// returns a `const char*` carrier the rest of the Phase 4.2.x
		// string ops accept without distinguishing literal from heap.
		// The buffer leaks; see runtime/c/src/mochi_str.h for the
		// ownership note.
		fmt.Fprintf(w, "    %s = mochi_str_concat(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpI64ToStr:
		// Decimal i64 via snprintf("%lld"). The runtime returns a
		// freshly allocated `const char*` carrier (see mochi_str.h).
		fmt.Fprintf(w, "    %s = mochi_str_from_i64((long long)%s);\n", name, valueName(v.Args[0]))
	case ir.OpF64ToStr:
		// Shortest round-trip f64 via the same search used by
		// runtime/c/src/print.c mochi_print_f64.
		fmt.Fprintf(w, "    %s = mochi_str_from_f64(%s);\n", name, valueName(v.Args[0]))
	case ir.OpBoolToStr:
		// Returns one of two static literals "true"/"false"; no
		// allocation. The literal type matches every other Phase 4.2.x
		// string carrier so downstream concat/print/len/strcmp work.
		fmt.Fprintf(w, "    %s = mochi_str_from_bool(%s);\n", name, valueName(v.Args[0]))
	case ir.OpStrCharAt:
		// `s[i]` on TypeStr. The runtime helper walks the UTF-8 byte
		// sequence to the i-th rune and returns a freshly-allocated
		// NUL-terminated single-rune string. Matches the VM's
		// `string([]rune(s)[i])` semantics on the v0.5 fixture corpus.
		fmt.Fprintf(w, "    %s = mochi_str_char_at(%s, %s);\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpStrIn:
		// `needle in haystack`. strstr returns the first occurrence of
		// the needle's byte sequence inside the haystack, or NULL when
		// the needle is absent. The empty needle is a substring of
		// every haystack (strstr returns the haystack itself); this
		// matches Go's strings.Contains so the VM and C target agree.
		fmt.Fprintf(w, "    %s = (strstr(%s, %s) != NULL);\n", name, valueName(v.Args[1]), valueName(v.Args[0]))
	case ir.OpStrRuneLen:
		// Rune count for the `for ch in s` loop bound. Walks the byte
		// sequence once; O(bytes), no allocation. Cf. OpLenStr above
		// which returns byte length via strlen.
		fmt.Fprintf(w, "    %s = mochi_str_rune_len(%s);\n", name, valueName(v.Args[0]))
	case ir.OpNow:
		fmt.Fprintf(w, "    %s = mochi_now_us();\n", name)
	case ir.OpJsonI64Object:
		if int(v.Const) < 0 || int(v.Const) >= len(fn.JsonObjects) {
			return fmt.Errorf("OpJsonI64Object v%d: Const %d out of range (have %d JsonObjects)",
				v.ID, v.Const, len(fn.JsonObjects))
		}
		obj := fn.JsonObjects[v.Const]
		if len(obj.Keys) != len(v.Args) {
			return fmt.Errorf("OpJsonI64Object v%d: %d keys but %d args",
				v.ID, len(obj.Keys), len(v.Args))
		}
		w.WriteString(`    printf("{`)
		for i, k := range obj.Keys {
			if i > 0 {
				w.WriteString(",")
			}
			fmt.Fprintf(w, `\"%s\":%%lld`, k)
		}
		w.WriteString(`}\n"`)
		for _, aid := range v.Args {
			fmt.Fprintf(w, ", (long long)%s", valueName(aid))
		}
		w.WriteString(");\n")
	case ir.OpCall, ir.OpTailCall:
		// Intra-program call. v.Const indexes into Program.Funcs;
		// args are SSA values in declared order. The emitter writes
		// `<lhs> = <callee>(args);` for non-unit results, and a bare
		// `<callee>(args);` for unit. OpTailCall lowers identically;
		// C compilers turn the tail position into a jump under -O2
		// when the call is in TermReturn position.
		if p == nil {
			return fmt.Errorf("%w: OpCall needs Program context", ErrUnsupportedOp)
		}
		if int(v.Const) < 0 || int(v.Const) >= len(p.Funcs) {
			return fmt.Errorf("%w: OpCall Const %d out of range (have %d funcs)",
				ErrUnsupportedOp, v.Const, len(p.Funcs))
		}
		callee := p.Funcs[v.Const]
		if v.Type == ir.TypeUnit || v.Type == ir.TypeInvalid {
			fmt.Fprintf(w, "    %s(", cFuncName(callee.Name))
		} else {
			fmt.Fprintf(w, "    %s = %s(", name, cFuncName(callee.Name))
		}
		for i, aid := range v.Args {
			if i > 0 {
				w.WriteString(", ")
			}
			w.WriteString(valueName(aid))
		}
		w.WriteString(");\n")
	case ir.OpCallGo:
		if int(v.Const) < 0 || int(v.Const) >= len(fn.GoBindings) {
			return fmt.Errorf("OpCallGo v%d: Const %d out of range (have %d bindings)",
				v.ID, v.Const, len(fn.GoBindings))
		}
		b := fn.GoBindings[v.Const]
		if !isPrintBinding(b) {
			return fmt.Errorf("%w: OpCallGo to %s.%s", ErrUnsupportedFFI, b.Pkg, b.Name)
		}
		if len(v.Args) != 1 {
			return fmt.Errorf("%w: print requires exactly one argument, got %d",
				ErrUnsupportedOp, len(v.Args))
		}
		argType := fn.Values[v.Args[0]].Type
		switch argType {
		case ir.TypeI64:
			fmt.Fprintf(w, "    mochi_print_i64(%s);\n", valueName(v.Args[0]))
		case ir.TypeF64:
			fmt.Fprintf(w, "    mochi_print_f64(%s);\n", valueName(v.Args[0]))
		case ir.TypeBool:
			fmt.Fprintf(w, "    mochi_print_bool(%s);\n", valueName(v.Args[0]))
		case ir.TypeStr:
			fmt.Fprintf(w, "    mochi_print_str(%s);\n", valueName(v.Args[0]))
		default:
			return fmt.Errorf("%w: print arg type %s",
				ErrUnsupportedType, argType)
		}
	case ir.OpPhi:
		return nil
	case ir.OpFnRef:
		return nil
	default:
		return fmt.Errorf("%w: %s", ErrUnsupportedOp, v.Op)
	}
	return nil
}

func emitTerminator(w *bytes.Buffer, fn *ir.Function, blk *ir.Block) error {
	emitPhiAssignments := func(succID uint32) {
		succ := fn.Block(succID)
		for _, vid := range succ.Values {
			v := fn.Values[vid]
			if v.Op != ir.OpPhi {
				continue
			}
			for i := 0; i < len(v.Args); i += 2 {
				if v.Args[i] == blk.ID {
					fmt.Fprintf(w, "    %s = %s;\n", valueName(v.ID), valueName(v.Args[i+1]))
				}
			}
		}
	}
	switch blk.Term.Kind {
	case ir.TermJump:
		emitPhiAssignments(blk.Term.Target)
		fmt.Fprintf(w, "    goto L%d;\n", blk.Term.Target)
	case ir.TermBranch:
		fmt.Fprintf(w, "    if (%s) {\n", valueName(blk.Term.Value))
		emitPhiAssignments(blk.Term.IfTrue)
		fmt.Fprintf(w, "        goto L%d;\n    }\n", blk.Term.IfTrue)
		emitPhiAssignments(blk.Term.IfFalse)
		fmt.Fprintf(w, "    goto L%d;\n", blk.Term.IfFalse)
	case ir.TermReturn:
		if fn.Result == ir.TypeUnit || fn.Result == ir.TypeInvalid {
			w.WriteString("    return;\n")
		} else {
			fmt.Fprintf(w, "    return %s;\n", valueName(blk.Term.Value))
		}
	default:
		return fmt.Errorf("%w: terminator %d", ErrUnsupportedOp, blk.Term.Kind)
	}
	return nil
}

func emitMain(w *bytes.Buffer, p *Program) error {
	var fn *ir.Function
	for _, f := range p.Funcs {
		if f.Name == p.Main {
			fn = f
			break
		}
	}
	if fn == nil {
		return fmt.Errorf("cgen: Main %q not found in Funcs", p.Main)
	}
	if len(fn.Params) != 0 {
		return fmt.Errorf("cgen: Main %q must take zero parameters", p.Main)
	}
	w.WriteString("int main(void) {\n")
	cName := cFuncName(p.Main)
	switch fn.Result {
	case ir.TypeI64:
		fmt.Fprintf(w, "    int64_t _r = %s();\n", cName)
		w.WriteString("    printf(\"%lld\\n\", (long long)_r);\n")
	case ir.TypeF64:
		fmt.Fprintf(w, "    double _r = %s();\n", cName)
		w.WriteString("    printf(\"%.17g\\n\", _r);\n")
	case ir.TypeBool:
		fmt.Fprintf(w, "    int _r = %s();\n", cName)
		w.WriteString("    printf(\"%d\\n\", _r ? 1 : 0);\n")
	case ir.TypeUnit, ir.TypeInvalid:
		fmt.Fprintf(w, "    %s();\n", cName)
	default:
		return fmt.Errorf("%w: Main result type %s", ErrUnsupportedType, fn.Result)
	}
	w.WriteString("    return 0;\n}\n")
	return nil
}

// cType maps an IR Type to the C99 spelling Phase 4.0 supports.
// Returns the empty string for TypeInvalid and "void" for TypeUnit;
// every other type outside the Phase 4.0 scalar set returns "" so
// the caller can detect it via the goTypeForValue analog (empty ->
// skip declaration, since the value cannot appear in well-typed
// Phase 4.0 output).
func cType(t ir.Type) string {
	switch t {
	case ir.TypeI64:
		return "int64_t"
	case ir.TypeF64:
		return "double"
	case ir.TypeBool:
		return "int"
	case ir.TypeStr:
		// String literals are read-only static-storage objects per
		// C99 §6.4.5; const char* matches their type and prevents the
		// generated body from accidentally mutating them. Phase 4.2.0
		// covers literal + print only, so no owning mochi_str runtime
		// is needed yet (a future 4.2.x adds concat/slice).
		return "const char*"
	case ir.TypeList:
		// list<int>: heap-allocated header backed by mochi_list_i64.
		// The MVP frontend constructs TypeList values with
		// ElemType=TypeI64 only; the f64 element-type lives on
		// TypeF64Arr (a separate flat-double backing) so this switch
		// stays branchless.
		return "mochi_list_i64*"
	case ir.TypeF64Arr:
		// list<float>: heap-allocated header backed by mochi_f64_array.
		// Distinct from TypeList so cc -O2 can vectorise the flat
		// double[] backing without a Cell-tag indirection.
		return "mochi_f64_array*"
	case ir.TypeStrArr:
		// list<str>: heap-allocated header backed by mochi_str_array.
		// The flat `const char**` backing aliases the same string
		// carriers the rest of the C target uses, so a push of a
		// literal element is a single pointer store (no copy).
		return "mochi_str_array*"
	case ir.TypeMap:
		// map<int, int>: heap-allocated open-addressing hashtable.
		// Backed by runtime/c/src/mochi_map_i64_i64.{h,c}; sized for
		// k_nucleotide's 20-key worst case but grows on demand.
		return "mochi_map_i64_i64*"
	case ir.TypeMapStrI64:
		// map<str, i64>: heap-allocated open-addressing hashtable
		// keyed by `const char*`. Backed by
		// runtime/c/src/mochi_map_str_i64.{h,c}. Get on an absent key
		// returns 0 (Go's `map[string]int64{}` zero-default).
		return "mochi_map_str_i64*"
	case ir.TypeListAny:
		// list<any>: heap-allocated recursive tree node. Backed by
		// runtime/c/src/mochi_tree.{h,c}; every child is itself a
		// `mochi_tree*`, matching binary_trees-style kernels where
		// every payload is recursively the same shape.
		return "mochi_tree*"
	case ir.TypeListList:
		// list<list<int>>: heap-allocated outer array of mochi_list_i64
		// pointers. Backed by runtime/c/src/mochi_list_list.{h,c}.
		// Distinct from TypeListAny so the get-op can return a typed
		// mochi_list_i64* directly without a tag check.
		return "mochi_list_list*"
	case ir.TypeUnit, ir.TypeInvalid:
		return "void"
	}
	return ""
}

func valueName(id uint32) string { return fmt.Sprintf("v%d", id) }

// cStringLiteral formats s as a C99 string literal, including the
// surrounding quotes. Printable ASCII bytes pass through; `"` and `\`
// are escaped; common whitespace gets the short forms (`\n`, `\t`,
// `\r`); other bytes use 3-digit octal so an immediately-following
// digit cannot be misparsed as part of the escape (which would be the
// case with `\x` hex escapes since cc consumes as many hex digits as
// possible).
func cStringLiteral(s string) string {
	var buf bytes.Buffer
	buf.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '"':
			buf.WriteString(`\"`)
		case '\\':
			buf.WriteString(`\\`)
		case '\n':
			buf.WriteString(`\n`)
		case '\t':
			buf.WriteString(`\t`)
		case '\r':
			buf.WriteString(`\r`)
		default:
			if c >= 0x20 && c <= 0x7e {
				buf.WriteByte(c)
			} else {
				fmt.Fprintf(&buf, "\\%03o", c)
			}
		}
	}
	buf.WriteByte('"')
	return buf.String()
}

