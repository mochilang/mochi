// reversePostorder is the same DFS-RPO the Go emitter uses. We
// duplicate the helper to avoid an import cycle with compiler3/emit/go.
func reversePostorder(fn *ir.Function) []uint32 {
	if len(fn.Blocks) == 0 {
		return nil
	}
	visited := make([]bool, len(fn.Blocks))
	order := make([]uint32, 0, len(fn.Blocks))
	var dfs func(id uint32)
	dfs = func(id uint32) {
		if visited[id] {
			return
		}
		visited[id] = true
		for _, s := range fn.Block(id).Succs {
			dfs(s)
		}
		order = append(order, id)
	}
	dfs(0)
	// Reverse in place.
	for i, j := 0, len(order)-1; i < j; i, j = i+1, j-1 {
		order[i], order[j] = order[j], order[i]
	}
	return order
}
