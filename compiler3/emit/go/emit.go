// reversePostorder computes a reverse-postorder block sequence
// starting at block 0. Phi predecessors precede their phis in this
// ordering, except across loop back-edges (which is why phi assignment
// is the predecessor's job, not the receiver's).
func reversePostorder(fn *ir.Function) []uint32 {
	visited := make(map[uint32]bool, len(fn.Blocks))
	order := []uint32{}
	var dfs func(uint32)
	dfs = func(id uint32) {
		if visited[id] {
			return
		}
		visited[id] = true
		blk := fn.Block(id)
		for _, s := range blk.Succs {
			dfs(s)
		}
		order = append(order, id)
	}
	dfs(0)
	// Reverse.
	for i, j := 0, len(order)-1; i < j; i, j = i+1, j-1 {
		order[i], order[j] = order[j], order[i]
	}
	return order
}

// stripBlockLabel is a tiny helper used by the test corpus to recover
// the block index from "L42:". Kept here so it's findable next to the
// emit logic.
func stripBlockLabel(s string) string {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "L") && strings.HasSuffix(s, ":") {
		return s[1 : len(s)-1]
	}
	return s
}

