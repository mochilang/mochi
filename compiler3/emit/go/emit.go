// Program is the multi-function unit the emitter consumes. compiler3
// today exposes only `ir.Function`; Program wraps a slice of them so
// the Phase 4 entry point Emit can produce a single .go file with
// every Mochi function reachable from the Mochi program's main.
type Program struct {
	PkgName string
	Funcs   []*ir.Function
	// Main, if non-empty, is the name of the function to invoke from
	// the generated `func main()`. The function must take no params
	// and return an int64 or unit. When Main is empty, no main() is
	// emitted (suitable for the --emit=go-library Phase 8 target).
	Main string
}

// Emit lowers p to gofmt-canonical Go source. The output imports
// runtime/mochi/* only if the IR references it. Returns the source
// bytes and any errors. The emitter does not invoke `go build`;
// callers feed the bytes to the toolchain.
func Emit(p *Program) ([]byte, error) {
	if p.PkgName == "" {
		p.PkgName = "main"
	}
	var body bytes.Buffer
	imports := map[string]bool{}
	for _, fn := range p.Funcs {
		if err := emitFunc(&body, fn, p.Funcs, imports); err != nil {
			return nil, fmt.Errorf("emit %s: %w", fn.Name, err)
		}
	}
	if p.Main != "" {
		fmt.Fprintf(&body, "\nfunc main() {\n\tresult := %s()\n\t_ = result\n}\n", p.Main)
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by compiler3/emit/go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&src, "package %s\n\n", p.PkgName)
	paths := make([]string, 0, len(imports))
	for ip, used := range imports {
		if used {
			paths = append(paths, ip)
		}
	}
	if len(paths) > 0 {
		sort.Strings(paths)
		fmt.Fprintf(&src, "import (\n")
		for _, ip := range paths {
			fmt.Fprintf(&src, "\t%q\n", ip)
		}
		fmt.Fprintf(&src, ")\n\n")
	}
	src.Write(body.Bytes())

	// gofmt the output. If gofmt rejects the source, return it
	// verbatim so the caller can debug; the test pipeline runs
	// `go vet` over the result so a broken emit will surface there.
	out, err := format.Source(src.Bytes())
	if err != nil {
		return src.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return out, nil
}

// emitFunc walks one Function and emits its Go form.
func emitFunc(w *bytes.Buffer, fn *ir.Function, all []*ir.Function, imports map[string]bool) error {
	// Header.
	fmt.Fprintf(w, "func %s(", fn.Name)
	for i, pid := range fn.Params {
		if i > 0 {
			w.WriteString(", ")
		}
		fmt.Fprintf(w, "%s %s", valueName(pid), goType(fn.Values[pid].Type))
	}
	w.WriteString(") ")
	if fn.Result != ir.TypeUnit && fn.Result != ir.TypeInvalid {
		w.WriteString(goType(fn.Result))
		w.WriteString(" ")
	}
	w.WriteString("{\n")

	// SSA-to-three-address: declare every value with a `var` at the
	// function head, then assign with `=` inside blocks. This is
	// mandatory because Go forbids `goto` from jumping over a `:=`
	// declaration; with all decls hoisted, label-driven control flow
	// is unconstrained.
	for _, v := range fn.Values {
		if v.Op == ir.OpParam {
			continue
		}
		if goType(v.Type) == "" {
			continue
		}
		fmt.Fprintf(w, "\tvar %s %s\n", valueName(v.ID), goType(v.Type))
		// Suppress "declared but not used" for values that only feed
		// terminators we don't reference (rare but possible after opt
		// passes drop dead values).
		fmt.Fprintf(w, "\t_ = %s\n", valueName(v.ID))
	}

	rpo := reversePostorder(fn)
	for i, bid := range rpo {
		blk := fn.Block(bid)
		// Label for non-entry blocks so jumps and branches can target.
		if i > 0 {
			fmt.Fprintf(w, "L%d:\n", bid)
		}
		// Initialise phis from the previous block? No: phi assignment
		// is the predecessor's job. We just lower the body values, then
		// the terminator.
		for _, vid := range blk.Values {
			v := fn.Values[vid]
			if v.Op == ir.OpPhi {
				// already declared
				continue
			}
			if err := emitValue(w, fn, v, all, imports); err != nil {
				return err
			}
		}
		if err := emitTerminator(w, fn, blk, all, imports); err != nil {
			return err
		}
	}
	w.WriteString("}\n")
	return nil
}

// emitValue lowers one SSA value. Each arm is a single fprintf.
func emitValue(w *bytes.Buffer, fn *ir.Function, v ir.Value, all []*ir.Function, imports map[string]bool) error {
	name := valueName(v.ID)
	switch v.Op {
	case ir.OpParam:
		// Already in scope from the function header.
		return nil
	case ir.OpConst:
		switch v.Type {
		case ir.TypeI64:
			fmt.Fprintf(w, "\t%s = int64(%d)\n", name, v.Const)
		case ir.TypeF64:
			imports["math"] = true
			fmt.Fprintf(w, "\t%s = math.Float64frombits(%d)\n", name, uint64(v.Const))
		case ir.TypeBool:
			val := "false"
			if v.Const != 0 {
				val = "true"
			}
			fmt.Fprintf(w, "\t%s = %s\n", name, val)
		default:
			return fmt.Errorf("OpConst unsupported type %s", v.Type)
		}
	case ir.OpAddI64, ir.OpSubI64, ir.OpMulI64, ir.OpDivI64, ir.OpModI64:
		op := i64BinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegI64:
		fmt.Fprintf(w, "\t%s = -%s\n", name, valueName(v.Args[0]))
	case ir.OpAddI64Imm, ir.OpSubI64Imm, ir.OpMulI64Imm, ir.OpDivI64Imm, ir.OpModI64Imm:
		op := i64ImmBinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s int64(%d)\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpAddF64, ir.OpSubF64, ir.OpMulF64, ir.OpDivF64:
		op := f64BinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegF64:
		fmt.Fprintf(w, "\t%s = -%s\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqI64, ir.OpCmpNeI64, ir.OpCmpLtI64, ir.OpCmpLeI64, ir.OpCmpGtI64, ir.OpCmpGeI64:
		op := i64CmpOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpCmpEqI64Imm, ir.OpCmpNeI64Imm, ir.OpCmpLtI64Imm, ir.OpCmpLeI64Imm, ir.OpCmpGtI64Imm, ir.OpCmpGeI64Imm:
		op := i64ImmCmpOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s int64(%d)\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpLenStr:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpConcatStr:
		fmt.Fprintf(w, "\t%s = %s + %s\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewList:
		fmt.Fprintf(w, "\t%s = []int64{}\n", name)
	case ir.OpListLenI64:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpListPushI64:
		// In-place mutation; emits an assignment.
		fmt.Fprintf(w, "\t%s = append(%s, %s)\n", valueName(v.Args[0]), valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListGetI64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListSetI64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpListGetF64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListSetF64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpNewMap:
		fmt.Fprintf(w, "\t%s = map[int64]int64{}\n", name)
	case ir.OpMapSetI64I64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpMapGetI64I64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewF64Array:
		fmt.Fprintf(w, "\t%s = []float64{}\n", name)
	case ir.OpF64ArrayLenI64:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpF64ArrayPushF64:
		fmt.Fprintf(w, "\t%s = append(%s, %s)\n", valueName(v.Args[0]), valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArrayGetF64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArraySetF64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpCall, ir.OpTailCall:
		callee := all[v.Const]
		fmt.Fprintf(w, "\t%s = %s(", name, callee.Name)
		for i, aid := range v.Args {
			if i > 0 {
				w.WriteString(", ")
			}
			w.WriteString(valueName(aid))
		}
		w.WriteString(")\n")
	case ir.OpPhi:
		// Declared in prelude; no body emit.
		return nil
	default:
		return fmt.Errorf("unsupported op: %s", v.Op)
	}
	return nil
}

// emitTerminator lowers the block exit, including any phi-back-edge
// assignments to predecessor sites.
func emitTerminator(w *bytes.Buffer, fn *ir.Function, blk *ir.Block, all []*ir.Function, imports map[string]bool) error {
	// Phi back-edge writes: walk every phi in every successor and emit
	// "<phi_name> = <our_source>" before the jump.
	emitPhiAssignments := func(succID uint32) {
		succ := fn.Block(succID)
		for _, vid := range succ.Values {
			v := fn.Values[vid]
			if v.Op != ir.OpPhi {
				continue
			}
			// Phi.Args layout: [predBlockID, srcValueID, predBlockID, srcValueID, ...]
			for i := 0; i < len(v.Args); i += 2 {
				if v.Args[i] == blk.ID {
					fmt.Fprintf(w, "\t%s = %s\n", valueName(v.ID), valueName(v.Args[i+1]))
				}
			}
		}
	}
	switch blk.Term.Kind {
	case ir.TermJump:
		emitPhiAssignments(blk.Term.Target)
		// If the jump target is the very next block in RPO, fall through.
		// Phase 4 does not yet detect RPO neighbours; emit goto always.
		fmt.Fprintf(w, "\tgoto L%d\n", blk.Term.Target)
	case ir.TermBranch:
		// Emit phi writes for both targets; only one fires at runtime.
		fmt.Fprintf(w, "\tif %s {\n", valueName(blk.Term.Value))
		emitPhiAssignments(blk.Term.IfTrue)
		fmt.Fprintf(w, "\t\tgoto L%d\n\t}\n", blk.Term.IfTrue)
		emitPhiAssignments(blk.Term.IfFalse)
		fmt.Fprintf(w, "\tgoto L%d\n", blk.Term.IfFalse)
	case ir.TermReturn:
		if fn.Result == ir.TypeUnit || fn.Result == ir.TypeInvalid {
			w.WriteString("\treturn\n")
		} else {
			fmt.Fprintf(w, "\treturn %s\n", valueName(blk.Term.Value))
		}
	default:
		return fmt.Errorf("unsupported terminator %d", blk.Term.Kind)
	}
	return nil
}

func valueName(id uint32) string { return fmt.Sprintf("v%d", id) }

func goType(t ir.Type) string {
	switch t {
	case ir.TypeI64:
		return "int64"
	case ir.TypeF64:
		return "float64"
	case ir.TypeBool:
		return "bool"
	case ir.TypeStr:
		return "string"
	case ir.TypeList:
		return "[]int64"
	case ir.TypeMap:
		return "map[int64]int64"
	case ir.TypeF64Arr:
		return "[]float64"
	case ir.TypeI64Arr:
		return "[]int64"
	case ir.TypeU8Arr:
		return "[]byte"
	case ir.TypeUnit, ir.TypeInvalid:
		return ""
	default:
		return "interface{}"
	}
}

func i64BinaryOp(op ir.OpCode) string {
	switch op {
	case ir.OpAddI64:
		return "+"
	case ir.OpSubI64:
		return "-"
	case ir.OpMulI64:
		return "*"
	case ir.OpDivI64:
		return "/"
	case ir.OpModI64:
		return "%"
	}
	return "?"
}

