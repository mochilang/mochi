// Program is the multi-function unit the emitter consumes. compiler3
// today exposes only `ir.Function`; Program wraps a slice of them so
// the Phase 4 entry point Emit can produce a single .go file with
// every Mochi function reachable from the Mochi program's main.
type Program struct {
	PkgName string
	Funcs   []*ir.Function
	// Main, if non-empty, is the name of the function to invoke from
	// the generated `func main()`. The function must take no params
	// and return an int64 or unit. When Main is empty, no main() is
	// emitted (suitable for the --emit=go-library Phase 8 target).
	Main string
}

// Emit lowers p to gofmt-canonical Go source. The output imports
// runtime/mochi/* only if the IR references it. Returns the source
// bytes and any errors. The emitter does not invoke `go build`;
// callers feed the bytes to the toolchain.
//
// When any function in p carries a SourceFile, the emitter writes
// `//line file:N` directives at function and block boundaries so the
// Go toolchain reports diagnostics with Mochi-source coordinates. In
// that mode the final gofmt pass is skipped because gofmt may reflow
// lines and break the directives' line-for-line mapping.
func Emit(p *Program) ([]byte, error) {
	if p.PkgName == "" {
		p.PkgName = "main"
	}
	// MEP-41 §6.2 verifier (Phase 1). Every function must pass rule
	// classes A through D before the emitter sees it. The verifier is
	// the single point of memory-safety policy named in
	// docs/security/threat-model.md.
	for _, fn := range p.Funcs {
		if err := verify.Function(fn); err != nil {
			return nil, fmt.Errorf("verify %s: %w", fn.Name, err)
		}
	}
	hasSourceMap := false
	for _, fn := range p.Funcs {
		if fn.SourceFile != "" {
			hasSourceMap = true
			break
		}
	}
	usesListAny := false
	for _, fn := range p.Funcs {
		if fn.Result == ir.TypeListAny {
			usesListAny = true
		}
		for _, v := range fn.Values {
			if v.Type == ir.TypeListAny ||
				v.Op == ir.OpNewListAny || v.Op == ir.OpListAnyLen ||
				v.Op == ir.OpListAnyPushAny || v.Op == ir.OpListAnyGetAny {
				usesListAny = true
				break
			}
		}
		if usesListAny {
			break
		}
	}
	var body bytes.Buffer
	imports := map[string]bool{}
	importAlias := map[string]string{}
	for _, fn := range p.Funcs {
		// Pre-seed importAlias from this function's Go bindings; the
		// emitter never invents an alias different from the binding
		// table's, so emission order is irrelevant for correctness.
		for _, b := range fn.GoBindings {
			if b.Alias != "" && b.Alias != defaultAlias(b.Pkg) {
				importAlias[b.Pkg] = b.Alias
			}
		}
		if err := emitFunc(&body, fn, p.Funcs, imports); err != nil {
			return nil, fmt.Errorf("emit %s: %w", fn.Name, err)
		}
	}
	if p.Main != "" {
		fmt.Fprintf(&body, "\nfunc main() {\n\tresult := %s()\n\t_ = result\n}\n", p.Main)
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by compiler3/emit/go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&src, "package %s\n\n", p.PkgName)
	paths := make([]string, 0, len(imports))
	for ip, used := range imports {
		if used {
			paths = append(paths, ip)
		}
	}
	if len(paths) > 0 {
		sort.Strings(paths)
		fmt.Fprintf(&src, "import (\n")
		for _, ip := range paths {
			if a, ok := importAlias[ip]; ok {
				fmt.Fprintf(&src, "\t%s %q\n", a, ip)
			} else {
				fmt.Fprintf(&src, "\t%q\n", ip)
			}
		}
		fmt.Fprintf(&src, ")\n\n")
	}
	if usesListAny {
		fmt.Fprintf(&src, "type _MochiAny []_MochiAny\n\n")
	}
	src.Write(body.Bytes())

	if hasSourceMap {
		// Phase 7: skip gofmt to preserve the line-for-line mapping
		// between emitted Go and Mochi-source `//line` directives.
		return src.Bytes(), nil
	}

	// gofmt the output. If gofmt rejects the source, return it
	// verbatim so the caller can debug; the test pipeline runs
	// `go vet` over the result so a broken emit will surface there.
	out, err := format.Source(src.Bytes())
	if err != nil {
		return src.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return out, nil
}

// emitFunc walks one Function and emits its Go form.
func emitFunc(w *bytes.Buffer, fn *ir.Function, all []*ir.Function, imports map[string]bool) error {
	// Optional source-map: anchor the function at the first block's
	// SourceLine. Subsequent blocks emit their own //line directives.
	if fn.SourceFile != "" {
		line := uint32(0)
		if len(fn.Blocks) > 0 {
			line = fn.Blocks[0].SourceLine
		}
		if line == 0 {
			line = 1
		}
		fmt.Fprintf(w, "//line %s:%d\n", fn.SourceFile, line)
	}
	// Header.
	fmt.Fprintf(w, "func %s(", fn.Name)
	for i, pid := range fn.Params {
		if i > 0 {
			w.WriteString(", ")
		}
		fmt.Fprintf(w, "%s %s", valueName(pid), goType(fn.Values[pid].Type))
	}
	w.WriteString(") ")
	if fn.Result != ir.TypeUnit && fn.Result != ir.TypeInvalid {
		w.WriteString(goType(fn.Result))
		w.WriteString(" ")
	}
	w.WriteString("{\n")

	// SSA-to-three-address: declare every value with a `var` at the
	// function head, then assign with `=` inside blocks. This is
	// mandatory because Go forbids `goto` from jumping over a `:=`
	// declaration; with all decls hoisted, label-driven control flow
	// is unconstrained.
	for _, v := range fn.Values {
		if v.Op == ir.OpParam {
			continue
		}
		if v.Op == ir.OpFnRef {
			// OpFnRef is not materialised as a Go local; consumers
			// inline the referenced function's name via fnName.
			continue
		}
		gt := goTypeForValue(v)
		if gt == "" {
			continue
		}
		if v.Op == ir.OpQueryGroupBy {
			imports["mochi/runtime/mochi/query"] = true
		}
		fmt.Fprintf(w, "\tvar %s %s\n", valueName(v.ID), gt)
		// Suppress "declared but not used" for values that only feed
		// terminators we don't reference (rare but possible after opt
		// passes drop dead values).
		fmt.Fprintf(w, "\t_ = %s\n", valueName(v.ID))
	}

	rpo := reversePostorder(fn)
	for i, bid := range rpo {
		blk := fn.Block(bid)
		// Block-level //line directive so any error inside this block's
		// emission shows the Mochi-source line, not the generated file.
		if fn.SourceFile != "" && blk.SourceLine != 0 {
			fmt.Fprintf(w, "//line %s:%d\n", fn.SourceFile, blk.SourceLine)
		}
		// Label for non-entry blocks so jumps and branches can target.
		if i > 0 {
			fmt.Fprintf(w, "L%d:\n", bid)
		}
		// Initialise phis from the previous block? No: phi assignment
		// is the predecessor's job. We just lower the body values, then
		// the terminator.
		for _, vid := range blk.Values {
			v := fn.Values[vid]
			if v.Op == ir.OpPhi {
				// already declared
				continue
			}
			if err := emitValue(w, fn, v, all, imports); err != nil {
				return err
			}
		}
		if err := emitTerminator(w, fn, blk, all, imports); err != nil {
			return err
		}
	}
	w.WriteString("}\n")
	return nil
}

// emitValue lowers one SSA value. Each arm is a single fprintf.
func emitValue(w *bytes.Buffer, fn *ir.Function, v ir.Value, all []*ir.Function, imports map[string]bool) error {
	name := valueName(v.ID)
	switch v.Op {
	case ir.OpParam:
		// Already in scope from the function header.
		return nil
	case ir.OpConst:
		switch v.Type {
		case ir.TypeI64:
			fmt.Fprintf(w, "\t%s = int64(%d)\n", name, v.Const)
		case ir.TypeF64:
			imports["math"] = true
			fmt.Fprintf(w, "\t%s = math.Float64frombits(%d)\n", name, uint64(v.Const))
		case ir.TypeBool:
			val := "false"
			if v.Const != 0 {
				val = "true"
			}
			fmt.Fprintf(w, "\t%s = %s\n", name, val)
		default:
			return fmt.Errorf("OpConst unsupported type %s", v.Type)
		}
	case ir.OpAddI64, ir.OpSubI64, ir.OpMulI64, ir.OpDivI64, ir.OpModI64:
		op := i64BinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegI64:
		fmt.Fprintf(w, "\t%s = -%s\n", name, valueName(v.Args[0]))
	case ir.OpAddI64Imm, ir.OpSubI64Imm, ir.OpMulI64Imm, ir.OpDivI64Imm, ir.OpModI64Imm:
		op := i64ImmBinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s int64(%d)\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpAddF64, ir.OpSubF64, ir.OpMulF64, ir.OpDivF64:
		op := f64BinaryOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNegF64:
		fmt.Fprintf(w, "\t%s = -%s\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqI64, ir.OpCmpNeI64, ir.OpCmpLtI64, ir.OpCmpLeI64, ir.OpCmpGtI64, ir.OpCmpGeI64:
		op := i64CmpOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpCmpEqI64Imm, ir.OpCmpNeI64Imm, ir.OpCmpLtI64Imm, ir.OpCmpLeI64Imm, ir.OpCmpGtI64Imm, ir.OpCmpGeI64Imm:
		op := i64ImmCmpOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s int64(%d)\n", name, valueName(v.Args[0]), op, v.Const)
	case ir.OpAndI64, ir.OpOrI64, ir.OpXorI64, ir.OpShlI64, ir.OpShrI64:
		op := i64BitwiseOp(v.Op)
		// Go requires the shift-count operand to be unsigned (uint or
		// untyped). Mochi's IR carries i64 throughout, so the shift
		// variants cast the right operand at the use site. The bitwise
		// AND/OR/XOR operands are both i64 and need no cast.
		if v.Op == ir.OpShlI64 || v.Op == ir.OpShrI64 {
			fmt.Fprintf(w, "\t%s = %s %s uint64(%s)\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
		} else {
			fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
		}
	case ir.OpNotI64:
		fmt.Fprintf(w, "\t%s = ^%s\n", name, valueName(v.Args[0]))
	case ir.OpCmpEqF64, ir.OpCmpNeF64, ir.OpCmpLtF64, ir.OpCmpLeF64, ir.OpCmpGtF64, ir.OpCmpGeF64:
		op := f64CmpOp(v.Op)
		fmt.Fprintf(w, "\t%s = %s %s %s\n", name, valueName(v.Args[0]), op, valueName(v.Args[1]))
	case ir.OpNotBool:
		fmt.Fprintf(w, "\t%s = !%s\n", name, valueName(v.Args[0]))
	case ir.OpI64ToF64:
		fmt.Fprintf(w, "\t%s = float64(%s)\n", name, valueName(v.Args[0]))
	case ir.OpF64ToI64:
		fmt.Fprintf(w, "\t%s = int64(%s)\n", name, valueName(v.Args[0]))
	case ir.OpSqrtF64:
		imports["math"] = true
		fmt.Fprintf(w, "\t%s = math.Sqrt(%s)\n", name, valueName(v.Args[0]))
	case ir.OpLenStr:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpConcatStr:
		fmt.Fprintf(w, "\t%s = %s + %s\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewList:
		fmt.Fprintf(w, "\t%s = []int64{}\n", name)
	case ir.OpListLenI64:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpListPushI64:
		// In-place mutation; emits an assignment.
		fmt.Fprintf(w, "\t%s = append(%s, %s)\n", valueName(v.Args[0]), valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListGetI64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListSetI64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpListGetF64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListSetF64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpNewMap:
		fmt.Fprintf(w, "\t%s = map[int64]int64{}\n", name)
	case ir.OpMapSetI64I64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpMapGetI64I64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewListAny:
		fmt.Fprintf(w, "\t%s = _MochiAny{}\n", name)
	case ir.OpListAnyLen:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpListAnyPushAny:
		fmt.Fprintf(w, "\t%s = append(%s, %s)\n", valueName(v.Args[0]), valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpListAnyGetAny:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNewF64Array:
		fmt.Fprintf(w, "\t%s = []float64{}\n", name)
	case ir.OpF64ArrayLenI64:
		fmt.Fprintf(w, "\t%s = int64(len(%s))\n", name, valueName(v.Args[0]))
	case ir.OpF64ArrayPushF64:
		fmt.Fprintf(w, "\t%s = append(%s, %s)\n", valueName(v.Args[0]), valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArrayGetF64:
		fmt.Fprintf(w, "\t%s = %s[%s]\n", name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArraySetF64:
		fmt.Fprintf(w, "\t%s[%s] = %s\n", valueName(v.Args[0]), valueName(v.Args[1]), valueName(v.Args[2]))
	case ir.OpListConcatI64:
		fmt.Fprintf(w, "\t%s = append(append([]int64{}, %s...), %s...)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpF64ArrayConcat:
		fmt.Fprintf(w, "\t%s = append(append([]float64{}, %s...), %s...)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpNow:
		imports["time"] = true
		fmt.Fprintf(w, "\t%s = time.Now().UnixMicro()\n", name)
	case ir.OpJsonI64Object:
		if int(v.Const) < 0 || int(v.Const) >= len(fn.JsonObjects) {
			return fmt.Errorf("OpJsonI64Object v%d: Const %d out of range (have %d JsonObjects)", v.ID, v.Const, len(fn.JsonObjects))
		}
		obj := fn.JsonObjects[v.Const]
		if len(obj.Keys) != len(v.Args) {
			return fmt.Errorf("OpJsonI64Object v%d: %d keys but %d args", v.ID, len(obj.Keys), len(v.Args))
		}
		imports["fmt"] = true
		var fb bytes.Buffer
		fb.WriteString(`"{`)
		for i, k := range obj.Keys {
			if i > 0 {
				fb.WriteString(",")
			}
			fmt.Fprintf(&fb, `\"%s\":%%d`, k)
		}
		fb.WriteString(`}\n"`)
		fmt.Fprintf(w, "\tfmt.Printf(%s", fb.String())
		for _, aid := range v.Args {
			fmt.Fprintf(w, ", %s", valueName(aid))
		}
		w.WriteString(")\n")
		_ = name
	case ir.OpCall, ir.OpTailCall:
		callee := all[v.Const]
		fmt.Fprintf(w, "\t%s = %s(", name, callee.Name)
		for i, aid := range v.Args {
			if i > 0 {
				w.WriteString(", ")
			}
			w.WriteString(valueName(aid))
		}
		w.WriteString(")\n")
	case ir.OpFnRef:
		// No Go-side expression; the consumer query op inlines the
		// referenced function name via fnName(fn, all, v.Args[i]).
		return nil
	case ir.OpQueryFilter:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.Filter[int64](%s, %s)\n",
			name, valueName(v.Args[0]), fnName(fn, all, v.Args[1]))
	case ir.OpQueryMap:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.Map[int64, int64](%s, %s)\n",
			name, valueName(v.Args[0]), fnName(fn, all, v.Args[1]))
	case ir.OpQuerySortBy:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.SortBy[int64, int64](%s, %s)\n",
			name, valueName(v.Args[0]), fnName(fn, all, v.Args[1]))
	case ir.OpQuerySortByDesc:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.SortByDesc[int64, int64](%s, %s)\n",
			name, valueName(v.Args[0]), fnName(fn, all, v.Args[1]))
	case ir.OpQueryLimit:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.Limit[int64](%s, int(%s))\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]))
	case ir.OpQueryDistinct:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.Distinct[int64](%s)\n",
			name, valueName(v.Args[0]))
	case ir.OpQueryGroupBy:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.GroupBy[int64, int64](%s, %s)\n",
			name, valueName(v.Args[0]), fnName(fn, all, v.Args[1]))
	case ir.OpQueryJoin:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.Join[int64, int64, int64, int64](%s, %s, %s, %s, %s)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]),
			fnName(fn, all, v.Args[2]), fnName(fn, all, v.Args[3]), fnName(fn, all, v.Args[4]))
	case ir.OpQueryLeftJoin:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.LeftJoin[int64, int64, int64, int64](%s, %s, %s, %s, %s)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]),
			fnName(fn, all, v.Args[2]), fnName(fn, all, v.Args[3]), fnName(fn, all, v.Args[4]))
	case ir.OpQueryOuterJoin:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.OuterJoin[int64, int64, int64, int64](%s, %s, %s, %s, %s)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]),
			fnName(fn, all, v.Args[2]), fnName(fn, all, v.Args[3]), fnName(fn, all, v.Args[4]))
	case ir.OpQueryCrossJoin:
		imports["mochi/runtime/mochi/query"] = true
		fmt.Fprintf(w, "\t%s = query.CrossJoin[int64, int64, int64](%s, %s, %s)\n",
			name, valueName(v.Args[0]), valueName(v.Args[1]),
			fnName(fn, all, v.Args[2]))
	case ir.OpCallGo:
		if int(v.Const) >= len(fn.GoBindings) {
			return fmt.Errorf("OpCallGo v%d: Const %d out of range (have %d bindings)", v.ID, v.Const, len(fn.GoBindings))
		}
		b := fn.GoBindings[v.Const]
		imports[b.Pkg] = true
		alias := b.Alias
		if alias == "" {
			alias = defaultAlias(b.Pkg)
		}
		if b.SealHandles {
			imports["mochi/runtime/mochi/ffi"] = true
		}
		// resultCast is the IR-side Go type the SSA value was declared
		// with. The Go call expression is wrapped in this cast so the
		// emitter never assigns a width-mismatched result (e.g. Go
		// `int` into an int64 SSA local). Empty means "no cast" because
		// the SSA value is unit-typed or has no declared Go shape.
		resultCast := ""
		if b.Result != "" {
			resultCast = goType(v.Type)
		}
		castBack := resultCast != "" && resultCast != b.Result && !b.SealHandles
		// Value bindings (vars, consts) read the symbol directly; no
		// parens, no args. SealHandles still wraps the read in Unseal
		// when the value is a Mochi-handle-typed export.
		if b.IsValue {
			switch {
			case b.SealHandles && b.Result != "":
				fmt.Fprintf(w, "\t%s = ffi.Unseal[%s](%s.%s)\n", name, b.Result, alias, b.Name)
			case castBack:
				fmt.Fprintf(w, "\t%s = %s(%s.%s)\n", name, resultCast, alias, b.Name)
			default:
				fmt.Fprintf(w, "\t%s = %s.%s\n", name, alias, b.Name)
			}
			return nil
		}
		// Phase 10: when this binding seals handles, wrap the return
		// value in `ffi.Unseal[T]` and each argument in `ffi.Seal[T]`
		// where T is the declared Go arg/result type from the binding.
		switch {
		case b.Result == "":
			fmt.Fprintf(w, "\t%s.%s(", alias, b.Name)
		case b.SealHandles:
			fmt.Fprintf(w, "\t%s = ffi.Unseal[%s](%s.%s(", name, b.Result, alias, b.Name)
		case castBack:
			fmt.Fprintf(w, "\t%s = %s(%s.%s(", name, resultCast, alias, b.Name)
		default:
			fmt.Fprintf(w, "\t%s = %s.%s(", name, alias, b.Name)
		}
		for i, aid := range v.Args {
			if i > 0 {
				w.WriteString(", ")
			}
			switch {
			case b.SealHandles && i < len(b.ArgTypes):
				fmt.Fprintf(w, "ffi.Seal[%s](%s)", b.ArgTypes[i], valueName(aid))
			case i < len(b.ArgTypes) && needsCallSiteCast(b.ArgTypes[i]):
				// Casts the SSA value to the callee's declared Go type at
				// the FFI boundary. Identity casts (int64(int64)) are
				// no-ops; cross-width casts (int(int64)) are how the
				// resolver-driven binding bridges Mochi's i64 surface to
				// Go's machine-int APIs.
				fmt.Fprintf(w, "%s(%s)", b.ArgTypes[i], valueName(aid))
			default:
				w.WriteString(valueName(aid))
			}
		}
		if b.Result != "" && (b.SealHandles || castBack) {
			w.WriteString("))\n")
		} else {
			w.WriteString(")\n")
		}
	case ir.OpPhi:
		// Declared in prelude; no body emit.
		return nil
	default:
		return fmt.Errorf("unsupported op: %s", v.Op)
	}
	return nil
}

// emitTerminator lowers the block exit, including any phi-back-edge
// assignments to predecessor sites.
func emitTerminator(w *bytes.Buffer, fn *ir.Function, blk *ir.Block, all []*ir.Function, imports map[string]bool) error {
	// Phi back-edge writes: walk every phi in every successor and emit
	// "<phi_name> = <our_source>" before the jump.
	emitPhiAssignments := func(succID uint32) {
		succ := fn.Block(succID)
		for _, vid := range succ.Values {
			v := fn.Values[vid]
			if v.Op != ir.OpPhi {
				continue
			}
			// Phi.Args layout: [predBlockID, srcValueID, predBlockID, srcValueID, ...]
			for i := 0; i < len(v.Args); i += 2 {
				if v.Args[i] == blk.ID {
					fmt.Fprintf(w, "\t%s = %s\n", valueName(v.ID), valueName(v.Args[i+1]))
				}
			}
		}
	}
	switch blk.Term.Kind {
	case ir.TermJump:
		emitPhiAssignments(blk.Term.Target)
		// If the jump target is the very next block in RPO, fall through.
		// Phase 4 does not yet detect RPO neighbours; emit goto always.
		fmt.Fprintf(w, "\tgoto L%d\n", blk.Term.Target)
	case ir.TermBranch:
		// Emit phi writes for both targets; only one fires at runtime.
		fmt.Fprintf(w, "\tif %s {\n", valueName(blk.Term.Value))
		emitPhiAssignments(blk.Term.IfTrue)
		fmt.Fprintf(w, "\t\tgoto L%d\n\t}\n", blk.Term.IfTrue)
		emitPhiAssignments(blk.Term.IfFalse)
		fmt.Fprintf(w, "\tgoto L%d\n", blk.Term.IfFalse)
	case ir.TermReturn:
		if fn.Result == ir.TypeUnit || fn.Result == ir.TypeInvalid {
			w.WriteString("\treturn\n")
		} else {
			fmt.Fprintf(w, "\treturn %s\n", valueName(blk.Term.Value))
		}
	default:
		return fmt.Errorf("unsupported terminator %d", blk.Term.Kind)
	}
	return nil
}

func valueName(id uint32) string { return fmt.Sprintf("v%d", id) }

// defaultAlias returns the last path segment of a Go import path,
// matching the implicit package alias `go build` would assign. The
// emitter uses this when a GoBinding leaves Alias blank.
func defaultAlias(pkg string) string {
	last := pkg
	for i := len(pkg) - 1; i >= 0; i-- {
		if pkg[i] == '/' {
			last = pkg[i+1:]
			break
		}
	}
	return last
}

// needsCallSiteCast reports whether arg type t should be wrapped in a
// type conversion at the FFI call site. The cast is harmless for the
// numeric and string scalar types (identity casts compile away in Go),
// and necessary for Mochi-i64 to Go-int bridging. Interface or named
// types are passed through untouched: they typically arrive at the
// boundary already in the right shape, and a value-typed cast on an
// interface receiver would not compile.
func needsCallSiteCast(t string) bool {
	switch t {
	case "":
		return false
	case "any", "interface{}", "error":
		return false
	}
	if strings.ContainsAny(t, ".*[]") {
		return false
	}
	return true
}

// fnName returns the Go function name referenced by an OpFnRef value.
// The argument is the SSA value ID of an OpFnRef; the helper looks
// through the value table, asserts the op, and indexes the program's
// function table by the embedded Const. Used by query op emission to
// inline closure references as Go function values.
func fnName(fn *ir.Function, all []*ir.Function, vid uint32) string {
	v := fn.Values[vid]
	if v.Op != ir.OpFnRef {
		return fmt.Sprintf("/* not an OpFnRef: v%d */", vid)
	}
	if int(v.Const) >= len(all) {
		return fmt.Sprintf("/* fnref out of range: %d */", v.Const)
	}
	return all[v.Const].Name
}

// goTypeForValue returns the Go type for an SSA value's variable
// declaration. For most ops this is just goType(v.Type), but a few
// ops (notably OpQueryGroupBy) produce values whose static Go type
// can't be derived from ir.Type alone.
func goTypeForValue(v ir.Value) string {
	if v.Op == ir.OpQueryGroupBy {
		// runtime/mochi/query.GroupBy returns []Group[K, T]; for the
		// i64-everywhere Phase 5 subset that's []query.Group[int64, int64].
		return "[]query.Group[int64, int64]"
	}
	return goType(v.Type)
}

func goType(t ir.Type) string {
	switch t {
	case ir.TypeI64:
		return "int64"
	case ir.TypeF64:
		return "float64"
	case ir.TypeBool:
		return "bool"
	case ir.TypeStr:
		return "string"
	case ir.TypeList:
		return "[]int64"
	case ir.TypeMap:
		return "map[int64]int64"
	case ir.TypeListAny:
		return "_MochiAny"
	case ir.TypeF64Arr:
		return "[]float64"
	case ir.TypeI64Arr:
		return "[]int64"
	case ir.TypeU8Arr:
		return "[]byte"
	case ir.TypeUnit, ir.TypeInvalid:
		return ""
	default:
		return "interface{}"
	}
}

