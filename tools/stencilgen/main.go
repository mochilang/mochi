package main

import (
	"fmt"
	"os"
)

// main is the entry point for the build-time stencil generator. It is
// a Phase 1 skeleton: usage and flag surface are wired up so go
// generate scripts can reference it; the actual Clang invocation and
// ELF extraction land in Phase 1.1 with the BG parity gate.
//
// Usage:
//
//	stencilgen -out compiler3/emit/copypatch/stencils_amd64_generated.go \
//	           -clang=/usr/bin/clang \
//	           -target=x86_64-linux-gnu \
//	           stencils/*.c
//
// Flags:
//
//	-out      Path to the generated Go file (one per target ISA).
//	-clang    Path to the Clang binary; defaults to ${CLANG} or "clang".
//	-target   LLVM triple (x86_64-linux-gnu, aarch64-linux-gnu, ...).
//	-version  Print the pinned Clang version from CLANG_VERSION and exit.
//
// The Phase 1.1 pipeline:
//
//  1. Parse each input .c file's filename to derive the IR opcode
//     (op_add_i64.c -> ir.OpAddI64). The convention is one C function
//     named mochi_op_<opcode> per file.
//  2. Invoke clang with the canonical flag set; write the resulting
//     .o into a temporary directory.
//  3. Open the .o via debug/elf; find the single function symbol;
//     extract its byte range from the .text section.
//  4. Walk .rela.text relocations whose offset falls inside the
//     function's byte range; map each to copypatch.RelocKind via the
//     elfRelocMap table in doc.go.
//  5. Emit one StencilLiteral entry per opcode into the output file
//     using a text/template with a "Code generated by stencilgen; DO
//     NOT EDIT." header.
func main() {
	if len(os.Args) >= 2 && os.Args[1] == "-version" {
		v, err := os.ReadFile("tools/stencilgen/CLANG_VERSION")
		if err != nil {
			fmt.Fprintf(os.Stderr, "stencilgen: cannot read CLANG_VERSION: %v\n", err)
			os.Exit(1)
		}
		fmt.Print(string(v))
		return
	}
	fmt.Fprintln(os.Stderr, "stencilgen: phase 1.1 skeleton; full pipeline lands with the BG parity gate")
	fmt.Fprintln(os.Stderr, "stencilgen: see tools/stencilgen/doc.go for the design")
	os.Exit(2)
}
