// Package main implements the MEP-42 Phase 1.1 build-time stencil
// generator for the copy-and-patch JIT (compiler3/emit/copypatch).
//
// # Strategy
//
// stencilgen compiles one C source file per Mochi IR opcode under
// stencils/. Each .c file declares a single function whose signature
// matches the copypatch stencil ABI (R12=Frame, R13=arena base table,
// R14=per-VM context, RAX/RDI/RSI/RDX/RCX/R8/R9 as operand registers).
// stencilgen invokes Clang with the canonical flag set:
//
//	clang -O2 -fno-asynchronous-unwind-tables -fno-stack-protector
//	      -mno-red-zone -fpic -fno-pie -c stencils/op_xxx.c -o /tmp/...
//
// then reads the resulting object file via Go's debug/elf, extracts
// the function body bytes from the .text section, and extracts the
// relocation table from .rela.text. Each extracted relocation is
// mapped to a copypatch.RelocKind via a small per-ELF-reloc-type
// table:
//
//	R_X86_64_64       -> copypatch.RelocAbs64
//	R_X86_64_32       -> copypatch.RelocImm32
//	R_X86_64_32S      -> copypatch.RelocImm32
//	R_X86_64_PC32     -> copypatch.RelocPCRel32
//	R_X86_64_PLT32    -> copypatch.RelocPCRel32
//
// Unknown relocation kinds are an error; stencilgen refuses to emit
// a partial table because the runtime patcher would silently mishandle
// the unknown shape.
//
// The output of stencilgen is a single generated Go file
// stencils_amd64_generated.go (one per target ISA) under the
// copypatch package. The file declares a map[ir.OpCode]Stencil with
// one entry per source .c file. The file carries a "Code generated by
// stencilgen; DO NOT EDIT." header so go generate plays nicely.
//
// # Phase 1.1 status
//
// This package ships as a SKELETON in MEP-42 Phase 1: the C source
// fragments under stencils/ exist as documented templates, the
// CLANG_VERSION file pins the build-time toolchain, and main.go
// describes the extraction pipeline. The actual Clang invocation and
// ELF parsing land in Phase 1.1 when the BG kernel parity gate
// materializes. Until then the runtime path uses the hand-written
// placeholder table in compiler3/emit/copypatch/stencils_amd64.go.
//
// # Reading order
//
//  1. doc.go (this file): package overview.
//  2. main.go: the Clang-driver + ELF-extraction pipeline (skeleton).
//  3. CLANG_VERSION: pinned Clang version.
//  4. stencils/*.c: per-opcode C source.
//  5. stencils_README.md: per-opcode C source authoring guide.
//
// # Why pin a Clang version
//
// Stencil output depends on Clang's code generator. A Clang upgrade
// can change calling-convention details, register-allocator decisions,
// or emitted relocation kinds. Pinning ensures every Mochi build
// produces byte-identical stencils, which keeps the cross-mode
// parity gate (MEP-42 Phase 1.6) reproducible on every host. The
// CI workflow re-runs stencilgen on every PR that bumps the pinned
// version and diffs the output against the checked-in tables.
//
